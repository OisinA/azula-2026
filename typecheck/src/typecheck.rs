use std::{
    collections::{HashMap, HashSet},
    ops::Deref,
    rc::Rc,
};

use azula_ast::prelude::*;
use azula_error::prelude::*;
use azula_type::prelude::AzulaType;

use crate::generics::{subst_stmt, subst_type, unify, Substitution};

pub struct Typechecker<'a> {
    ast: Statement<'a>,

    functions: HashMap<&'a str, FunctionDefinition<'a>>,
    globals: HashMap<String, VariableDefinition<'a>>,
    structs: HashMap<String, StructDefinition<'a>>,
    namespaces: HashMap<String, Namespace<'a>>,
    enums: HashMap<String, Vec<String>>,
    /// Payload types of each variant, for enums declared with any payload ("boxed" enums)
    enum_payloads: HashMap<String, Vec<Vec<AzulaType<'a>>>>,
    type_aliases: HashMap<String, AzulaType<'a>>,

    // Generic definitions, keyed by name, with their type parameters
    generic_structs: HashMap<String, (Vec<String>, Vec<(AzulaType<'a>, &'a str)>)>,
    generic_enums: HashMap<String, (Vec<String>, Vec<&'a str>, Vec<Vec<AzulaType<'a>>>)>,
    generic_impls: HashMap<String, Vec<(Vec<String>, Statement<'a>)>>,
    generic_funcs: HashMap<String, (Vec<String>, Statement<'a>)>,
    /// Instantiated generic types: instance name (`Vec<int>`) -> (generic, arguments)
    instances: HashMap<String, (String, Vec<AzulaType<'a>>)>,
    /// Instantiated generic functions and methods (by mangled name)
    instantiated_functions: HashSet<String>,
    /// Instantiated functions still to be typechecked, with the type they are a method of
    pending: Vec<(Option<AzulaType<'a>>, Statement<'a>)>,
    /// Definitions generated by instantiation, appended to the program
    output: Vec<Statement<'a>>,

    /// The type the expression currently being checked should have, when known
    /// (used to infer generic arguments, e.g. `var v: Vec<int> = Vec::new()`)
    expected: Option<AzulaType<'a>>,
    current_return: AzulaType<'a>,

    pub errors: Vec<AzulaError>,
}

#[derive(Clone, Debug)]
struct FunctionDefinition<'a> {
    name: String,
    args: Vec<(AzulaType<'a>, String)>,
    varargs: bool,
    returns: AzulaType<'a>,
}

struct StructDefinition<'a> {
    name: &'a str,
    attrs: Vec<(AzulaType<'a>, &'a str)>,
}

#[derive(Debug, Clone)]
pub struct VariableDefinition<'a> {
    name: String,
    mutable: bool,
    typ: AzulaType<'a>,
}

#[derive(Debug, Clone)]
pub struct Namespace<'a> {
    name: String,
    funcs: HashMap<&'a str, FunctionDefinition<'a>>,
}

#[derive(Clone)]
pub struct Environment<'a> {
    variable_definitions: HashMap<String, VariableDefinition<'a>>,
}

impl<'a> Environment<'a> {
    pub fn new() -> Self {
        Self {
            variable_definitions: HashMap::new(),
        }
    }

    pub fn add_variable(&mut self, name: String, def: VariableDefinition<'a>) {
        self.variable_definitions.insert(name, def);
    }
}

fn leak<'a>(s: String) -> &'a str {
    Box::leak(s.into_boxed_str())
}

fn dummy_span() -> Span {
    Span { start: 0, end: 0 }
}

impl<'a> Typechecker<'a> {
    pub fn new(root: Statement<'a>) -> Self {
        Typechecker {
            ast: root,
            functions: HashMap::new(),
            globals: HashMap::new(),
            structs: HashMap::new(),
            namespaces: HashMap::new(),
            enums: HashMap::new(),
            enum_payloads: HashMap::new(),
            type_aliases: HashMap::new(),
            generic_structs: HashMap::new(),
            generic_enums: HashMap::new(),
            generic_impls: HashMap::new(),
            generic_funcs: HashMap::new(),
            instances: HashMap::new(),
            instantiated_functions: HashSet::new(),
            pending: vec![],
            output: vec![],
            expected: None,
            current_return: AzulaType::Void,
            errors: vec![],
        }
    }

    pub fn typecheck(&mut self) -> Result<Statement<'a>, String> {
        let stmts = match self.ast.clone() {
            Statement::Root(stmts) => stmts,
            _ => return Err("Not a root node".to_string()),
        };

        // Pass 0: collect names of everything declared, so declaration order doesn't matter
        for stmt in &stmts {
            match stmt {
                Statement::Generic(params, inner) => self.register_generic(params, inner),
                Statement::TypeAlias { name, typ, .. } => {
                    self.type_aliases.insert(name.to_string(), typ.clone());
                }
                Statement::Enum { name, variants, .. } => {
                    self.enums.insert(name.to_string(), variants.iter().map(|v| v.to_string()).collect());
                }
                Statement::Struct { name, attributes, .. } => {
                    self.structs.insert(name.to_string(), StructDefinition { name, attrs: attributes.clone() });
                }
                _ => {}
            }
        }

        // Pass 1: resolve the types used in declarations and register signatures
        let mut root = vec![];
        for stmt in stmts {
            match stmt {
                Statement::Generic(..) => {}
                Statement::Struct { name, attributes, span } => {
                    let attributes: Vec<_> = attributes.into_iter().map(|(t, n)| (self.resolve_type(t), n)).collect();
                    self.structs.insert(name.to_string(), StructDefinition { name, attrs: attributes.clone() });
                    root.push(Statement::Struct { name, attributes, span });
                }
                Statement::Enum { name, variants, payloads, span } => {
                    let payloads: Vec<Vec<_>> = payloads
                        .into_iter()
                        .map(|p| p.into_iter().map(|t| self.resolve_type(t)).collect())
                        .collect();
                    if payloads.iter().any(|p| !p.is_empty()) {
                        self.enum_payloads.insert(name.to_string(), payloads.clone());
                    }
                    root.push(Statement::Enum { name, variants, payloads, span });
                }
                Statement::Function { name, ref args, ref returns, .. } => {
                    let def = self.signature(name, args, returns);
                    self.functions.insert(name, def);
                    root.push(stmt);
                }
                Statement::ExternFunction { name, varargs, args, returns, span } => {
                    let args: Vec<_> = args.into_iter().map(|t| self.resolve_type(t)).collect();
                    let returns = self.resolve_type(returns);
                    self.functions.insert(
                        name,
                        FunctionDefinition {
                            name: name.to_string(),
                            varargs,
                            args: args.iter().map(|t| (t.clone(), "_".to_string())).collect(),
                            returns: returns.clone(),
                        },
                    );
                    root.push(Statement::ExternFunction { name, varargs, args, returns, span });
                }
                Statement::Impl { ref struct_impl, ref funcs, .. } => {
                    let struct_name = self.resolve_type(struct_impl.clone()).to_string();
                    let mut namespace = self.namespaces.remove(&struct_name).unwrap_or(Namespace {
                        name: struct_name.clone(),
                        funcs: HashMap::new(),
                    });
                    for func in funcs {
                        if let Statement::Function { name, args, returns, .. } = func {
                            let def = self.signature(name, args, returns);
                            namespace.funcs.insert(name, def);
                        }
                    }
                    self.namespaces.insert(struct_name, namespace);
                    root.push(stmt);
                }
                Statement::Assign(..) => match self.typecheck_global_assign(stmt) {
                    Ok(stmt) => root.push(stmt),
                    Err(_) => {}
                },
                other => root.push(other),
            }
        }

        // Pass 2: check function bodies
        let mut failed = false;
        for stmt in root.iter_mut() {
            match stmt.clone() {
                Statement::Function { .. } => match self.typecheck_function(stmt.clone()) {
                    Ok(checked) => *stmt = checked,
                    Err(_) => failed = true,
                },
                Statement::Impl { struct_impl, trait_impl, funcs, span } => {
                    let mut checked_funcs = vec![];
                    for func in funcs {
                        match self.typecheck_function(func) {
                            Ok(checked) => checked_funcs.push(checked),
                            Err(_) => failed = true,
                        }
                    }
                    *stmt = Statement::Impl {
                        struct_impl: self.resolve_type(struct_impl),
                        trait_impl,
                        funcs: checked_funcs,
                        span,
                    };
                }
                _ => {}
            }
        }

        // Pass 3: check the generic instances that were requested along the way
        while let Some((impl_type, func)) = self.pending.pop() {
            match self.typecheck_function(func) {
                Ok(checked) => match impl_type {
                    Some(struct_impl) => self.output.push(Statement::Impl {
                        struct_impl,
                        trait_impl: None,
                        funcs: vec![checked],
                        span: dummy_span(),
                    }),
                    None => self.output.push(checked),
                },
                Err(_) => failed = true,
            }
        }

        root.extend(self.output.drain(..));

        if failed || !self.errors.is_empty() {
            return Err("typechecking failed".to_string());
        }
        Ok(Statement::Root(root))
    }

    fn register_generic(&mut self, params: &[&'a str], inner: &Statement<'a>) {
        let params: Vec<String> = params.iter().map(|p| p.to_string()).collect();
        match inner {
            Statement::Function { name, .. } => {
                self.generic_funcs.insert(name.to_string(), (params, inner.clone()));
            }
            Statement::Struct { name, attributes, .. } => {
                self.generic_structs.insert(name.to_string(), (params, attributes.clone()));
            }
            Statement::Enum { name, variants, payloads, .. } => {
                self.enums.insert(name.to_string(), variants.iter().map(|v| v.to_string()).collect());
                self.generic_enums
                    .insert(name.to_string(), (params, variants.clone(), payloads.clone()));
            }
            Statement::Impl { struct_impl, funcs, .. } => {
                if let AzulaType::Generic(name, args) = struct_impl {
                    let impl_params: Vec<String> = args.iter().map(|a| a.to_string()).collect();
                    let entry = self.generic_impls.entry(name.clone()).or_default();
                    for func in funcs {
                        entry.push((impl_params.clone(), func.clone()));
                    }
                }
            }
            _ => {}
        }
    }

    /// The signature of a function, with its types resolved.
    fn signature(&mut self, name: &str, args: &[TypedIdentifier<'a>], returns: &AzulaType<'a>) -> FunctionDefinition<'a> {
        FunctionDefinition {
            name: name.to_string(),
            varargs: false,
            args: args.iter().map(|(t, n)| (self.resolve_type(t.clone()), n.to_string())).collect(),
            returns: self.resolve_type(returns.clone()),
        }
    }

    fn error(&mut self, message: String, span: &Span) {
        self.errors.push(AzulaError::new(ErrorType::Custom(message), span.start, span.end));
    }

    /// Instantiate the generic type `name<args>` (if not done already), returning the instance type.
    fn instantiate_type(&mut self, name: &str, args: Vec<AzulaType<'a>>) -> AzulaType<'a> {
        let instance = AzulaType::Generic(name.to_string(), args.clone()).mangle();
        if self.instances.contains_key(&instance) {
            return AzulaType::Named(instance);
        }

        let params = if let Some((params, _)) = self.generic_structs.get(name) {
            params.clone()
        } else if let Some((params, _, _)) = self.generic_enums.get(name) {
            params.clone()
        } else {
            self.errors.push(AzulaError::new(ErrorType::UnknownStruct(name.to_string()), 0, 0));
            return AzulaType::Named(instance);
        };
        if params.len() != args.len() {
            self.errors.push(AzulaError::new(
                ErrorType::Custom(format!("{} expects {} type arguments, got {}", name, params.len(), args.len())),
                0,
                0,
            ));
            return AzulaType::Named(instance);
        }

        self.instances.insert(instance.clone(), (name.to_string(), args.clone()));
        let map: Substitution<'a> = params.iter().cloned().zip(args.iter().cloned()).collect();
        let instance_name = leak(instance.clone());

        if let Some((_, attrs)) = self.generic_structs.get(name).cloned() {
            let attributes: Vec<_> = attrs
                .iter()
                .map(|(t, n)| (self.resolve_type(subst_type(t, &map)), *n))
                .collect();
            self.structs.insert(
                instance.clone(),
                StructDefinition { name: instance_name, attrs: attributes.clone() },
            );
            self.output.push(Statement::Struct { name: instance_name, attributes, span: dummy_span() });
        } else if let Some((_, variants, payloads)) = self.generic_enums.get(name).cloned() {
            let payloads: Vec<Vec<_>> = payloads
                .iter()
                .map(|p| p.iter().map(|t| self.resolve_type(subst_type(t, &map))).collect())
                .collect();
            self.enums.insert(instance.clone(), variants.iter().map(|v| v.to_string()).collect());
            if payloads.iter().any(|p| !p.is_empty()) {
                self.enum_payloads.insert(instance.clone(), payloads.clone());
            }
            self.output.push(Statement::Enum { name: instance_name, variants, payloads, span: dummy_span() });
        }

        // Method signatures of the instance (bodies are instantiated when first called)
        let mut funcs = HashMap::new();
        for (impl_params, func) in self.generic_impls.get(name).cloned().unwrap_or_default() {
            if let Statement::Function { name: fname, args: fargs, returns, .. } = &func {
                let map: Substitution<'a> = impl_params.iter().cloned().zip(args.iter().cloned()).collect();
                let fargs: Vec<_> = fargs.iter().map(|(t, n)| (subst_type(t, &map), *n)).collect();
                let def = self.signature(fname, &fargs, &subst_type(returns, &map));
                funcs.insert(*fname, def);
            }
        }
        self.namespaces.insert(instance.clone(), Namespace { name: instance.clone(), funcs });

        AzulaType::Named(instance)
    }

    /// Make sure the body of method `method` of generic instance `instance` is generated.
    fn instantiate_method(&mut self, instance: &str, method: &str) {
        let key = format!("{}_{}", instance, method);
        if self.instantiated_functions.contains(&key) {
            return;
        }
        let (generic, args) = match self.instances.get(instance) {
            Some(x) => x.clone(),
            None => return,
        };
        for (impl_params, func) in self.generic_impls.get(&generic).cloned().unwrap_or_default() {
            if let Statement::Function { name, .. } = &func {
                if *name == method {
                    self.instantiated_functions.insert(key);
                    let map: Substitution<'a> = impl_params.iter().cloned().zip(args.iter().cloned()).collect();
                    self.pending.push((Some(AzulaType::Named(instance.to_string())), subst_stmt(&func, &map)));
                    return;
                }
            }
        }
    }

    /// Instantiate generic function `name` with `args`, returning the instance's name.
    fn instantiate_function(&mut self, name: &str, args: Vec<AzulaType<'a>>) -> String {
        let instance = AzulaType::Generic(name.to_string(), args.clone()).mangle();
        if self.instantiated_functions.contains(&instance) {
            return instance;
        }
        self.instantiated_functions.insert(instance.clone());
        let (params, func) = self.generic_funcs.get(name).cloned().unwrap();
        let map: Substitution<'a> = params.iter().cloned().zip(args.iter().cloned()).collect();
        if let Statement::Function { args: fargs, returns, body, span, .. } = subst_stmt(&func, &map) {
            let instance_name = leak(instance.clone());
            let def = self.signature(instance_name, &fargs, &returns);
            self.functions.insert(instance_name, def);
            self.pending.push((
                None,
                Statement::Function { name: instance_name, args: fargs, returns, body, span },
            ));
        }
        instance
    }

    /// Work out the arguments of generic `name` (with parameters `params`) from the
    /// expected type and from matching `patterns` against the `concrete` types.
    fn infer_type_args(
        &mut self,
        name: &str,
        params: &[String],
        expected: &Option<AzulaType<'a>>,
        patterns: &[AzulaType<'a>],
        concrete: &[AzulaType<'a>],
        span: &Span,
    ) -> Option<Vec<AzulaType<'a>>> {
        let mut bindings = Substitution::new();
        if let Some(AzulaType::Named(expected)) = expected {
            if let Some((generic, args)) = self.instances.get(expected) {
                if generic == name {
                    return Some(args.clone());
                }
            }
        }
        for (pattern, concrete) in patterns.iter().zip(concrete) {
            unify(pattern, concrete, params, &self.instances, &mut bindings);
        }
        let mut args = vec![];
        for param in params {
            match bindings.get(param) {
                Some(t) => args.push(t.clone()),
                None => {
                    self.error(
                        format!("Cannot infer type parameter {} of {}; add type arguments like {}::<...>", param, name, name),
                        span,
                    );
                    return None;
                }
            }
        }
        Some(args)
    }

    /// Pair up parameter `patterns` with the types of the `args` that can be
    /// typechecked on their own. Arguments that need more context (such as
    /// `Option::None`) are skipped and their errors discarded; they are checked
    /// properly once the type arguments are known.
    fn types_for_inference(
        &mut self,
        patterns: &[AzulaType<'a>],
        args: &[ExpressionNode<'a>],
        env: &Environment<'a>,
    ) -> (Vec<AzulaType<'a>>, Vec<AzulaType<'a>>) {
        let mut known_patterns = vec![];
        let mut concrete = vec![];
        for (pattern, arg) in patterns.iter().zip(args) {
            let error_count = self.errors.len();
            match self.typecheck_expression(arg.clone(), env) {
                Ok((_, typ)) => {
                    known_patterns.push(pattern.clone());
                    concrete.push(typ);
                }
                Err(_) => self.errors.truncate(error_count),
            }
        }
        (known_patterns, concrete)
    }

    /// Typecheck `expr`, telling it the type it is expected to have.
    fn typecheck_expecting(
        &mut self,
        expr: ExpressionNode<'a>,
        env: &Environment<'a>,
        expected: &AzulaType<'a>,
    ) -> Result<(ExpressionNode<'a>, AzulaType<'a>), String> {
        self.expected = Some(expected.clone());
        let result = self.typecheck_expression(expr, env);
        self.expected = None;
        result
    }

    pub fn typecheck_statement(
        &mut self,
        stmt: Statement<'a>,
        env: &mut Environment<'a>,
    ) -> Result<(Statement<'a>, AzulaType<'a>), String> {
        match stmt {
            Statement::Assign(..) => self.typecheck_assign(stmt, env),
            Statement::Return(..) => self.typecheck_return(stmt, env),
            Statement::ExpressionStatement(expr, span) => {
                let result = match self.typecheck_expression(expr, env) {
                    Ok((expr, _)) => expr,
                    Err(e) => return Err(e),
                };
                Ok((
                    Statement::ExpressionStatement(result, span),
                    AzulaType::Void,
                ))
            }
            Statement::If(..) => self.typecheck_if(stmt, env),
            Statement::While(..) => self.typecheck_while(stmt, env),
            Statement::For(..) => self.typecheck_for(stmt, env),
            Statement::Break(span) => Ok((Statement::Break(span), AzulaType::Void)),
            Statement::Continue(span) => Ok((Statement::Continue(span), AzulaType::Void)),
            Statement::Reassign(..) => self.typecheck_reassign(stmt, env),
            Statement::Block(stmts) => {
                let mut checked = vec![];
                let env = &mut env.clone();
                for s in stmts {
                    match self.typecheck_statement(s, env) {
                        Ok((s, _)) => checked.push(s),
                        Err(e) => return Err(e),
                    }
                }
                Ok((Statement::Block(checked), AzulaType::Void))
            }
            _ => unreachable!("{:?}", stmt),
        }
    }

    fn typecheck_function(&mut self, stmt: Statement<'a>) -> Result<Statement<'a>, String> {
        if let Statement::Function {
            name,
            args,
            returns,
            body,
            span,
        } = stmt
        {
            let args: Vec<_> = args.into_iter().map(|(t, n)| (self.resolve_type(t), n)).collect();
            let returns = self.resolve_type(returns);
            self.current_return = returns.clone();

            let mut environment = Environment::new();
            for (typ, name) in &args {
                environment.add_variable(
                    name.to_string(),
                    VariableDefinition {
                        name: name.to_string(),
                        mutable: false,
                        typ: typ.clone(),
                    },
                )
            }
            let mut statements = vec![];
            let mut failed = false;
            if let Statement::Block(stmts) = body.deref().clone() {
                for stmt in stmts {
                    match self.typecheck_statement(stmt, &mut environment) {
                        Ok((stmt, _)) => statements.push(stmt),
                        // Keep going to report errors in later statements too
                        Err(_) => failed = true,
                    }
                }
            }
            if failed {
                return Err(format!("errors in function {}", name));
            }
            if returns != AzulaType::Void && !always_returns(&statements) {
                self.error(format!("Function {} might not return a value", name), &span);
                return Err("missing return".to_string());
            }

            return Ok(Statement::Function {
                name,
                args,
                returns,
                body: Rc::new(Statement::Block(statements)),
                span,
            });
        }

        unreachable!()
    }

    fn typecheck_global_assign(&mut self, expr: Statement<'a>) -> Result<Statement<'a>, String> {
        if let Statement::Assign(mutable, name, type_annotation, value, span) = expr {
            if mutable {
                self.errors.push(AzulaError::new(
                    ErrorType::NonGlobalConstant,
                    span.start,
                    span.end,
                ));
                return Err("Non constant at top-level".to_string());
            }

            // let (expr, typ) = match self.typecheck_expression(value, &Environment::new()) {
            //     Ok((expr, value)) => (expr, value),
            //     Err(e) => return Err(e),
            // };

            let typ = match value.expression.clone() {
                Expression::Integer(_) => AzulaType::Int,
                Expression::Float(_) => AzulaType::Float,
                Expression::Boolean(_) => AzulaType::Bool,
                Expression::String(_) => AzulaType::Str,
                Expression::Array(val) => {
                    AzulaType::Array(Rc::new(val[0].typed.clone()), Some(val.len()))
                }
                _ => {
                    self.errors.push(AzulaError::new(
                        ErrorType::NonGlobalConstant,
                        span.start,
                        span.end,
                    ));
                    return Err("Non constant at top-level".to_string());
                }
            };

            if type_annotation.is_some() {
                let type_annotation = self.resolve_type(type_annotation.clone().unwrap());

                if type_annotation != typ {
                    self.errors.push(AzulaError::new(
                        ErrorType::MismatchedAssignTypes(
                            format!("{:?}", type_annotation),
                            format!("{:?}", typ),
                        ),
                        span.start,
                        value.span.end,
                    ));
                    return Err("mismatched types in assign".to_string());
                }
            }

            self.globals.insert(
                name.clone(),
                VariableDefinition {
                    name: name.clone(),
                    mutable,
                    typ,
                },
            );

            Ok(Statement::Assign(
                mutable,
                name,
                type_annotation,
                value,
                span,
            ))
        } else {
            unreachable!()
        }
    }

    fn typecheck_assign(
        &mut self,
        expr: Statement<'a>,
        env: &mut Environment<'a>,
    ) -> Result<(Statement<'a>, AzulaType<'a>), String> {
        if let Statement::Assign(mutable, name, type_annotation, value, span) = expr {
            let type_annotation = type_annotation.map(|t| self.resolve_type(t));
            let (expr, typ) = match &type_annotation {
                Some(annotation) => self.typecheck_expecting(value, env, annotation)?,
                None => self.typecheck_expression(value, env)?,
            };

            if type_annotation.is_some() {
                let mut type_annotation = type_annotation.clone().unwrap();

                if let AzulaType::Array(arr_typ, size) = typ.clone() {
                    if let AzulaType::Array(inner_type, inner_size) = type_annotation.clone() {
                        if arr_typ != inner_type {
                            self.errors.push(AzulaError::new(
                                ErrorType::MismatchedAssignTypes(
                                    format!("{:?}", type_annotation),
                                    format!("{:?}", typ),
                                ),
                                span.start,
                                expr.span.end,
                            ));
                            return Err("mismatched types in assign".to_string());
                        }

                        if size.is_some() && inner_size.is_some() {
                            if size.unwrap() != inner_size.unwrap() {
                                self.errors.push(AzulaError::new(
                                    ErrorType::MismatchedAssignTypes(
                                        format!("{:?}", type_annotation),
                                        format!("{:?}", typ),
                                    ),
                                    span.start,
                                    expr.span.end,
                                ));
                                return Err("mismatched types in assign".to_string());
                            }
                        }

                        type_annotation = AzulaType::Array(arr_typ, size);
                    }
                }

                let types_compatible = assignable(&type_annotation, &typ, &expr);

                if !types_compatible {
                    self.errors.push(AzulaError::new(
                        ErrorType::MismatchedAssignTypes(
                            format!("{:?}", type_annotation),
                            format!("{:?}", typ),
                        ),
                        span.start,
                        expr.span.end,
                    ));
                    return Err("mismatched types in assign".to_string());
                }
            }

            let resolved_typ = if let Some(ann) = type_annotation.clone() { ann } else { typ };

            env.add_variable(
                name.clone(),
                VariableDefinition {
                    name: name.clone(),
                    mutable,
                    typ: resolved_typ.clone(),
                },
            );

            Ok((
                Statement::Assign(mutable, name, type_annotation, expr, span),
                AzulaType::Void,
            ))
        } else {
            unreachable!()
        }
    }

    fn typecheck_reassign(
        &mut self,
        expr: Statement<'a>,
        env: &mut Environment<'a>,
    ) -> Result<(Statement<'a>, AzulaType<'a>), String> {
        if let Statement::Reassign(var, val, span) = expr {

            let mut mutable = true;
            match var.expression {
                Expression::Identifier(ref v) => match env.variable_definitions.get(v) {
                    Some(var) => {
                        mutable = var.mutable;
                    }
                    _ => {
                        self.errors.push(AzulaError::new(
                            ErrorType::UnknownVariable(v.clone()),
                            var.span.start,
                            var.span.end,
                        ));
                        return Err(format!("unknown variable {:?}", var.expression));
                    }
                },
                Expression::ArrayAccess(..) => {}
                Expression::StructAccess(..) => {}
                _ => {
                    unreachable!("{:?}", var.expression)
                }
            }

            if !mutable {
                self.errors.push(AzulaError::new(
                    ErrorType::ConstantAssign,
                    var.span.start,
                    var.span.end,
                ));
                return Err("constant assign".to_string());
            }

            let (variable, var_type) = match self.typecheck_expression(var, env) {
                Ok((expr, value)) => (expr, value),
                Err(e) => return Err(e),
            };
            let (val, typ) = self.typecheck_expecting(val, env, &var_type)?;

            if !assignable(&var_type, &typ, &val) {
                self.errors.push(AzulaError::new(
                    ErrorType::MismatchedAssignTypes(
                        format!("{:?}", var_type),
                        format!("{:?}", typ),
                    ),
                    span.start,
                    val.span.end,
                ));
                return Err("mismatched types in assign".to_string());
            }

            Ok((Statement::Reassign(variable, val, span), AzulaType::Void))
        } else {
            unreachable!()
        }
    }

    fn typecheck_return(
        &mut self,
        stmt: Statement<'a>,
        env: &mut Environment<'a>,
    ) -> Result<(Statement<'a>, AzulaType<'a>), String> {
        if let Statement::Return(value, span) = stmt {
            let expected = self.current_return.clone();
            let value = match value {
                None => {
                    if expected != AzulaType::Void {
                        self.error(format!("Missing return value of type {}", expected.mangle()), &span);
                        return Err("missing return value".to_string());
                    }
                    return Ok((Statement::Return(None, span), AzulaType::Void));
                }
                Some(value) => value,
            };
            let (value, typ) = self.typecheck_expecting(value, env, &expected)?;
            if !assignable(&expected, &typ, &value) {
                self.errors.push(AzulaError::new(
                    ErrorType::IncorrectFunctionReturn(expected.mangle(), typ.mangle()),
                    value.span.start,
                    value.span.end,
                ));
                return Err("wrong return type".to_string());
            }
            Ok((Statement::Return(Some(value), span), typ))
        } else {
            unreachable!()
        }
    }

    fn typecheck_if(
        &mut self,
        stmt: Statement<'a>,
        env: &mut Environment<'a>,
    ) -> Result<(Statement<'a>, AzulaType<'a>), String> {
        if let Statement::If(ref expr, ref body, ref else_branch, ref span) = stmt {
            let (expr, typ) = match self.typecheck_expression(expr.clone(), env) {
                Ok((expr, value)) => (expr, value),
                Err(e) => return Err(e),
            };

            if typ != AzulaType::Bool {
                self.errors.push(AzulaError::new(
                    ErrorType::NonBoolCondition(format!("{:?}", typ)),
                    expr.span.start,
                    expr.span.end,
                ));
                return Err("Non boolean condition".to_string());
            }

            let mut stmts = vec![];
            let mut body_env = env.clone();
            for stmt in body {
                match self.typecheck_statement(stmt.clone(), &mut body_env) {
                    Ok((stmt, _)) => stmts.push(stmt),
                    Err(e) => return Err(e),
                };
            }

            let checked_else = match else_branch {
                Some(else_stmt) => {
                    match self.typecheck_statement(else_stmt.as_ref().clone(), &mut env.clone()) {
                        Ok((stmt, _)) => Some(Rc::new(stmt)),
                        Err(e) => return Err(e),
                    }
                }
                None => None,
            };

            Ok((Statement::If(expr, stmts, checked_else, span.clone()), AzulaType::Void))
        } else {
            unreachable!()
        }
    }

    fn typecheck_while(
        &mut self,
        stmt: Statement<'a>,
        env: &mut Environment<'a>,
    ) -> Result<(Statement<'a>, AzulaType<'a>), String> {
        if let Statement::While(ref expr, ref body, ref span) = stmt {
            let (expr, typ) = match self.typecheck_expression(expr.clone(), env) {
                Ok((expr, value)) => (expr, value),
                Err(e) => return Err(e),
            };

            if typ != AzulaType::Bool {
                self.errors.push(AzulaError::new(
                    ErrorType::NonBoolCondition(format!("{:?}", typ)),
                    expr.span.start,
                    expr.span.end,
                ));
                return Err("Non boolean condition".to_string());
            }

            let mut stmts = vec![];
            let mut body_env = env.clone();
            for stmt in body {
                match self.typecheck_statement(stmt.clone(), &mut body_env) {
                    Ok((stmt, _)) => stmts.push(stmt),
                    Err(e) => return Err(e),
                };
            }

            Ok((Statement::While(expr, stmts, span.clone()), AzulaType::Void))
        } else {
            unreachable!()
        }
    }

    fn typecheck_for(
        &mut self,
        stmt: Statement<'a>,
        env: &mut Environment<'a>,
    ) -> Result<(Statement<'a>, AzulaType<'a>), String> {
        if let Statement::For(ref cond, ref body, ref span) = stmt {
            let checked_cond = match cond {
                Some(expr) => {
                    let (checked, typ) = match self.typecheck_expression(expr.clone(), env) {
                        Ok(v) => v,
                        Err(e) => return Err(e),
                    };
                    if typ != AzulaType::Bool {
                        self.errors.push(AzulaError::new(
                            ErrorType::NonBoolCondition(format!("{:?}", typ)),
                            checked.span.start,
                            checked.span.end,
                        ));
                        return Err("Non boolean condition".to_string());
                    }
                    Some(checked)
                }
                None => None,
            };

            let mut stmts = vec![];
            let mut body_env = env.clone();
            for stmt in body {
                match self.typecheck_statement(stmt.clone(), &mut body_env) {
                    Ok((stmt, _)) => stmts.push(stmt),
                    Err(e) => return Err(e),
                };
            }

            Ok((Statement::For(checked_cond, stmts, span.clone()), AzulaType::Void))
        } else {
            unreachable!()
        }
    }

    fn typecheck_expression(
        &mut self,
        mut expr: ExpressionNode<'a>,
        env: &Environment<'a>,
    ) -> Result<(ExpressionNode<'a>, AzulaType<'a>), String> {
        // The expected type only applies to this node, not its sub-expressions
        let expected = self.expected.take();
        match expr.expression {
            Expression::Infix(..) => self.typecheck_infix_expression(expr, env),
            Expression::Integer(_) => {
                expr.typed = AzulaType::Int;
                Ok((expr.clone(), AzulaType::Int))
            }
            Expression::Float(_) => {
                expr.typed = AzulaType::Float;
                Ok((expr.clone(), AzulaType::Float))
            }
            Expression::Boolean(_) => {
                expr.typed = AzulaType::Bool;
                Ok((expr.clone(), AzulaType::Bool))
            }
            Expression::String(_) => {
                expr.typed = AzulaType::Str;
                Ok((expr.clone(), AzulaType::Str))
            }
            Expression::Identifier(ref name) => {
                if name == "nil" {
                    return Ok((expr.clone(), AzulaType::Void));
                }
                if let Some(variable) = env.variable_definitions.get(name) {
                    expr.typed = variable.typ.clone().into();

                    Ok((expr.clone(), variable.typ.clone()))
                } else if let Some(variable) = self.globals.get(name) {
                    expr.typed = variable.typ.clone().into();

                    Ok((expr.clone(), variable.typ.clone()))
                } else {
                    self.errors.push(AzulaError::new(
                        ErrorType::UnknownVariable(name.clone()),
                        expr.span.start,
                        expr.span.end,
                    ));
                    return Err(format!("Unknown variable {:?}", name));
                }
            }
            Expression::FunctionCall { function, args } => {
                self.typecheck_call(function.deref().clone(), args, expr.span, env, expected)
            }
            Expression::Turbofish(..) => {
                self.error("Type arguments must be followed by a call, `::` or `{`".to_string(), &expr.span);
                Err("stray turbofish".to_string())
            }
            Expression::Not(exp) => {
                let (node, typ) = match self.typecheck_expression(exp.deref().clone(), env) {
                    Ok((node, typ)) => (node, typ),
                    Err(e) => return Err(e),
                };

                if typ != AzulaType::Bool {
                    self.errors.push(AzulaError::new(
                        ErrorType::NonBoolCondition(format!("{:?}", typ)),
                        expr.span.start,
                        expr.span.end,
                    ));

                    return Err("Non-bool in condition".to_string());
                }

                return Ok((
                    ExpressionNode {
                        expression: Expression::Not(Rc::new(node)),
                        typed: typ,
                        span: expr.span,
                    },
                    AzulaType::Bool,
                ));
            }
            Expression::BitNot(exp) => {
                let (node, typ) = self.typecheck_expression(exp.deref().clone(), env)?;
                if !is_integer_type(&typ) {
                    self.errors.push(AzulaError::new(
                        ErrorType::NonOperatorType(format!("{:?}", typ), "~".to_string()),
                        expr.span.start,
                        expr.span.end,
                    ));
                    return Err("~ requires an integer".to_string());
                }
                Ok((
                    ExpressionNode {
                        expression: Expression::BitNot(Rc::new(node)),
                        typed: typ.clone(),
                        span: expr.span,
                    },
                    typ,
                ))
            }
            Expression::SizeOf(typ) => {
                let typ = self.resolve_type(typ);
                Ok((
                    ExpressionNode {
                        expression: Expression::SizeOf(typ),
                        typed: AzulaType::Int,
                        span: expr.span,
                    },
                    AzulaType::Int,
                ))
            }
            Expression::Negate(exp) => {
                let (node, typ) = match self.typecheck_expression(exp.deref().clone(), env) {
                    Ok((node, typ)) => (node, typ),
                    Err(e) => return Err(e),
                };

                if !is_integer_type(&typ) && !is_float_type(&typ) {
                    self.errors.push(AzulaError::new(
                        ErrorType::MismatchedTypes(format!("{:?}", typ), "Int or Float".to_string()),
                        expr.span.start,
                        expr.span.end,
                    ));
                    return Err("Negate requires numeric type".to_string());
                }

                return Ok((
                    ExpressionNode {
                        expression: Expression::Negate(Rc::new(node)),
                        typed: typ.clone(),
                        span: expr.span,
                    },
                    typ,
                ));
            }
            Expression::Pointer(exp) => {
                let (node, typ) = match self.typecheck_expression(exp.deref().clone(), env) {
                    Ok((node, typ)) => (node, typ),
                    Err(e) => return Err(e),
                };

                return Ok((
                    ExpressionNode {
                        expression: Expression::Pointer(Rc::new(node)),
                        typed: AzulaType::Pointer(Rc::new(typ.clone())),
                        span: expr.span,
                    },
                    AzulaType::Pointer(Rc::new(typ)),
                ));
            }
            Expression::Array(items) => {
                let typs = items
                    .iter()
                    .map(|v| self.typecheck_expression(v.clone(), env))
                    .collect::<Vec<_>>();

                if typs.is_empty() {
                    return Ok((
                        ExpressionNode {
                            expression: Expression::Array(vec![]),
                            typed: AzulaType::Array(Rc::new(AzulaType::Infer), Some(0)),
                            span: expr.span,
                        },
                        AzulaType::Array(Rc::new(AzulaType::Infer), Some(0)),
                    ));
                }

                let first_typ = &typs[0].as_ref().unwrap().1;

                for val in typs.clone() {
                    let (node, typ) = match val {
                        Ok((node, typ)) => (node, typ),
                        Err(_) => continue,
                    };
                    if typ != first_typ.clone() {
                        self.errors.push(AzulaError::new(
                            ErrorType::MismatchedTypes(
                                format!("{:?}", typ),
                                format!("{:?}", first_typ),
                            ),
                            node.span.start,
                            node.span.end,
                        ));
                    }
                }

                Ok((
                    ExpressionNode {
                        expression: Expression::Array(
                            typs.clone()
                                .iter()
                                .map(|s| s.as_ref().unwrap().clone())
                                .map(|(node, _)| node)
                                .collect(),
                        ),
                        typed: AzulaType::Array(Rc::new(first_typ.clone()), Some(typs.len())),
                        span: expr.span,
                    },
                    AzulaType::Array(Rc::new(first_typ.clone()), Some(typs.len())),
                ))
            }
            Expression::ArrayAccess(array, index) => {
                let (array, array_typ) = self
                    .typecheck_expression(array.deref().clone(), env)
                    .unwrap();

                let (index, typ) = self
                    .typecheck_expression(index.deref().clone(), env)
                    .unwrap();

                if typ != AzulaType::Int {
                    self.errors.push(AzulaError::new(
                        ErrorType::NonIntIndex(format!("{:?}", typ)),
                        array.span.start,
                        index.span.end,
                    ));

                    return Err("Non int index".to_string());
                }

                let return_typ = if array_typ.is_indexable() {
                    match array_typ {
                        AzulaType::Array(nested, _) => nested.deref().clone(),
                        AzulaType::Str => AzulaType::SizedSignedInt(8),
                        AzulaType::Pointer(nested) => nested.deref().clone(),
                        _ => unreachable!(),
                    }
                } else {
                    self.errors.push(AzulaError::new(
                        ErrorType::NonArrayInIndex(format!("{:?}", array_typ)),
                        array.span.start,
                        array.span.end,
                    ));
                    return Err("non-array in index".to_string());
                };

                return Ok((
                    ExpressionNode {
                        expression: Expression::ArrayAccess(Rc::new(array), Rc::new(index)),
                        typed: return_typ.clone(),
                        span: expr.span,
                    },
                    return_typ,
                ));
            }
            Expression::StructInitialisation(struc, attrs) => {
                self.typecheck_struct_init(struc.deref().clone(), attrs, expr.span, env, expected)
            }
            Expression::StructAccess(struc, access) => {
                let (struc, struc_type) =
                    match self.typecheck_expression(struc.deref().clone(), env) {
                        Ok(x) => x,
                        Err(e) => return Err(e),
                    };

                let struc_name = match struc_type {
                    AzulaType::Named(s) => s,
                    AzulaType::Pointer(nested) => match nested.deref().clone() {
                        AzulaType::Named(s) => s,
                        _ => {
                            self.errors.push(AzulaError::new(
                                ErrorType::AccessNonStruct,
                                struc.span.start,
                                struc.span.end,
                            ));
                            return Err("accessing non-struct".to_string());
                        }
                    },
                    _ => {
                        self.errors.push(AzulaError::new(
                            ErrorType::AccessNonStruct,
                            struc.span.start,
                            struc.span.end,
                        ));
                        return Err("accessing non-struct".to_string());
                    }
                };

                let struct_type = if let Some(struct_type) = self.structs.get(&struc_name) {
                    struct_type
                } else {
                    self.errors.push(AzulaError::new(
                        ErrorType::UnknownStruct(struc_name),
                        struc.span.start,
                        struc.span.end,
                    ));
                    return Err("Struct not found".to_string());
                };

                let member_name = match &access.expression {
                    Expression::Identifier(s) => s,
                    _ => {
                        self.errors.push(AzulaError::new(
                            ErrorType::AccessNonStruct,
                            access.span.start,
                            access.span.end,
                        ));
                        return Err("accessing non-struct".to_string());
                    }
                };

                let typ = match struct_type
                    .attrs
                    .iter()
                    .find(|(_, name)| name.to_string() == member_name.clone())
                {
                    Some((typ, _)) => typ,
                    _ => {
                        self.errors.push(AzulaError::new(
                            ErrorType::UnknownStructMember(member_name.clone(), struc_name),
                            access.span.start,
                            access.span.end,
                        ));
                        return Err("unknown struct member".to_string());
                    }
                };

                return Ok((
                    ExpressionNode {
                        expression: Expression::StructAccess(Rc::new(struc), access),
                        typed: typ.clone(),
                        span: expr.span,
                    },
                    typ.clone(),
                ));
            }
            Expression::NamespaceAccess(ns, identifier) => {
                let member = match &identifier.expression {
                    Expression::Identifier(m) => m.clone(),
                    _ => String::new(),
                };
                let ns = Rc::new(self.concretize_namespace(ns.deref().clone(), &member, None, env, &expected)?);
                let ns_name = if let Expression::Identifier(ref ident) = ns.deref().expression {
                    ident.clone()
                } else {
                    unreachable!()
                };

                // Check if it's an enum variant access
                if let Some(variants) = self.enums.get(&ns_name).cloned() {
                    let variant_name = match &identifier.expression {
                        Expression::Identifier(v) => v.clone(),
                        _ => unreachable!(),
                    };
                    if !variants.contains(&variant_name) {
                        self.errors.push(AzulaError::new(
                            ErrorType::UnknownVariant(variant_name.clone(), ns_name.clone()),
                            identifier.span.start,
                            identifier.span.end,
                        ));
                        return Err(format!("Unknown variant {} on {}", variant_name, ns_name));
                    }
                    if self.variant_payload(&ns_name, &variant_name).map(|p| !p.is_empty()).unwrap_or(false) {
                        self.errors.push(AzulaError::new(
                            ErrorType::Custom(format!("Variant {}::{} needs a payload", ns_name, variant_name)),
                            expr.span.start,
                            expr.span.end,
                        ));
                        return Err("variant without payload".to_string());
                    }
                    let typ = AzulaType::Named(ns_name.clone());
                    return Ok((
                        ExpressionNode {
                            expression: Expression::NamespaceAccess(ns, identifier),
                            typed: typ.clone(),
                            span: expr.span,
                        },
                        typ,
                    ));
                }

                let namespace = self.namespaces.get(&ns_name);
                let namespace = match namespace {
                    Some(f) => f.clone(),
                    None => return Err("namespace".to_string()),
                };

                let mut ns_node = ns.deref().clone();
                ns_node.typed = AzulaType::Named(namespace.name.clone());

                return Ok((
                    ExpressionNode {
                        expression: Expression::NamespaceAccess(Rc::new(ns_node), identifier),
                        typed: AzulaType::Infer,
                        span: expr.span,
                    },
                    AzulaType::Infer,
                ));
            }
            Expression::Match(scrutinee, arms) => {
                self.typecheck_match(scrutinee, arms, expr.span, env)
            }
            Expression::Cast(_, _) => self.typecheck_cast_expression(expr, env),
            Expression::Null => Ok((
                ExpressionNode { expression: Expression::Null, typed: AzulaType::Str, span: expr.span },
                AzulaType::Str,
            )),
            Expression::Alloc(inner) => {
                let (inner_node, inner_typ) = self.typecheck_expression(inner.as_ref().clone(), env)?;
                let ptr_type = AzulaType::Pointer(Rc::new(inner_typ));
                Ok((
                    ExpressionNode {
                        expression: Expression::Alloc(Rc::new(inner_node)),
                        typed: ptr_type.clone(),
                        span: expr.span,
                    },
                    ptr_type,
                ))
            }
            Expression::Block(stmts, final_expr) => {
                let mut new_env = env.clone();
                let mut new_stmts = vec![];
                for stmt in stmts {
                    match self.typecheck_statement(stmt, &mut new_env) {
                        Ok((s, _)) => new_stmts.push(s),
                        Err(e) => return Err(e),
                    }
                }
                match final_expr {
                    Some(fe) => {
                        let (fe_node, fe_type) =
                            self.typecheck_expression(fe.as_ref().clone(), &new_env)?;
                        Ok((
                            ExpressionNode {
                                expression: Expression::Block(new_stmts, Some(Rc::new(fe_node))),
                                typed: fe_type.clone(),
                                span: expr.span,
                            },
                            fe_type,
                        ))
                    }
                    None => Ok((
                        ExpressionNode {
                            expression: Expression::Block(new_stmts, None),
                            typed: AzulaType::Void,
                            span: expr.span,
                        },
                        AzulaType::Void,
                    )),
                }
            }
        }
    }

    fn typecheck_match(
        &mut self,
        scrutinee: Rc<ExpressionNode<'a>>,
        arms: Vec<(MatchPattern<'a>, ExpressionNode<'a>)>,
        span: Span,
        env: &Environment<'a>,
    ) -> Result<(ExpressionNode<'a>, AzulaType<'a>), String> {
        let (scrut_node, scrut_type) = match self.typecheck_expression(scrutinee.deref().clone(), env) {
            Ok(x) => x,
            Err(e) => return Err(e),
        };

        // Dispatch based on scrutinee type: enum match or integer match
        let is_integer_match = matches!(scrut_type, AzulaType::Int | AzulaType::SizedSignedInt(_) | AzulaType::SizedUnsignedInt(_));

        let (enum_name, variants) = if is_integer_match {
            (String::new(), vec![])
        } else {
            let name = match &scrut_type {
                AzulaType::Named(n) => n.clone(),
                _ => {
                    self.errors.push(AzulaError::new(
                        ErrorType::MatchOnNonEnum(format!("{:?}", scrut_type)),
                        scrut_node.span.start,
                        scrut_node.span.end,
                    ));
                    return Err("match on non-enum".to_string());
                }
            };
            let vars = match self.enums.get(&name).cloned() {
                Some(v) => v,
                None => {
                    self.errors.push(AzulaError::new(
                        ErrorType::UnknownEnum(name.clone()),
                        scrut_node.span.start,
                        scrut_node.span.end,
                    ));
                    return Err(format!("Unknown enum {}", name));
                }
            };
            (name, vars)
        };

        let mut covered: Vec<String> = vec![];
        let mut has_wildcard = false;
        let mut result_type: Option<AzulaType<'a>> = None;
        let mut new_arms = vec![];

        for (pattern, body) in arms {
            match &pattern {
                MatchPattern::Wildcard => {
                    has_wildcard = true;
                }
                MatchPattern::Integer(_) => {
                    if !is_integer_match {
                        self.errors.push(AzulaError::new(
                            ErrorType::MatchOnNonEnum(format!("{:?}", scrut_type)),
                            body.span.start,
                            body.span.end,
                        ));
                        return Err("integer pattern on non-integer scrutinee".to_string());
                    }
                }
                MatchPattern::Variant(pat_enum, variant) | MatchPattern::Destructure(pat_enum, variant, _) => {
                    // `Option::Some(x)` matches a value of an instance such as `Option<int>`
                    let generic_of_instance = self.instances.get(&enum_name).map(|(g, _)| g.clone());
                    if *pat_enum != enum_name.as_str() && generic_of_instance.as_deref() != Some(*pat_enum) {
                        self.errors.push(AzulaError::new(
                            ErrorType::UnknownEnum(pat_enum.to_string()),
                            body.span.start,
                            body.span.end,
                        ));
                        return Err(format!("Unknown enum {}", pat_enum));
                    }
                    if !variants.contains(&variant.to_string()) {
                        self.errors.push(AzulaError::new(
                            ErrorType::UnknownVariant(variant.to_string(), enum_name.clone()),
                            body.span.start,
                            body.span.end,
                        ));
                        return Err(format!("Unknown variant {}", variant));
                    }
                    covered.push(variant.to_string());
                }
            }

            // Bind the payload fields of a destructured variant
            let mut arm_env = env.clone();
            if let MatchPattern::Destructure(_, variant, bindings) = &pattern {
                let payload = self.variant_payload(&enum_name, variant).unwrap_or_default();
                if payload.len() != bindings.len() {
                    self.errors.push(AzulaError::new(
                        ErrorType::Custom(format!(
                            "Variant {}::{} has {} fields, pattern binds {}",
                            enum_name,
                            variant,
                            payload.len(),
                            bindings.len()
                        )),
                        body.span.start,
                        body.span.end,
                    ));
                    return Err("wrong binding count".to_string());
                }
                for (binding, typ) in bindings.iter().zip(payload) {
                    if let Some(name) = binding {
                        arm_env.add_variable(
                            name.to_string(),
                            VariableDefinition {
                                name: name.to_string(),
                                mutable: false,
                                typ: self.resolve_type(typ),
                            },
                        );
                    }
                }
            }

            let (body_node, body_type) = self.typecheck_expression(body, &arm_env)?;

            // Arms that disagree on their type make the match a statement (Void)
            match result_type.clone() {
                Some(rt) if rt != body_type => result_type = Some(AzulaType::Void),
                Some(_) => {}
                None => result_type = Some(body_type),
            }

            let pattern = match pattern {
                MatchPattern::Variant(_, variant) => MatchPattern::Variant(leak(enum_name.clone()), variant),
                MatchPattern::Destructure(_, variant, bindings) => {
                    MatchPattern::Destructure(leak(enum_name.clone()), variant, bindings)
                }
                other => other,
            };
            new_arms.push((pattern, body_node));
        }

        // Exhaustiveness: enum match requires all variants covered or wildcard;
        // integer match just requires a wildcard (infinite domain).
        if !has_wildcard && !is_integer_match {
            let uncovered: Vec<_> = variants.iter().filter(|v| !covered.contains(v)).collect();
            if !uncovered.is_empty() {
                self.errors.push(AzulaError::new(
                    ErrorType::NonExhaustiveMatch(enum_name.clone()),
                    span.start,
                    span.end,
                ));
                return Err("non-exhaustive match".to_string());
            }
        }

        let typ = result_type.unwrap_or(AzulaType::Void);
        Ok((
            ExpressionNode {
                expression: Expression::Match(Rc::new(scrut_node), new_arms),
                typed: typ.clone(),
                span,
            },
            typ,
        ))
    }

    fn typecheck_call(
        &mut self,
        function: ExpressionNode<'a>,
        args: Vec<ExpressionNode<'a>>,
        span: Span,
        env: &Environment<'a>,
        expected: Option<AzulaType<'a>>,
    ) -> Result<(ExpressionNode<'a>, AzulaType<'a>), String> {
        let function = self.concretize_callee(function, &args, env, &expected)?;

        // Enum variant construction: `Enum::Variant(values...)`
        if let Some((enum_name, variant_name)) = self.as_variant(&function) {
            let payload = self.variant_payload(&enum_name, &variant_name).unwrap_or_default();
            if payload.len() != args.len() {
                self.error(
                    format!(
                        "Variant {}::{} takes {} values, got {}",
                        enum_name,
                        variant_name,
                        payload.len(),
                        args.len()
                    ),
                    &span,
                );
                return Err("wrong payload count".to_string());
            }
            let mut new_args = vec![];
            for (arg, expected) in args.into_iter().zip(payload.iter()) {
                let (arg, typ) = self.typecheck_expecting(arg, env, expected)?;
                if !assignable(expected, &typ, &arg) {
                    self.errors.push(AzulaError::new(
                        ErrorType::MismatchedTypes(format!("{:?}", expected), format!("{:?}", typ)),
                        arg.span.start,
                        arg.span.end,
                    ));
                    return Err("mismatched payload".to_string());
                }
                new_args.push(arg);
            }
            let typ = AzulaType::Named(enum_name);
            return Ok((
                ExpressionNode {
                    expression: Expression::FunctionCall { function: Rc::new(function), args: new_args },
                    typed: typ.clone(),
                    span,
                },
                typ,
            ));
        }

        let func = match self.resolve_function(self.functions.clone(), function.clone(), env) {
            Ok(f) => f,
            Err(e) => {
                self.errors.push(AzulaError::new(
                    ErrorType::FunctionNotFound(e),
                    function.span.start,
                    function.span.end,
                ));
                return Err(format!("Function not found {:?}", function));
            }
        };

        // Methods called as `value.method(...)` receive `value` as their first argument
        let is_method = matches!(function.expression, Expression::StructAccess(..));
        let function = self.typecheck_function_def(function, env);
        let params: Vec<AzulaType<'a>> = func
            .args
            .iter()
            .skip(if is_method { 1 } else { 0 })
            .map(|(t, _)| t.clone())
            .collect();

        if (!func.varargs && args.len() != params.len()) || args.len() < params.len() {
            self.error(
                format!("{} takes {} arguments, got {}", func.name, params.len(), args.len()),
                &span,
            );
            return Err("wrong argument count".to_string());
        }

        let mut new_args = vec![];
        for (i, arg) in args.into_iter().enumerate() {
            let (arg, typ) = match params.get(i) {
                Some(param) => {
                    let (arg, typ) = self.typecheck_expecting(arg, env, param)?;
                    if !assignable(param, &typ, &arg) {
                        self.errors.push(AzulaError::new(
                            ErrorType::MismatchedTypes(format!("{:?}", param), format!("{:?}", typ)),
                            arg.span.start,
                            arg.span.end,
                        ));
                        return Err("mismatched argument".to_string());
                    }
                    (arg, typ)
                }
                None => self.typecheck_expression(arg, env)?,
            };
            let _ = typ;
            new_args.push(arg);
        }

        let return_type = func.returns;
        Ok((
            ExpressionNode {
                expression: Expression::FunctionCall {
                    function: Rc::new(function),
                    args: new_args,
                },
                typed: return_type.clone(),
                span,
            },
            return_type,
        ))
    }

    /// Rewrite references to generic functions and types in a callee into the
    /// names of concrete instances, inferring type arguments where needed.
    fn concretize_callee(
        &mut self,
        function: ExpressionNode<'a>,
        args: &[ExpressionNode<'a>],
        env: &Environment<'a>,
        expected: &Option<AzulaType<'a>>,
    ) -> Result<ExpressionNode<'a>, String> {
        match function.expression.clone() {
            Expression::Identifier(name) if self.generic_funcs.contains_key(&name) => {
                let (params, def) = self.generic_funcs[&name].clone();
                let (mut patterns, returns) = match def {
                    Statement::Function { args, returns, .. } => {
                        (args.into_iter().map(|(t, _)| t).collect::<Vec<_>>(), returns)
                    }
                    _ => unreachable!(),
                };
                let (patterns_known, concrete) = self.types_for_inference(&patterns, args, env);
                let mut patterns = patterns_known;
                let mut concrete = concrete;
                if let Some(expected) = expected {
                    patterns.push(returns);
                    concrete.push(expected.clone());
                }
                let type_args = self
                    .infer_type_args(&name, &params, &None, &patterns, &concrete, &function.span)
                    .ok_or("cannot infer")?;
                let instance = self.instantiate_function(&name, type_args);
                Ok(ExpressionNode { expression: Expression::Identifier(instance), ..function })
            }
            Expression::Turbofish(name, type_args) if self.generic_funcs.contains_key(&name) => {
                let type_args = type_args.into_iter().map(|t| self.resolve_type(t)).collect();
                let instance = self.instantiate_function(&name, type_args);
                Ok(ExpressionNode { expression: Expression::Identifier(instance), ..function })
            }
            Expression::NamespaceAccess(ns, member) => {
                let member_name = match &member.expression {
                    Expression::Identifier(m) => m.clone(),
                    _ => return Ok(function),
                };
                let ns = self.concretize_namespace(ns.deref().clone(), &member_name, Some(args), env, expected)?;
                Ok(ExpressionNode {
                    expression: Expression::NamespaceAccess(Rc::new(ns), member),
                    ..function
                })
            }
            _ => Ok(function),
        }
    }

    /// Turn the namespace part of `Name::member` into a concrete type name when
    /// `Name` is generic, using explicit type arguments or inference.
    fn concretize_namespace(
        &mut self,
        ns: ExpressionNode<'a>,
        member: &str,
        args: Option<&[ExpressionNode<'a>]>,
        env: &Environment<'a>,
        expected: &Option<AzulaType<'a>>,
    ) -> Result<ExpressionNode<'a>, String> {
        let instance = match ns.expression.clone() {
            Expression::Turbofish(name, type_args) => {
                let type_args = type_args.into_iter().map(|t| self.resolve_type(t)).collect();
                self.resolve_type(AzulaType::Generic(name, type_args))
            }
            Expression::Identifier(name)
                if self.generic_structs.contains_key(&name) || self.generic_enums.contains_key(&name) =>
            {
                // What the member's parameters look like, to match against the arguments
                let mut params: Vec<String> = vec![];
                let mut patterns: Vec<AzulaType<'a>> = vec![];
                if let Some((enum_params, variants, payloads)) = self.generic_enums.get(&name).cloned() {
                    params = enum_params;
                    if let Some(index) = variants.iter().position(|v| *v == member) {
                        patterns = payloads[index].clone();
                    }
                } else {
                    params = self.generic_structs[&name].0.clone();
                    for (impl_params, func) in self.generic_impls.get(&name).cloned().unwrap_or_default() {
                        if let Statement::Function { name: fname, args: fargs, returns, .. } = func {
                            if fname == member {
                                // Rename the impl's parameters to the struct's
                                let map: Substitution<'a> = impl_params
                                    .iter()
                                    .cloned()
                                    .zip(params.iter().map(|p| AzulaType::Named(p.clone())))
                                    .collect();
                                patterns = fargs.iter().map(|(t, _)| subst_type(t, &map)).collect();
                                if let Some(expected) = expected {
                                    // matched against the expected type below
                                    let _ = (returns, expected);
                                }
                            }
                        }
                    }
                }
                let (patterns, concrete) = self.types_for_inference(&patterns, args.unwrap_or(&[]), env);
                let type_args = self
                    .infer_type_args(&name, &params, expected, &patterns, &concrete, &ns.span)
                    .ok_or("cannot infer")?;
                self.instantiate_type(&name, type_args)
            }
            _ => return Ok(ns),
        };
        Ok(ExpressionNode {
            expression: Expression::Identifier(instance.to_string()),
            typed: AzulaType::Infer,
            span: ns.span,
        })
    }

    fn typecheck_struct_init(
        &mut self,
        struc: ExpressionNode<'a>,
        fields: Vec<(&'a str, ExpressionNode<'a>)>,
        span: Span,
        env: &Environment<'a>,
        expected: Option<AzulaType<'a>>,
    ) -> Result<(ExpressionNode<'a>, AzulaType<'a>), String> {
        // Work out which (possibly generic) struct is being built
        let name = match struc.expression.clone() {
            Expression::Identifier(name) if self.generic_structs.contains_key(&name) => {
                let (params, attrs) = self.generic_structs[&name].clone();
                let mut patterns = vec![];
                let mut concrete = vec![];
                for (field, value) in &fields {
                    if let Some((typ, _)) = attrs.iter().find(|(_, n)| n == field) {
                        patterns.push(typ.clone());
                        concrete.push(self.typecheck_expression(value.clone(), env)?.1);
                    }
                }
                let args = self
                    .infer_type_args(&name, &params, &expected, &patterns, &concrete, &span)
                    .ok_or("cannot infer")?;
                self.instantiate_type(&name, args).to_string()
            }
            Expression::Turbofish(name, args) => {
                let args = args.into_iter().map(|t| self.resolve_type(t)).collect();
                self.instantiate_type(&name, args).to_string()
            }
            Expression::Identifier(name) => name,
            _ => unreachable!(),
        };

        let attrs = match self.structs.get(&name) {
            Some(def) => def.attrs.clone(),
            None => {
                self.errors.push(AzulaError::new(ErrorType::UnknownStruct(name), span.start, span.end));
                return Err("Struct not found".to_string());
            }
        };

        for (field, value) in &fields {
            if !attrs.iter().any(|(_, n)| n == field) {
                self.errors.push(AzulaError::new(
                    ErrorType::UnknownStructMember(field.to_string(), name.clone()),
                    value.span.start,
                    value.span.end,
                ));
                return Err("unknown struct member".to_string());
            }
        }

        // Check the fields, putting them in declaration order
        let mut checked = vec![];
        for (typ, attr) in &attrs {
            let value = match fields.iter().find(|(n, _)| n == attr) {
                Some((_, value)) => value.clone(),
                None => {
                    self.error(format!("Missing field {} in {}", attr, name), &span);
                    return Err("missing field".to_string());
                }
            };
            let (value, value_typ) = self.typecheck_expecting(value, env, typ)?;
            if !assignable(typ, &value_typ, &value) {
                self.errors.push(AzulaError::new(
                    ErrorType::MismatchedTypes(format!("{:?}", typ), format!("{:?}", value_typ)),
                    value.span.start,
                    value.span.end,
                ));
                return Err("mismatched field".to_string());
            }
            checked.push((*attr, value));
        }

        let typ = AzulaType::Named(name.clone());
        let struc = ExpressionNode {
            expression: Expression::Identifier(name),
            typed: typ.clone(),
            span: struc.span,
        };
        Ok((
            ExpressionNode {
                expression: Expression::StructInitialisation(Rc::new(struc), checked),
                typed: typ.clone(),
                span,
            },
            typ,
        ))
    }

    /// If `function` names an enum variant (`Enum::Variant`), return (enum, variant).
    fn as_variant(&self, function: &ExpressionNode<'a>) -> Option<(String, String)> {
        if let Expression::NamespaceAccess(ns, variant) = &function.expression {
            if let (Expression::Identifier(ns), Expression::Identifier(variant)) = (&ns.expression, &variant.expression) {
                if self.enums.contains_key(ns) {
                    return Some((ns.clone(), variant.clone()));
                }
            }
        }
        None
    }

    fn variant_payload(&self, enum_name: &str, variant: &str) -> Option<Vec<AzulaType<'a>>> {
        let index = self.enums.get(enum_name)?.iter().position(|v| v == variant)?;
        Some(
            self.enum_payloads
                .get(enum_name)
                .map(|p| p[index].clone())
                .unwrap_or_default(),
        )
    }

    /// Resolve type aliases and instantiate generic types used in `typ`.
    fn resolve_type(&mut self, typ: AzulaType<'a>) -> AzulaType<'a> {
        match typ {
            AzulaType::Named(ref n) => {
                if let Some(resolved) = self.type_aliases.get(n.as_str()).cloned() {
                    self.resolve_type(resolved)
                } else {
                    typ
                }
            }
            AzulaType::Pointer(inner) => AzulaType::Pointer(Rc::new(self.resolve_type(inner.as_ref().clone()))),
            AzulaType::Array(inner, size) => {
                AzulaType::Array(Rc::new(self.resolve_type(inner.as_ref().clone())), size)
            }
            AzulaType::Generic(name, args) => {
                let args = args.into_iter().map(|a| self.resolve_type(a)).collect();
                self.instantiate_type(&name, args)
            }
            _ => typ,
        }
    }

    fn typecheck_cast_expression(
        &mut self,
        expr: ExpressionNode<'a>,
        env: &Environment<'a>,
    ) -> Result<(ExpressionNode<'a>, AzulaType<'a>), String> {
        if let Expression::Cast(ref inner, ref target_type) = expr.expression {
            let (inner_node, _) = self.typecheck_expression(inner.deref().clone(), env)?;
            let typ = self.resolve_type(target_type.clone());
            return Ok((
                ExpressionNode {
                    expression: Expression::Cast(Rc::new(inner_node), typ.clone()),
                    typed: typ.clone(),
                    span: expr.span,
                },
                typ,
            ));
        }
        unreachable!()
    }

    fn typecheck_infix_expression(
        &mut self,
        expr: ExpressionNode<'a>,
        env: &Environment<'a>,
    ) -> Result<(ExpressionNode<'a>, AzulaType<'a>), String> {
        if let Expression::Infix(ref left, ref operator, ref right) = expr.expression {
            let (mut left, mut left_typ) = self.typecheck_expression(left.deref().clone(), env)?;
            let (mut right, mut right_typ) = self.typecheck_expression(right.deref().clone(), env)?;

            // Integer literals take on the integer type of the other operand.
            if is_integer_type(&left_typ) && is_integer_literal(&right) {
                right.typed = left_typ.clone();
                right_typ = left_typ.clone();
            } else if is_integer_type(&right_typ) && is_integer_literal(&left) {
                left.typed = right_typ.clone();
                left_typ = right_typ.clone();
            }

            // Only plain (payload-free) enums can be compared
            let is_enum = |t: &AzulaType<'a>| {
                matches!(t, AzulaType::Named(n) if self.enums.contains_key(n.as_str()) && !self.enum_payloads.contains_key(n.as_str()))
            };
            let is_pointer_like = |t: &AzulaType<'a>| matches!(t, AzulaType::Pointer(_) | AzulaType::Str);

            let operand_ok = |t: &AzulaType<'a>| -> bool {
                match operator {
                    Operator::Add | Operator::Sub | Operator::Mul | Operator::Div | Operator::Mod | Operator::Power => {
                        is_integer_type(t) || is_float_type(t)
                    }
                    Operator::BitAnd | Operator::BitOr | Operator::BitXor | Operator::Shl | Operator::Shr => {
                        is_integer_type(t)
                    }
                    Operator::Or | Operator::And => *t == AzulaType::Bool,
                    Operator::Eq | Operator::Neq => {
                        is_integer_type(t) || is_float_type(t) || *t == AzulaType::Bool || is_enum(t) || is_pointer_like(t)
                    }
                    Operator::Lt | Operator::Lte | Operator::Gt | Operator::Gte => {
                        is_integer_type(t) || is_float_type(t) || is_pointer_like(t)
                    }
                }
            };

            for (node, typ) in [(&left, &left_typ), (&right, &right_typ)] {
                if !operand_ok(typ) {
                    self.errors.push(AzulaError::new(
                        ErrorType::NonOperatorType(format!("{:?}", typ), format!("{:?}", operator)),
                        node.span.start,
                        node.span.end,
                    ));
                    return Err("cannot use operator with type".to_string());
                }
            }

            let result_typ = match operator {
                Operator::Or
                | Operator::And
                | Operator::Eq
                | Operator::Neq
                | Operator::Lt
                | Operator::Lte
                | Operator::Gt
                | Operator::Gte => {
                    let both_pointers = is_pointer_like(&left_typ) && is_pointer_like(&right_typ);
                    if left_typ != right_typ && !both_pointers {
                        self.errors.push(AzulaError::new(
                            ErrorType::MismatchedTypes(format!("{:?}", left_typ), format!("{:?}", right_typ)),
                            left.span.start,
                            right.span.end,
                        ));
                        return Err("mismatched types in infix".to_string());
                    }
                    AzulaType::Bool
                }
                _ => {
                    if left_typ != right_typ {
                        self.errors.push(AzulaError::new(
                            ErrorType::MismatchedTypes(format!("{:?}", left_typ), format!("{:?}", right_typ)),
                            left.span.start,
                            right.span.end,
                        ));
                        return Err("mismatched types in infix".to_string());
                    }
                    left_typ.clone()
                }
            };

            Ok((
                ExpressionNode {
                    expression: Expression::Infix(Rc::new(left), operator.clone(), Rc::new(right)),
                    typed: result_typ.clone(),
                    span: expr.span,
                },
                result_typ,
            ))
        } else {
            unreachable!()
        }
    }

    fn typecheck_function_def(
        &mut self,
        mut expr: ExpressionNode<'a>,
        env: &Environment<'a>,
    ) -> ExpressionNode<'a> {
        if let Expression::Identifier(..) = expr.expression {
            return expr.clone();
        }

        if let Expression::NamespaceAccess(ref ns, _) = expr.expression {
            let namespace = if let Expression::Identifier(ident) = ns.deref().clone().expression {
                ident
            } else {
                unreachable!()
            };

            expr.typed = AzulaType::Named(namespace);
            return expr.clone();
        }

        if let Expression::StructAccess(ref struc, ref right) = expr.expression {
            let (typechecked_struc, resolved_type) = self
                .typecheck_expression(struc.deref().clone(), env)
                .unwrap();

            return ExpressionNode {
                expression: Expression::StructAccess(
                    Rc::new(typechecked_struc),
                    right.clone(),
                ),
                typed: resolved_type.clone(),
                span: expr.span,
            };
        }

        expr
    }

    fn resolve_function(
        &mut self,
        namespace: HashMap<&'a str, FunctionDefinition<'a>>,
        expr: ExpressionNode<'a>,
        env: &Environment<'a>,
    ) -> Result<FunctionDefinition<'a>, String> {
        if let Expression::Identifier(s) = expr.expression {
            return match namespace.get(&s.as_str()) {
                Some(f) => Ok(f.clone()),
                None => {
                    if s == "printf" || s == "sprintf" || s == "puts" {
                        Ok(FunctionDefinition {
                            name: s,
                            args: vec![],
                            varargs: true,
                            returns: AzulaType::Void,
                        })
                    } else if s == "strlen" {
                        Ok(FunctionDefinition {
                            name: s,
                            args: vec![(AzulaType::Str, "s".to_string())],
                            varargs: false,
                            returns: AzulaType::Int,
                        })
                    } else if s == "strcmp" {
                        Ok(FunctionDefinition {
                            name: s,
                            args: vec![(AzulaType::Str, "a".to_string()), (AzulaType::Str, "b".to_string())],
                            varargs: false,
                            returns: AzulaType::Int,
                        })
                    } else if s == "malloc" {
                        Ok(FunctionDefinition {
                            name: s,
                            args: vec![(AzulaType::Int, "size".to_string())],
                            varargs: false,
                            returns: AzulaType::Str,
                        })
                    } else if s == "memcpy" {
                        Ok(FunctionDefinition {
                            name: s,
                            args: vec![
                                (AzulaType::Str, "dest".to_string()),
                                (AzulaType::Str, "src".to_string()),
                                (AzulaType::Int, "n".to_string()),
                            ],
                            varargs: false,
                            returns: AzulaType::Str,
                        })
                    } else if s == "free" {
                        Ok(FunctionDefinition {
                            name: s,
                            args: vec![(AzulaType::Str, "ptr".to_string())],
                            varargs: false,
                            returns: AzulaType::Void,
                        })
                    } else if s == "realloc" {
                        Ok(FunctionDefinition {
                            name: s,
                            args: vec![(AzulaType::Str, "ptr".to_string()), (AzulaType::Int, "size".to_string())],
                            varargs: false,
                            returns: AzulaType::Str,
                        })
                    } else if s == "ptr_read_int" {
                        Ok(FunctionDefinition {
                            name: s,
                            args: vec![(AzulaType::Str, "ptr".to_string())],
                            varargs: false,
                            returns: AzulaType::Int,
                        })
                    } else if s == "ptr_write_int" {
                        Ok(FunctionDefinition {
                            name: s,
                            args: vec![(AzulaType::Str, "ptr".to_string()), (AzulaType::Int, "val".to_string())],
                            varargs: false,
                            returns: AzulaType::Void,
                        })
                    } else if s == "ptr_read_str" {
                        Ok(FunctionDefinition {
                            name: s,
                            args: vec![(AzulaType::Str, "ptr".to_string())],
                            varargs: false,
                            returns: AzulaType::Str,
                        })
                    } else if s == "ptr_write_str" {
                        Ok(FunctionDefinition {
                            name: s,
                            args: vec![(AzulaType::Str, "ptr".to_string()), (AzulaType::Str, "val".to_string())],
                            varargs: false,
                            returns: AzulaType::Void,
                        })
                    } else if s == "ptr_add" {
                        Ok(FunctionDefinition {
                            name: s,
                            args: vec![(AzulaType::Str, "ptr".to_string()), (AzulaType::Int, "offset".to_string())],
                            varargs: false,
                            returns: AzulaType::Str,
                        })
                    } else if s == "fopen" {
                        Ok(FunctionDefinition {
                            name: s,
                            args: vec![(AzulaType::Str, "path".to_string()), (AzulaType::Str, "mode".to_string())],
                            varargs: false,
                            returns: AzulaType::Str,
                        })
                    } else if s == "fclose" {
                        Ok(FunctionDefinition {
                            name: s,
                            args: vec![(AzulaType::Str, "file".to_string())],
                            varargs: false,
                            returns: AzulaType::Int,
                        })
                    } else if s == "fseek" {
                        Ok(FunctionDefinition {
                            name: s,
                            args: vec![
                                (AzulaType::Str, "file".to_string()),
                                (AzulaType::Int, "offset".to_string()),
                                (AzulaType::Int, "whence".to_string()),
                            ],
                            varargs: false,
                            returns: AzulaType::Int,
                        })
                    } else if s == "ftell" {
                        Ok(FunctionDefinition {
                            name: s,
                            args: vec![(AzulaType::Str, "file".to_string())],
                            varargs: false,
                            returns: AzulaType::Int,
                        })
                    } else if s == "fread" {
                        Ok(FunctionDefinition {
                            name: s,
                            args: vec![
                                (AzulaType::Str, "buf".to_string()),
                                (AzulaType::Int, "size".to_string()),
                                (AzulaType::Int, "count".to_string()),
                                (AzulaType::Str, "file".to_string()),
                            ],
                            varargs: false,
                            returns: AzulaType::Int,
                        })
                    } else {
                        Err(s)
                    }
                }
            };
        }

        if let Expression::NamespaceAccess(ns, identifier) = expr.expression {
            let namespace = if let Expression::Identifier(ident) = ns.deref().clone().expression {
                let namespace = self.namespaces.get(&ident);
                match namespace {
                    Some(f) => Ok(f.clone()),
                    None => Err(ident),
                }
            } else {
                unreachable!()
            };

            if namespace.is_err() {
                return Err("namespace".to_string());
            }

            let namespace = namespace.unwrap();
            if let Expression::Identifier(method) = &identifier.expression {
                self.instantiate_method(&namespace.name, method);
            }

            return self.resolve_function(namespace.funcs.clone(), identifier.deref().clone(), env);
        }

        if let Expression::StructAccess(struc, method) = expr.expression {
            let (_, resolved_type) = self
                .typecheck_expression(struc.deref().clone(), env)
                .unwrap();

            let namespace = match self.namespaces.get(&resolved_type.to_string()) {
                Some(namespace) => namespace.clone(),
                None => return Err(format!("no methods on {}", resolved_type.mangle())),
            };
            if let Expression::Identifier(name) = &method.expression {
                self.instantiate_method(&namespace.name, name);
            }

            return self.resolve_function(namespace.funcs.clone(), method.deref().clone(), env);
        }

        Err("none".to_string())
    }
}

/// Whether executing `body` always ends in a `return` (or never finishes).
fn always_returns(body: &[Statement]) -> bool {
    match body.last() {
        Some(stmt) => statement_always_returns(stmt),
        None => false,
    }
}

fn statement_always_returns(stmt: &Statement) -> bool {
    match stmt {
        Statement::Return(..) => true,
        Statement::Block(body) => always_returns(body),
        Statement::If(_, body, Some(else_branch), _) => {
            always_returns(body) && statement_always_returns(else_branch)
        }
        // Infinite loops only finish through `break`
        Statement::For(None, body, _) => !contains_break(body),
        Statement::While(cond, body, _) if cond.expression == Expression::Boolean(true) => !contains_break(body),
        Statement::ExpressionStatement(expr, _) => match &expr.expression {
            Expression::Match(_, arms) => arms.iter().all(|(_, arm)| match &arm.expression {
                Expression::Block(stmts, None) => always_returns(stmts),
                _ => false,
            }),
            Expression::FunctionCall { function, .. } => matches!(
                &function.expression,
                Expression::Identifier(name) if name == "exit" || name == "abort"
            ),
            _ => false,
        },
        _ => false,
    }
}

/// Whether `body` contains a `break` that exits this loop (not a nested one).
fn contains_break(body: &[Statement]) -> bool {
    body.iter().any(|stmt| match stmt {
        Statement::Break(_) => true,
        Statement::If(_, body, else_branch, _) => {
            contains_break(body) || else_branch.as_ref().map(|e| contains_break(std::slice::from_ref(e.as_ref()))).unwrap_or(false)
        }
        Statement::Block(body) => contains_break(body),
        Statement::ExpressionStatement(expr, _) => match &expr.expression {
            Expression::Match(_, arms) => arms.iter().any(|(_, arm)| match &arm.expression {
                Expression::Block(stmts, _) => contains_break(stmts),
                _ => false,
            }),
            _ => false,
        },
        _ => false,
    })
}

fn is_integer_type(t: &AzulaType) -> bool {
    matches!(t, AzulaType::Int | AzulaType::SizedSignedInt(_) | AzulaType::SizedUnsignedInt(_))
}

fn is_float_type(t: &AzulaType) -> bool {
    matches!(t, AzulaType::Float | AzulaType::SizedFloat(_))
}

fn is_integer_literal(expr: &ExpressionNode) -> bool {
    match &expr.expression {
        Expression::Integer(_) => true,
        Expression::Negate(inner) => is_integer_literal(inner),
        _ => false,
    }
}

/// Whether a value of type `got` (produced by `expr`) can be stored in a slot of type `expected`.
fn assignable(expected: &AzulaType, got: &AzulaType, expr: &ExpressionNode) -> bool {
    if expected == got {
        return true;
    }
    if is_integer_type(expected) && is_integer_type(got) {
        // Literals fit any integer type; otherwise only int <-> sized conversions
        // that the old compiler allowed.
        return is_integer_literal(expr)
            || matches!(got, AzulaType::Int)
            || matches!(expected, AzulaType::Int);
    }
    let pointer_like = |t: &AzulaType| matches!(t, AzulaType::Pointer(_) | AzulaType::Str);
    pointer_like(expected) && pointer_like(got) && (matches!(got, AzulaType::Str) || matches!(expected, AzulaType::Str))
}


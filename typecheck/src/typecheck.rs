use std::{
    collections::{HashMap, HashSet},
    ops::Deref,
    rc::Rc,
};

use azula_ast::prelude::*;
use azula_error::prelude::*;
use azula_type::prelude::AzulaType;

use crate::closures::{captured_names, closure_free_names};
use crate::generics::{subst_stmt, subst_type, unify, Substitution, TUPLE};

pub struct Typechecker<'a> {
    ast: Statement<'a>,

    functions: HashMap<&'a str, FunctionDefinition<'a>>,
    globals: HashMap<String, VariableDefinition<'a>>,
    structs: HashMap<String, StructDefinition<'a>>,
    namespaces: HashMap<String, Namespace<'a>>,
    enums: HashMap<String, Vec<String>>,
    /// Payload types of each variant, for enums declared with any payload ("boxed" enums)
    enum_payloads: HashMap<String, Vec<Vec<AzulaType<'a>>>>,
    type_aliases: HashMap<String, AzulaType<'a>>,

    // Generic definitions, keyed by name, with their type parameters
    generic_structs: HashMap<String, (Vec<String>, Vec<(AzulaType<'a>, &'a str)>)>,
    generic_enums: HashMap<String, (Vec<String>, Vec<&'a str>, Vec<Vec<AzulaType<'a>>>)>,
    generic_impls: HashMap<String, Vec<(Vec<String>, Statement<'a>)>>,
    generic_funcs: HashMap<String, (Vec<String>, Statement<'a>)>,
    /// Generic methods, keyed by the (generic) type they belong to: the type's
    /// parameters (as named in the impl), the method's parameters, and the method
    generic_methods: HashMap<String, Vec<(Vec<String>, Vec<String>, Statement<'a>)>>,
    /// Bounds on the type parameters of generic functions and types
    generic_bounds: HashMap<String, Vec<(String, String)>>,
    /// Interfaces: their methods, and whether each has a default body
    interfaces: HashMap<String, (Vec<String>, Vec<(Statement<'a>, bool)>)>,
    /// The interfaces each type (or generic type) implements, with where that was declared
    conformances: HashMap<String, Vec<(String, Vec<AzulaType<'a>>, Span)>>,
    /// Instantiated generic types: instance name (`Vec<int>`) -> (generic, arguments)
    instances: HashMap<String, (String, Vec<AzulaType<'a>>)>,
    /// Instantiated generic functions and methods (by mangled name)
    instantiated_functions: HashSet<String>,
    /// Instantiated functions still to be typechecked, with the type they are a method of
    pending: Vec<(Option<AzulaType<'a>>, Statement<'a>)>,
    /// Definitions generated by instantiation, appended to the program
    output: Vec<Statement<'a>>,

    /// The type the expression currently being checked should have, when known
    /// (used to infer generic arguments, e.g. `var v: Vec<int> = Vec::new()`)
    expected: Option<AzulaType<'a>>,
    current_return: AzulaType<'a>,
    /// For naming temporaries
    temp_counter: usize,
    /// The call or literal being checked, for errors found while instantiating generics
    last_span: Span,
    /// Names that closures in the function being checked may capture: mutable
    /// variables with these names are kept in heap cells
    captured: HashSet<String>,
    /// For naming the functions closures are lifted into
    closure_counter: usize,
    /// Functions that have a wrapper for use as function values
    function_values: HashSet<String>,

    pub errors: Vec<AzulaError>,
}

#[derive(Clone, Debug)]
struct FunctionDefinition<'a> {
    name: String,
    args: Vec<(AzulaType<'a>, String)>,
    varargs: bool,
    returns: AzulaType<'a>,
}

struct StructDefinition<'a> {
    name: &'a str,
    attrs: Vec<(AzulaType<'a>, &'a str)>,
}

#[derive(Debug, Clone)]
pub struct VariableDefinition<'a> {
    name: String,
    mutable: bool,
    typ: AzulaType<'a>,
}

#[derive(Debug, Clone)]
pub struct Namespace<'a> {
    name: String,
    funcs: HashMap<&'a str, FunctionDefinition<'a>>,
}

#[derive(Clone)]
pub struct Environment<'a> {
    variable_definitions: HashMap<String, VariableDefinition<'a>>,
    /// Variables kept in heap cells (because closures capture them): the
    /// variable holds a pointer to the cell
    boxed: HashSet<String>,
}

impl<'a> Environment<'a> {
    pub fn new() -> Self {
        Self {
            variable_definitions: HashMap::new(),
            boxed: HashSet::new(),
        }
    }

    pub fn add_variable(&mut self, name: String, def: VariableDefinition<'a>) {
        self.boxed.remove(&name);
        self.variable_definitions.insert(name, def);
    }

    /// Add a variable living in a heap cell; `def.typ` is the type of its value
    pub fn add_boxed(&mut self, name: String, def: VariableDefinition<'a>) {
        self.boxed.insert(name.clone());
        self.variable_definitions.insert(name, def);
    }
}

fn leak<'a>(s: String) -> &'a str {
    Box::leak(s.into_boxed_str())
}

fn dummy_span() -> Span {
    Span { start: 0, end: 0 }
}

impl<'a> Typechecker<'a> {
    pub fn new(root: Statement<'a>) -> Self {
        Typechecker {
            ast: root,
            functions: HashMap::new(),
            globals: HashMap::new(),
            structs: HashMap::new(),
            namespaces: HashMap::new(),
            enums: HashMap::new(),
            enum_payloads: HashMap::new(),
            type_aliases: HashMap::new(),
            generic_structs: HashMap::new(),
            generic_enums: HashMap::new(),
            generic_impls: HashMap::new(),
            generic_funcs: HashMap::new(),
            generic_methods: HashMap::new(),
            generic_bounds: HashMap::new(),
            interfaces: HashMap::new(),
            conformances: HashMap::new(),
            instances: HashMap::new(),
            instantiated_functions: HashSet::new(),
            pending: vec![],
            output: vec![],
            expected: None,
            current_return: AzulaType::Void,
            temp_counter: 0,
            last_span: dummy_span(),
            captured: HashSet::new(),
            closure_counter: 0,
            function_values: HashSet::new(),
            errors: vec![],
        }
    }

    pub fn typecheck(&mut self) -> Result<Statement<'a>, String> {
        let stmts = match self.ast.clone() {
            Statement::Root(stmts) => resolve_receivers(self.collect_interfaces(stmts)),
            _ => return Err("Not a root node".to_string()),
        };

        // Pass 0: collect names of everything declared, so declaration order doesn't matter
        let mut defined: HashSet<String> = HashSet::new();
        for stmt in &stmts {
            let defined_name = match stmt {
                Statement::Struct { name, span, .. } | Statement::Enum { name, span, .. } => Some((format!("type {}", name), span.clone())),
                Statement::Function { name, span, .. } => Some((format!("func {}", name), span.clone())),
                Statement::Generic(_, _, inner) => match inner.as_ref() {
                    Statement::Struct { name, span, .. } | Statement::Enum { name, span, .. } => Some((format!("type {}", name), span.clone())),
                    Statement::Function { name, span, .. } => Some((format!("func {}", name), span.clone())),
                    _ => None,
                },
                _ => None,
            };
            if let Some((key, span)) = defined_name {
                if !defined.insert(key.clone()) {
                    self.error(format!("`{}` is defined more than once", &key[5..]), &span);
                }
            }
            match stmt {
                Statement::Generic(params, bounds, inner) => {
                    self.register_generic(params, inner);
                    let name = match inner.as_ref() {
                        Statement::Function { name, .. } | Statement::Struct { name, .. } | Statement::Enum { name, .. } => Some(name),
                        _ => None,
                    };
                    if let Some(name) = name {
                        for (_, interface) in bounds {
                            if !self.interfaces.contains_key(*interface) {
                                self.error(format!("Unknown interface `{}`", interface), &dummy_span());
                            }
                        }
                        self.generic_bounds.insert(
                            name.to_string(),
                            bounds.iter().map(|(p, i)| (p.to_string(), i.to_string())).collect(),
                        );
                    }
                }
                Statement::TypeAlias { name, typ, .. } => {
                    self.type_aliases.insert(name.to_string(), typ.clone());
                }
                Statement::Enum { name, variants, .. } => {
                    self.enums.insert(name.to_string(), variants.iter().map(|v| v.to_string()).collect());
                }
                Statement::Struct { name, attributes, .. } => {
                    self.structs.insert(name.to_string(), StructDefinition { name, attrs: attributes.clone() });
                }
                _ => {}
            }
        }

        // Pass 1: resolve the types used in declarations and register signatures
        let mut root = vec![];
        for stmt in stmts {
            match stmt {
                Statement::Generic(..) => {}
                Statement::Struct { name, attributes, span } => {
                    let attributes: Vec<_> = attributes.into_iter().map(|(t, n)| (self.resolve_type(t), n)).collect();
                    self.structs.insert(name.to_string(), StructDefinition { name, attrs: attributes.clone() });
                    root.push(Statement::Struct { name, attributes, span });
                }
                Statement::Enum { name, variants, payloads, span } => {
                    let payloads: Vec<Vec<_>> = payloads
                        .into_iter()
                        .map(|p| p.into_iter().map(|t| self.resolve_type(t)).collect())
                        .collect();
                    if payloads.iter().any(|p| !p.is_empty()) {
                        self.enum_payloads.insert(name.to_string(), payloads.clone());
                    }
                    root.push(Statement::Enum { name, variants, payloads, span });
                }
                Statement::Function { name, ref args, ref returns, .. } => {
                    let def = self.signature(name, args, returns);
                    self.functions.insert(name, def);
                    root.push(stmt);
                }
                Statement::ExternFunction { name, varargs, args, returns, span } => {
                    let args: Vec<_> = args.into_iter().map(|t| self.resolve_type(t)).collect();
                    let returns = self.resolve_type(returns);
                    self.functions.insert(
                        name,
                        FunctionDefinition {
                            name: name.to_string(),
                            varargs,
                            args: args.iter().map(|t| (t.clone(), "_".to_string())).collect(),
                            returns: returns.clone(),
                        },
                    );
                    root.push(Statement::ExternFunction { name, varargs, args, returns, span });
                }
                Statement::Impl { struct_impl, trait_impl, funcs, span } => {
                    let struct_name = self.resolve_type(struct_impl.clone()).to_string();
                    let mut namespace = self.namespaces.remove(&struct_name).unwrap_or(Namespace {
                        name: struct_name.clone(),
                        funcs: HashMap::new(),
                    });
                    let mut plain = vec![];
                    for func in funcs {
                        match &func {
                            Statement::Function { name, args, returns, .. } => {
                                let def = self.signature(name, args, returns);
                                namespace.funcs.insert(name, def);
                                plain.push(func);
                            }
                            // Generic methods are instantiated when called
                            Statement::Generic(params, _, inner) => {
                                let params = params.iter().map(|p| p.to_string()).collect();
                                self.generic_methods.entry(struct_name.clone()).or_default().push((
                                    vec![],
                                    params,
                                    inner.as_ref().clone(),
                                ));
                            }
                            _ => plain.push(func),
                        }
                    }
                    self.namespaces.insert(struct_name, namespace);
                    root.push(Statement::Impl { struct_impl, trait_impl, funcs: plain, span });
                }
                Statement::Assign(..) => match self.typecheck_global_assign(stmt) {
                    Ok(stmt) => root.push(stmt),
                    Err(_) => {}
                },
                other => root.push(other),
            }
        }

        // Check that types implement the interfaces they claim to (generic
        // types are checked as they are instantiated)
        let mut claims: Vec<(String, String, Vec<AzulaType<'a>>, Span)> = vec![];
        for (type_name, interfaces) in &self.conformances {
            if self.generic_structs.contains_key(type_name) || self.generic_enums.contains_key(type_name) {
                continue;
            }
            for (interface, args, span) in interfaces {
                claims.push((type_name.clone(), interface.clone(), args.clone(), span.clone()));
            }
        }
        claims.sort_by(|a, b| a.3.start.cmp(&b.3.start));
        for (type_name, interface, args, span) in claims {
            let self_type: AzulaType<'a> = AzulaType::from(leak(type_name.clone()));
            self.verify_conformance(&type_name, self_type, &interface, &args, &span);
        }

        // Pass 2: check function bodies
        let mut failed = false;
        for stmt in root.iter_mut() {
            match stmt.clone() {
                Statement::Function { .. } => match self.typecheck_function(stmt.clone()) {
                    Ok(checked) => *stmt = checked,
                    Err(_) => failed = true,
                },
                Statement::Impl { struct_impl, trait_impl, funcs, span } => {
                    let mut checked_funcs = vec![];
                    for func in funcs {
                        match self.typecheck_function(func) {
                            Ok(checked) => checked_funcs.push(checked),
                            Err(_) => failed = true,
                        }
                    }
                    *stmt = Statement::Impl {
                        struct_impl: self.resolve_type(struct_impl),
                        trait_impl,
                        funcs: checked_funcs,
                        span,
                    };
                }
                _ => {}
            }
        }

        // Pass 3: check the generic instances that were requested along the way
        while let Some((impl_type, func)) = self.pending.pop() {
            match self.typecheck_function(func) {
                Ok(checked) => match impl_type {
                    Some(struct_impl) => self.output.push(Statement::Impl {
                        struct_impl,
                        trait_impl: None,
                        funcs: vec![checked],
                        span: dummy_span(),
                    }),
                    None => self.output.push(checked),
                },
                Err(_) => failed = true,
            }
        }

        root.extend(self.output.drain(..));

        if failed || !self.errors.is_empty() {
            return Err("typechecking failed".to_string());
        }
        Ok(Statement::Root(root))
    }

    fn register_generic(&mut self, params: &[&'a str], inner: &Statement<'a>) {
        let params: Vec<String> = params.iter().map(|p| p.to_string()).collect();
        match inner {
            Statement::Function { name, .. } => {
                self.generic_funcs.insert(name.to_string(), (params, inner.clone()));
            }
            Statement::Struct { name, attributes, .. } => {
                self.generic_structs.insert(name.to_string(), (params, attributes.clone()));
            }
            Statement::Enum { name, variants, payloads, .. } => {
                self.enums.insert(name.to_string(), variants.iter().map(|v| v.to_string()).collect());
                self.generic_enums
                    .insert(name.to_string(), (params, variants.clone(), payloads.clone()));
            }
            Statement::Impl { struct_impl, funcs, .. } => {
                if let AzulaType::Generic(name, args) = struct_impl {
                    let impl_params: Vec<String> = args.iter().map(|a| a.to_string()).collect();
                    for func in funcs {
                        if let Statement::Generic(params, _, inner) = func {
                            let params = params.iter().map(|p| p.to_string()).collect();
                            self.generic_methods.entry(name.clone()).or_default().push((
                                impl_params.clone(),
                                params,
                                inner.as_ref().clone(),
                            ));
                        } else {
                            self.generic_impls.entry(name.clone()).or_default().push((impl_params.clone(), func.clone()));
                        }
                    }
                }
            }
            _ => {}
        }
    }

    /// The signature of a function, with its types resolved.
    fn signature(&mut self, name: &str, args: &[TypedIdentifier<'a>], returns: &AzulaType<'a>) -> FunctionDefinition<'a> {
        FunctionDefinition {
            name: name.to_string(),
            varargs: false,
            args: args.iter().map(|(t, n)| (self.resolve_type(t.clone()), n.to_string())).collect(),
            returns: self.resolve_type(returns.clone()),
        }
    }

    fn error(&mut self, message: String, span: &Span) {
        self.errors.push(AzulaError::new(ErrorType::Custom(message), span.start, span.end));
    }

    /// A closure: its body becomes a function taking the closure object
    /// (`$env`) first, and the value is a closure object holding the cells of
    /// the variables it captures
    #[allow(clippy::too_many_arguments)]
    fn typecheck_closure(
        &mut self,
        params: Vec<(Option<AzulaType<'a>>, String)>,
        returns: Option<AzulaType<'a>>,
        body: Vec<Statement<'a>>,
        span: Span,
        env: &Environment<'a>,
        expected: Option<AzulaType<'a>>,
    ) -> Result<(ExpressionNode<'a>, AzulaType<'a>), String> {
        // Types the context expects, if any
        let (expected_params, expected_return) = match expected {
            Some(AzulaType::Function(p, r)) if p.len() == params.len() => (Some(p), Some(r.as_ref().clone())),
            _ => (None, None),
        };
        let mut param_types = vec![];
        for (i, (typ, name)) in params.iter().enumerate() {
            let typ = match (typ, &expected_params) {
                (Some(t), _) => self.resolve_type(t.clone()),
                (None, Some(p)) if p[i] != AzulaType::Infer => p[i].clone(),
                _ => {
                    self.error(
                        format!("Can't infer the type of parameter `{}`; give it a type like `{}: int`", name, name),
                        &span,
                    );
                    return Err("cannot infer closure parameter".to_string());
                }
            };
            param_types.push(typ);
        }
        let declared_return = match (returns, expected_return) {
            (Some(r), _) => self.resolve_type(r),
            (None, Some(r)) => r,
            (None, None) => AzulaType::Infer,
        };

        // The variables it captures, as cells
        let names: Vec<String> = params.iter().map(|(_, n)| n.clone()).collect();
        let mut captures = vec![];
        let mut inner_env = Environment::new();
        let mut prologue = vec![];
        for name in closure_free_names(&names, &body) {
            let def = match env.variable_definitions.get(&name) {
                Some(def) => def.clone(),
                None => continue,
            };
            let cell_type = AzulaType::Pointer(Rc::new(def.typ.clone()));
            let variable = ExpressionNode { expression: Expression::Identifier(name.clone()), typed: def.typ.clone(), span: span.clone() };
            let cell = if env.boxed.contains(&name) {
                // Share the variable's cell
                ExpressionNode { typed: cell_type.clone(), ..variable }
            } else {
                // Immutable variables can't change, so a copy is as good as the original
                ExpressionNode { expression: Expression::NewCell(Rc::new(variable)), typed: cell_type.clone(), span: span.clone() }
            };
            let index = captures.len();
            captures.push(cell);
            prologue.push(Statement::Assign(
                false,
                name.clone(),
                Some(cell_type.clone()),
                ExpressionNode { expression: Expression::EnvCell(index), typed: cell_type, span: span.clone() },
                span.clone(),
            ));
            inner_env.add_boxed(name.clone(), def);
        }
        for (typ, name) in param_types.iter().zip(&names) {
            inner_env.add_variable(name.clone(), VariableDefinition { name: name.clone(), mutable: false, typ: typ.clone() });
        }

        // Check the body as a function of its own
        let saved_return = std::mem::replace(&mut self.current_return, declared_return);
        let saved_captured = std::mem::replace(&mut self.captured, captured_names(&body));
        let mut statements = prologue;
        let mut failed = false;
        for stmt in body {
            match self.typecheck_statement(stmt, &mut inner_env) {
                Ok((stmt, _)) => statements.push(stmt),
                Err(_) => failed = true,
            }
        }
        let mut returns = std::mem::replace(&mut self.current_return, saved_return);
        self.captured = saved_captured;
        if failed {
            return Err("errors in closure".to_string());
        }
        if returns == AzulaType::Infer {
            returns = AzulaType::Void;
        }
        if returns != AzulaType::Void && !always_returns(&statements) {
            self.error("This closure might not return a value".to_string(), &span);
            return Err("missing return".to_string());
        }

        let name = leak(format!("closure.{}", self.closure_counter));
        self.closure_counter += 1;
        let mut args: Vec<(AzulaType<'a>, &'a str)> = vec![(AzulaType::Str, "$env")];
        for (typ, n) in param_types.iter().zip(&names) {
            args.push((typ.clone(), leak(n.clone())));
        }
        self.output.push(Statement::Function {
            name,
            args,
            returns: returns.clone(),
            body: Rc::new(Statement::Block(statements)),
            span: span.clone(),
        });
        let typ = AzulaType::Function(param_types, Rc::new(returns));
        Ok((ExpressionNode { expression: Expression::MakeClosure(name.to_string(), captures), typed: typ.clone(), span }, typ))
    }

    /// Function `name` as a value: a closure object for a wrapper that takes
    /// the (unused) environment and calls it
    fn function_value(&mut self, name: &str, span: Span) -> Result<(ExpressionNode<'a>, AzulaType<'a>), String> {
        let def = self.functions[name].clone();
        let wrapper = format!("fn.{}", name);
        if self.function_values.insert(name.to_string()) {
            let mut args: Vec<(AzulaType<'a>, &'a str)> = vec![(AzulaType::Str, "$env")];
            let mut call_args = vec![];
            for (i, (typ, _)) in def.args.iter().enumerate() {
                let arg = leak(format!("a{}", i));
                args.push((typ.clone(), arg));
                call_args.push(ExpressionNode { expression: Expression::Identifier(arg.to_string()), typed: AzulaType::Infer, span: span.clone() });
            }
            let call = ExpressionNode {
                expression: Expression::FunctionCall {
                    function: Rc::new(ExpressionNode { expression: Expression::Identifier(name.to_string()), typed: AzulaType::Infer, span: span.clone() }),
                    args: call_args,
                },
                typed: AzulaType::Infer,
                span: span.clone(),
            };
            let body = if def.returns == AzulaType::Void || def.returns == AzulaType::Never {
                Statement::ExpressionStatement(call, span.clone())
            } else {
                Statement::Return(Some(call), span.clone())
            };
            let function = Statement::Function {
                name: leak(wrapper.clone()),
                args,
                returns: def.returns.clone(),
                body: Rc::new(Statement::Block(vec![body])),
                span: span.clone(),
            };
            let saved_return = self.current_return.clone();
            let saved_captured = std::mem::take(&mut self.captured);
            let checked = self.typecheck_function(function);
            self.current_return = saved_return;
            self.captured = saved_captured;
            self.output.push(checked?);
        }
        let typ = AzulaType::Function(def.args.iter().map(|(t, _)| t.clone()).collect(), Rc::new(def.returns.clone()));
        Ok((ExpressionNode { expression: Expression::MakeClosure(wrapper, vec![]), typed: typ.clone(), span }, typ))
    }

    /// Whether `obj.field` is a field holding a function (rather than a method)
    fn is_function_field(&mut self, obj: &ExpressionNode<'a>, field: &str, env: &Environment<'a>) -> bool {
        let error_count = self.errors.len();
        let typ = match self.typecheck_expression(obj.clone(), env) {
            Ok((_, t)) => t,
            Err(_) => {
                self.errors.truncate(error_count);
                return false;
            }
        };
        let type_name = match &typ {
            AzulaType::Pointer(inner) => inner.to_string(),
            t => t.to_string(),
        };
        if self.namespaces.get(&type_name).map(|n| n.funcs.contains_key(field)).unwrap_or(false) {
            return false;
        }
        self.structs
            .get(&type_name)
            .map(|s| s.attrs.iter().any(|(t, n)| *n == field && matches!(t, AzulaType::Function(..))))
            .unwrap_or(false)
    }

    /// Call a function value
    fn typecheck_closure_call(
        &mut self,
        callee: ExpressionNode<'a>,
        args: Vec<ExpressionNode<'a>>,
        span: Span,
        env: &Environment<'a>,
    ) -> Result<(ExpressionNode<'a>, AzulaType<'a>), String> {
        let (params, returns) = match &callee.typed {
            AzulaType::Function(p, r) => (p.clone(), r.as_ref().clone()),
            other => {
                self.error(format!("A value of type {} can't be called", other.mangle()), &callee.span);
                return Err("not callable".to_string());
            }
        };
        if params.len() != args.len() {
            self.error(format!("This function takes {} arguments, got {}", params.len(), args.len()), &span);
            return Err("wrong argument count".to_string());
        }
        let mut checked = vec![];
        for (arg, param) in args.into_iter().zip(&params) {
            let (arg, typ) = self.typecheck_expecting(arg, env, param)?;
            if !assignable(param, &typ, &arg) {
                self.errors.push(AzulaError::new(
                    ErrorType::MismatchedTypes(param.mangle(), typ.mangle()),
                    arg.span.start,
                    arg.span.end,
                ));
                return Err("mismatched argument".to_string());
            }
            checked.push(arg);
        }
        Ok((
            ExpressionNode { expression: Expression::CallClosure(Rc::new(callee), checked), typed: returns.clone(), span },
            returns,
        ))
    }

    /// `if cond { a } else { b }` as a value: branches that always return don't
    /// affect its type, and branches of different types (or no `else`) make it void
    fn typecheck_if_expression(
        &mut self,
        cond: Rc<ExpressionNode<'a>>,
        then: Rc<ExpressionNode<'a>>,
        otherwise: Option<Rc<ExpressionNode<'a>>>,
        span: Span,
        env: &Environment<'a>,
        expected: Option<AzulaType<'a>>,
    ) -> Result<(ExpressionNode<'a>, AzulaType<'a>), String> {
        let (cond, cond_type) = self.typecheck_expression(cond.as_ref().clone(), env)?;
        if cond_type != AzulaType::Bool {
            self.errors.push(AzulaError::new(
                ErrorType::NonBoolCondition(cond_type.mangle()),
                cond.span.start,
                cond.span.end,
            ));
            return Err("non-bool condition".to_string());
        }
        let mut check = |this: &mut Self, branch: ExpressionNode<'a>| match &expected {
            Some(e) => this.typecheck_expecting(branch, env, e),
            None => this.typecheck_expression(branch, env),
        };
        let (then, then_type) = check(self, then.as_ref().clone())?;
        let (otherwise, typ) = match otherwise {
            None => (None, AzulaType::Void),
            Some(o) => {
                let (o, o_type) = check(self, o.as_ref().clone())?;
                let diverges = |node: &ExpressionNode<'a>, t: &AzulaType<'a>| {
                    *t == AzulaType::Never
                        || matches!(&node.expression, Expression::Block(stmts, None) if always_returns(stmts))
                };
                let typ = if diverges(&then, &then_type) {
                    o_type.clone()
                } else if diverges(&o, &o_type) || then_type == o_type {
                    then_type.clone()
                } else {
                    AzulaType::Void
                };
                (Some(Rc::new(o)), typ)
            }
        };
        Ok((
            ExpressionNode { expression: Expression::If(Rc::new(cond), Rc::new(then), otherwise), typed: typ.clone(), span },
            typ,
        ))
    }

    /// `value?` on an Option or Result becomes
    ///
    ///   match value { Option::Some(v) => v, Option::None => { return Option::None; } }
    ///   match value { Result::Ok(v) => v, Result::Err(e) => { return Result::Err(e); } }
    ///
    /// which needs the function to return an Option, or a Result with the same error type
    fn typecheck_try(
        &mut self,
        inner: ExpressionNode<'a>,
        span: Span,
        env: &Environment<'a>,
    ) -> Result<(ExpressionNode<'a>, AzulaType<'a>), String> {
        let (_, typ) = self.typecheck_expression(inner.clone(), env)?;
        let generic_of = |t: &AzulaType<'a>| self.instances.get(&t.to_string()).cloned();
        let (kind, args) = match generic_of(&typ) {
            Some((g, args)) if g == "Option" || g == "Result" => (g, args),
            _ => {
                self.error(format!("`?` needs an Option or a Result, not {}", typ.mangle()), &inner.span);
                return Err("bad ?".to_string());
            }
        };
        let returns = self.current_return.clone();
        match (kind.as_str(), generic_of(&returns)) {
            ("Option", Some((g, _))) if g == "Option" => {}
            ("Result", Some((g, ret_args))) if g == "Result" => {
                if ret_args[1] != args[1] {
                    self.error(
                        format!(
                            "`?` would return an error of type {}, but this function's errors are {}",
                            args[1].mangle(),
                            ret_args[1].mangle()
                        ),
                        &span,
                    );
                    return Err("mismatched error types".to_string());
                }
            }
            _ => {
                self.error(format!("`?` on {} can only be used in a function returning {}", typ.mangle(), if kind == "Option" { "an Option" } else { "a Result" }), &span);
                return Err("bad ?".to_string());
            }
        }

        let value = leak(format!("$try{}", self.temp_counter));
        let error = leak(format!("$error{}", self.temp_counter));
        self.temp_counter += 1;
        let node = |e: Expression<'a>| ExpressionNode { expression: e, typed: AzulaType::Infer, span: span.clone() };
        let ident = |n: &str| ExpressionNode { expression: Expression::Identifier(n.to_string()), typed: AzulaType::Infer, span: span.clone() };
        let path = |ns: &str, member: &str| node(Expression::NamespaceAccess(Rc::new(ident(ns)), Rc::new(ident(member))));
        let early_return = |value: ExpressionNode<'a>| node(Expression::Block(vec![Statement::Return(Some(value), span.clone())], None));
        let arms = if kind == "Option" {
            vec![
                (MatchPattern::Destructure("Option", "Some", vec![Some(value)]), ident(value)),
                (MatchPattern::Variant("Option", "None"), early_return(path("Option", "None"))),
            ]
        } else {
            let rewrap = node(Expression::FunctionCall { function: Rc::new(path("Result", "Err")), args: vec![ident(error)] });
            vec![
                (MatchPattern::Destructure("Result", "Ok", vec![Some(value)]), ident(value)),
                (MatchPattern::Destructure("Result", "Err", vec![Some(error)]), early_return(rewrap)),
            ]
        };
        self.typecheck_expression(node(Expression::Match(Rc::new(inner), arms)), env)
    }

    /// The struct standing for tuple type `(items)`, with fields named `0`, `1`, ...
    fn instantiate_tuple(&mut self, items: Vec<AzulaType<'a>>) -> AzulaType<'a> {
        let name = AzulaType::Tuple(items.clone()).mangle();
        if !self.structs.contains_key(&name) {
            let attributes: Vec<_> = items.iter().enumerate().map(|(i, t)| (t.clone(), leak(i.to_string()))).collect();
            let struct_name = leak(name.clone());
            self.structs.insert(name.clone(), StructDefinition { name: struct_name, attrs: attributes.clone() });
            self.instances.insert(name.clone(), (TUPLE.to_string(), items));
            self.output.push(Statement::Struct { name: struct_name, attributes, span: dummy_span() });
        }
        AzulaType::Named(name)
    }

    /// The element types of `typ`, if it is a tuple
    fn tuple_items(&self, typ: &AzulaType<'a>) -> Option<Vec<AzulaType<'a>>> {
        match typ {
            AzulaType::Named(name) => match self.instances.get(name) {
                Some((generic, items)) if generic == TUPLE => Some(items.clone()),
                _ => None,
            },
            _ => None,
        }
    }

    /// `(a, b)` becomes a literal of the tuple's struct
    fn typecheck_tuple(
        &mut self,
        items: Vec<ExpressionNode<'a>>,
        span: Span,
        env: &Environment<'a>,
        expected: Option<AzulaType<'a>>,
    ) -> Result<(ExpressionNode<'a>, AzulaType<'a>), String> {
        let expected_items = expected
            .and_then(|t| self.tuple_items(&t))
            .filter(|e| e.len() == items.len());
        let mut checked = vec![];
        let mut types = vec![];
        for (i, item) in items.into_iter().enumerate() {
            let (node, typ) = match &expected_items {
                Some(e) => self.typecheck_expecting(item, env, &e[i])?,
                None => self.typecheck_expression(item, env)?,
            };
            // Integer literals take the expected element type
            let typ = match &expected_items {
                Some(e) if is_integer_literal(&node) && is_integer_type(&e[i]) => e[i].clone(),
                _ => typ,
            };
            let mut node = node;
            node.typed = typ.clone();
            types.push(typ);
            checked.push((leak(i.to_string()), node));
        }
        let typ = self.instantiate_tuple(types);
        let name = typ.to_string();
        let struc = ExpressionNode { expression: Expression::Identifier(name), typed: typ.clone(), span: span.clone() };
        Ok((
            ExpressionNode { expression: Expression::StructInitialisation(Rc::new(struc), checked), typed: typ.clone(), span },
            typ,
        ))
    }

    /// `var (a, b) = value;` becomes `const $tupleN = value; var a = $tupleN.0; var b = $tupleN.1;`
    fn typecheck_destructure(
        &mut self,
        stmt: Statement<'a>,
        env: &mut Environment<'a>,
    ) -> Result<(Statement<'a>, AzulaType<'a>), String> {
        if let Statement::Destructure(mutable, names, value, span) = stmt {
            let temp = format!("$tuple{}", self.temp_counter);
            self.temp_counter += 1;
            let value_span = value.span.clone();
            let (first, _) = self.typecheck_statement(Statement::Assign(false, temp.clone(), None, value, span.clone()), env)?;
            let typ = env.variable_definitions[&temp].typ.clone();
            let items = match self.tuple_items(&typ) {
                Some(items) => items,
                None => {
                    self.error(format!("Can't destructure a value of type {}; it isn't a tuple", typ.mangle()), &value_span);
                    return Err("not a tuple".to_string());
                }
            };
            if items.len() != names.len() {
                self.error(format!("This tuple has {} elements, but {} names are given", items.len(), names.len()), &span);
                return Err("wrong tuple arity".to_string());
            }
            let mut stmts = vec![first];
            for (i, name) in names.into_iter().enumerate() {
                if name == "_" {
                    continue;
                }
                let node = |e| ExpressionNode { expression: e, typed: AzulaType::Infer, span: span.clone() };
                let access = node(Expression::StructAccess(
                    Rc::new(node(Expression::Identifier(temp.clone()))),
                    Rc::new(node(Expression::Identifier(i.to_string()))),
                ));
                let (stmt, _) = self.typecheck_statement(Statement::Assign(mutable, name, None, access, span.clone()), env)?;
                stmts.push(stmt);
            }
            return Ok((Statement::Group(stmts), AzulaType::Void));
        }
        unreachable!()
    }

    /// Record interfaces and which types implement them, and give types the
    /// default methods of their interfaces they don't define themselves.
    /// Returns the program without interface declarations.
    fn collect_interfaces(&mut self, stmts: Vec<Statement<'a>>) -> Vec<Statement<'a>> {
        for stmt in &stmts {
            if let Statement::Interface { name, params, methods, span } = stmt {
                let params = params.iter().map(|p| p.to_string()).collect();
                if self.interfaces.insert(name.to_string(), (params, methods.clone())).is_some() {
                    self.error(format!("`{}` is defined more than once", name), span);
                }
            }
        }
        // The methods each type defines
        let mut defined: HashMap<String, HashSet<String>> = HashMap::new();
        for stmt in &stmts {
            let imp = match stmt {
                Statement::Generic(_, _, inner) => inner.as_ref(),
                other => other,
            };
            if let Statement::Impl { struct_impl, funcs, .. } = imp {
                let entry = defined.entry(type_key(struct_impl)).or_default();
                for f in funcs {
                    let f = match f {
                        Statement::Generic(_, _, inner) => inner.as_ref(),
                        other => other,
                    };
                    if let Statement::Function { name, .. } = f {
                        entry.insert(name.to_string());
                    }
                }
            }
        }
        let mut out = vec![];
        let mut defaults = vec![];
        for stmt in stmts {
            match stmt {
                Statement::Interface { .. } => {}
                Statement::Conforms(target, interfaces, span) => {
                    let key = type_key(&target);
                    for (interface, args) in interfaces {
                        self.conformances.entry(key.clone()).or_default().push((interface.to_string(), args.clone(), span.clone()));
                        let (params, methods) = match self.interfaces.get(interface) {
                            Some(m) => m.clone(),
                            None => {
                                self.error(format!("Unknown interface `{}`", interface), &span);
                                continue;
                            }
                        };
                        if params.len() != args.len() {
                            self.error(format!("Interface `{}` takes {} type arguments, got {}", interface, params.len(), args.len()), &span);
                            continue;
                        }
                        // Default methods use the type arguments given here
                        let iface_map: Substitution<'a> = params.iter().cloned().zip(args.iter().cloned()).collect();
                        for (method, has_body) in methods {
                            let name = match &method {
                                Statement::Function { name, .. } => name.to_string(),
                                Statement::Generic(_, _, inner) => match inner.as_ref() {
                                    Statement::Function { name, .. } => name.to_string(),
                                    _ => continue,
                                },
                                _ => continue,
                            };
                            if !has_body || defined.get(&key).map(|d| d.contains(&name)).unwrap_or(false) {
                                continue;
                            }
                            defined.entry(key.clone()).or_default().insert(name);
                            let imp = Statement::Impl {
                                struct_impl: target.clone(),
                                trait_impl: None,
                                funcs: vec![subst_stmt(&method, &iface_map)],
                                span: span.clone(),
                            };
                            defaults.push(match &target {
                                AzulaType::Generic(_, args) => Statement::Generic(
                                    args.iter().map(|a| leak(a.to_string())).collect(),
                                    vec![],
                                    Rc::new(imp),
                                ),
                                _ => imp,
                            });
                        }
                    }
                }
                other => out.push(other),
            }
        }
        out.extend(defaults);

        out
    }

    /// A signature with its types resolved
    fn resolve_signature(&mut self, def: FunctionDefinition<'a>) -> FunctionDefinition<'a> {
        FunctionDefinition {
            args: def.args.into_iter().map(|(t, n)| (self.resolve_type(t), n)).collect(),
            returns: self.resolve_type(def.returns),
            ..def
        }
    }

    /// Check that `type_name` has the methods of `interface`, with matching signatures
    fn verify_conformance(
        &mut self,
        type_name: &str,
        self_type: AzulaType<'a>,
        interface: &str,
        args: &[AzulaType<'a>],
        span: &Span,
    ) {
        let (params, methods) = match self.interfaces.get(interface) {
            Some(m) => m.clone(),
            None => return,
        };
        let receiver = if self.structs.contains_key(type_name) {
            AzulaType::Pointer(Rc::new(self_type.clone()))
        } else {
            self_type.clone()
        };
        let mut map = Substitution::new();
        map.insert("Self".to_string(), self_type.clone());
        map.insert("__self".to_string(), receiver);
        for (param, arg) in params.iter().zip(args) {
            map.insert(param.clone(), arg.clone());
        }
        for (method, has_body) in methods {
            // Default methods are copied from the interface, so they fit
            if has_body {
                continue;
            }
            if let Statement::Function { name, args, returns, .. } = method {
                let found = self.namespaces.get(type_name).and_then(|n| n.funcs.get(name)).cloned();
                let found = match found {
                    Some(f) => self.resolve_signature(f),
                    None => {
                        self.error(
                            format!("`{}` doesn't implement `{}`: it has no method `{}`", self_type.mangle(), interface, name),
                            span,
                        );
                        continue;
                    }
                };
                let expected_args: Vec<AzulaType<'a>> =
                    args.iter().map(|(t, _)| self.resolve_type(subst_type(t, &map))).collect();
                let expected_return = self.resolve_type(subst_type(&returns, &map));
                let actual_args: Vec<AzulaType<'a>> = found.args.iter().map(|(t, _)| t.clone()).collect();
                let takes_self = |a: &[(AzulaType<'a>, &str)]| a.first().map(|(_, n)| *n == "self").unwrap_or(false);
                let self_matches = takes_self(&args) == found.args.first().map(|(_, n)| n == "self").unwrap_or(false);
                let skip = if takes_self(&args) { 1 } else { 0 };
                if !self_matches {
                    let problem = if takes_self(&args) { "is static" } else { "is a method" };
                    let wanted = if takes_self(&args) { "a method" } else { "static" };
                    self.error(
                        format!("`{}.{}` {}, but interface `{}` needs it to be {}", self_type.mangle(), name, problem, interface, wanted),
                        span,
                    );
                    continue;
                }
                if !self_matches || expected_args[skip.min(expected_args.len())..] != actual_args[skip.min(actual_args.len())..] || expected_return != found.returns {
                    let signature = AzulaType::Function(expected_args[skip.min(expected_args.len())..].to_vec(), Rc::new(expected_return));
                    self.error(
                        format!(
                            "`{}.{}` doesn't match interface `{}`, which expects {}",
                            self_type.mangle(),
                            name,
                            interface,
                            signature.mangle()
                        ),
                        span,
                    );
                }
            }
        }
    }

    /// Whether `typ` implements `interface`
    fn implements(&self, typ: &AzulaType<'a>, interface: &str) -> bool {
        let key = type_key(typ);
        let has = |key: &str| {
            self.conformances.get(key).map(|c| c.iter().any(|(i, _, _)| i == interface)).unwrap_or(false)
        };
        has(&key) || self.instances.get(&key).map(|(generic, _)| has(generic)).unwrap_or(false)
    }

    /// Check the bounds generic `name` puts on its type parameters `params` against `args`
    fn check_bounds(&mut self, name: &str, params: &[String], args: &[AzulaType<'a>]) {
        let bounds = self.generic_bounds.get(name).cloned().unwrap_or_default();
        for (param, interface) in bounds {
            if let Some(index) = params.iter().position(|p| *p == param) {
                if index < args.len() && !self.implements(&args[index], &interface) {
                    let span = self.last_span.clone();
                    self.error(
                        format!(
                            "`{}` doesn't implement `{}`, which `{}` requires of {}",
                            args[index].mangle(),
                            interface,
                            name,
                            param
                        ),
                        &span,
                    );
                }
            }
        }
    }

    /// Instantiate the generic type `name<args>` (if not done already), returning the instance type.
    fn instantiate_type(&mut self, name: &str, args: Vec<AzulaType<'a>>) -> AzulaType<'a> {
        let instance = AzulaType::Generic(name.to_string(), args.clone()).mangle();
        if self.instances.contains_key(&instance) {
            return AzulaType::Named(instance);
        }

        let params = if let Some((params, _)) = self.generic_structs.get(name) {
            params.clone()
        } else if let Some((params, _, _)) = self.generic_enums.get(name) {
            params.clone()
        } else {
            self.errors.push(AzulaError::new(ErrorType::UnknownStruct(name.to_string()), 0, 0));
            return AzulaType::Named(instance);
        };
        if params.len() != args.len() {
            self.errors.push(AzulaError::new(
                ErrorType::Custom(format!("{} expects {} type arguments, got {}", name, params.len(), args.len())),
                0,
                0,
            ));
            return AzulaType::Named(instance);
        }

        self.instances.insert(instance.clone(), (name.to_string(), args.clone()));
        self.check_bounds(name, &params, &args);
        let map: Substitution<'a> = params.iter().cloned().zip(args.iter().cloned()).collect();
        let instance_name = leak(instance.clone());

        if let Some((_, attrs)) = self.generic_structs.get(name).cloned() {
            let attributes: Vec<_> = attrs
                .iter()
                .map(|(t, n)| (self.resolve_type(subst_type(t, &map)), *n))
                .collect();
            self.structs.insert(
                instance.clone(),
                StructDefinition { name: instance_name, attrs: attributes.clone() },
            );
            self.output.push(Statement::Struct { name: instance_name, attributes, span: dummy_span() });
        } else if let Some((_, variants, payloads)) = self.generic_enums.get(name).cloned() {
            let payloads: Vec<Vec<_>> = payloads
                .iter()
                .map(|p| p.iter().map(|t| self.resolve_type(subst_type(t, &map))).collect())
                .collect();
            self.enums.insert(instance.clone(), variants.iter().map(|v| v.to_string()).collect());
            if payloads.iter().any(|p| !p.is_empty()) {
                self.enum_payloads.insert(instance.clone(), payloads.clone());
            }
            self.output.push(Statement::Enum { name: instance_name, variants, payloads, span: dummy_span() });
        }

        // Method signatures of the instance (bodies are instantiated when first
        // called). Their types are resolved when they're used: resolving them
        // now could instantiate types without end, e.g. an iterator adapter
        // whose `filter` returns Filtered<Self>.
        let mut funcs = HashMap::new();
        for (impl_params, func) in self.generic_impls.get(name).cloned().unwrap_or_default() {
            if let Statement::Function { name: fname, args: fargs, returns, .. } = &func {
                let map: Substitution<'a> = impl_params.iter().cloned().zip(args.iter().cloned()).collect();
                let def = FunctionDefinition {
                    name: fname.to_string(),
                    varargs: false,
                    args: fargs.iter().map(|(t, n)| (subst_type(t, &map), n.to_string())).collect(),
                    returns: subst_type(returns, &map),
                };
                funcs.insert(*fname, def);
            }
        }
        self.namespaces.insert(instance.clone(), Namespace { name: instance.clone(), funcs });

        // Generic types implementing interfaces are checked per instance
        for (interface, iface_args, span) in self.conformances.get(name).cloned().unwrap_or_default() {
            // The interface's arguments are in terms of the generic's parameters
            let instance_map: Substitution<'a> = params.iter().cloned().zip(args.iter().cloned()).collect();
            let iface_args: Vec<AzulaType<'a>> =
                iface_args.iter().map(|a| self.resolve_type(subst_type(a, &instance_map))).collect();
            self.verify_conformance(&instance, AzulaType::Named(instance.clone()), &interface, &iface_args, &span);
        }

        AzulaType::Named(instance)
    }

    /// Make sure the body of method `method` of generic instance `instance` is generated.
    fn instantiate_method(&mut self, instance: &str, method: &str) {
        let key = format!("{}_{}", instance, method);
        if self.instantiated_functions.contains(&key) {
            return;
        }
        let (generic, args) = match self.instances.get(instance) {
            Some(x) => x.clone(),
            None => return,
        };
        for (impl_params, func) in self.generic_impls.get(&generic).cloned().unwrap_or_default() {
            if let Statement::Function { name, .. } = &func {
                if *name == method {
                    self.instantiated_functions.insert(key);
                    let map: Substitution<'a> = impl_params.iter().cloned().zip(args.iter().cloned()).collect();
                    self.pending.push((Some(AzulaType::Named(instance.to_string())), subst_stmt(&func, &map)));
                    return;
                }
            }
        }
    }

    /// Instantiate generic function `name` with `args`, returning the instance's name.
    fn instantiate_function(&mut self, name: &str, args: Vec<AzulaType<'a>>) -> String {
        let instance = AzulaType::Generic(name.to_string(), args.clone()).mangle();
        if self.instantiated_functions.contains(&instance) {
            return instance;
        }
        self.instantiated_functions.insert(instance.clone());
        let (params, func) = self.generic_funcs.get(name).cloned().unwrap();
        self.check_bounds(name, &params, &args);
        let map: Substitution<'a> = params.iter().cloned().zip(args.iter().cloned()).collect();
        if let Statement::Function { args: fargs, returns, body, span, .. } = subst_stmt(&func, &map) {
            let instance_name = leak(instance.clone());
            let def = self.signature(instance_name, &fargs, &returns);
            self.functions.insert(instance_name, def);
            self.pending.push((
                None,
                Statement::Function { name: instance_name, args: fargs, returns, body, span },
            ));
        }
        instance
    }

    /// Work out the arguments of generic `name` (with parameters `params`) from the
    /// expected type and from matching `patterns` against the `concrete` types.
    fn infer_type_args(
        &mut self,
        name: &str,
        params: &[String],
        expected: &Option<AzulaType<'a>>,
        patterns: &[AzulaType<'a>],
        concrete: &[AzulaType<'a>],
        span: &Span,
    ) -> Option<Vec<AzulaType<'a>>> {
        let mut bindings = Substitution::new();
        if let Some(AzulaType::Named(expected)) = expected {
            if let Some((generic, args)) = self.instances.get(expected) {
                if generic == name {
                    return Some(args.clone());
                }
            }
        }
        for (pattern, concrete) in patterns.iter().zip(concrete) {
            unify(pattern, concrete, params, &self.instances, &mut bindings);
        }
        let mut args = vec![];
        for param in params {
            match bindings.get(param) {
                Some(t) => args.push(t.clone()),
                None => {
                    self.error(
                        format!("Cannot infer type parameter {} of {}; add type arguments like {}::<...>", param, name, name),
                        span,
                    );
                    return None;
                }
            }
        }
        Some(args)
    }

    /// Pair up parameter `patterns` with the types of the `args` that can be
    /// typechecked on their own. Arguments that need more context (such as
    /// `Option::None`) are skipped and their errors discarded; they are checked
    /// properly once the type arguments are known.
    fn types_for_inference(
        &mut self,
        patterns: &[AzulaType<'a>],
        args: &[ExpressionNode<'a>],
        env: &Environment<'a>,
    ) -> (Vec<AzulaType<'a>>, Vec<AzulaType<'a>>) {
        let mut known_patterns = vec![];
        let mut concrete = vec![];
        for (pattern, arg) in patterns.iter().zip(args) {
            let error_count = self.errors.len();
            match self.typecheck_expression(arg.clone(), env) {
                Ok((_, typ)) => {
                    known_patterns.push(pattern.clone());
                    concrete.push(typ);
                }
                Err(_) => self.errors.truncate(error_count),
            }
        }
        (known_patterns, concrete)
    }

    /// Closures whose parameter types weren't given can't be typechecked on
    /// their own. Once the type parameters their parameters use are known
    /// (from `known` patterns and `concrete` types so far), check them to
    /// learn their return types, adding what they tell us to the lists.
    fn infer_from_closures(
        &mut self,
        params: &[String],
        patterns: &[AzulaType<'a>],
        args: &[ExpressionNode<'a>],
        known: &mut Vec<AzulaType<'a>>,
        concrete: &mut Vec<AzulaType<'a>>,
        env: &Environment<'a>,
    ) {
        let mut bindings = Substitution::new();
        for (p, c) in known.iter().zip(concrete.iter()) {
            unify(p, c, params, &self.instances, &mut bindings);
        }
        for (pattern, arg) in patterns.iter().zip(args) {
            let (closure_params, returns) = match (pattern, &arg.expression) {
                (AzulaType::Function(p, r), Expression::Closure(cp, _, _)) if cp.iter().any(|(t, _)| t.is_none()) => (p, r),
                _ => continue,
            };
            let closure_params: Vec<_> = closure_params.iter().map(|t| subst_type(t, &bindings)).collect();
            if closure_params.iter().any(|t| mentions_params(t, params)) {
                continue;
            }
            let expected = AzulaType::Function(closure_params, Rc::new(AzulaType::Infer));
            let error_count = self.errors.len();
            match self.typecheck_expecting(arg.clone(), env, &expected) {
                Ok((_, typ)) => {
                    let _ = returns;
                    unify(pattern, &typ, params, &self.instances, &mut bindings);
                    known.push(pattern.clone());
                    concrete.push(typ);
                }
                Err(_) => self.errors.truncate(error_count),
            }
        }
    }

    /// Typecheck `expr`, telling it the type it is expected to have.
    fn typecheck_expecting(
        &mut self,
        expr: ExpressionNode<'a>,
        env: &Environment<'a>,
        expected: &AzulaType<'a>,
    ) -> Result<(ExpressionNode<'a>, AzulaType<'a>), String> {
        self.expected = Some(expected.clone());
        let result = self.typecheck_expression(expr, env);
        self.expected = None;
        // An unsigned integer (or char) stored in a wider integer is
        // zero-extended, which needs an explicit conversion
        match result {
            Ok((mut node, typ)) if is_unsigned_type(&typ) && int_bits(expected) > int_bits(&typ) && int_bits(&typ) > 0 => {
                node.typed = typ.clone();
                let span = node.span.clone();
                Ok((
                    ExpressionNode {
                        expression: Expression::Cast(Rc::new(node), expected.clone()),
                        typed: expected.clone(),
                        span,
                    },
                    expected.clone(),
                ))
            }
            other => other,
        }
    }

    pub fn typecheck_statement(
        &mut self,
        stmt: Statement<'a>,
        env: &mut Environment<'a>,
    ) -> Result<(Statement<'a>, AzulaType<'a>), String> {
        match stmt {
            Statement::Assign(..) => self.typecheck_assign(stmt, env),
            Statement::Return(..) => self.typecheck_return(stmt, env),
            Statement::ExpressionStatement(expr, span) => {
                let result = match self.typecheck_expression(expr, env) {
                    Ok((expr, _)) => expr,
                    Err(e) => return Err(e),
                };
                Ok((
                    Statement::ExpressionStatement(result, span),
                    AzulaType::Void,
                ))
            }
            Statement::If(..) => self.typecheck_if(stmt, env),
            Statement::While(..) => self.typecheck_while(stmt, env),
            Statement::For(..) => self.typecheck_for(stmt, env),
            Statement::ForIn(..) => self.typecheck_for_in(stmt, env),
            Statement::CompoundAssign(..) => self.typecheck_compound_assign(stmt, env),
            Statement::Destructure(..) => self.typecheck_destructure(stmt, env),
            Statement::Break(span) => Ok((Statement::Break(span), AzulaType::Void)),
            Statement::Continue(span) => Ok((Statement::Continue(span), AzulaType::Void)),
            Statement::Reassign(..) => self.typecheck_reassign(stmt, env),
            Statement::Block(stmts) => {
                let mut checked = vec![];
                let env = &mut env.clone();
                for s in stmts {
                    match self.typecheck_statement(s, env) {
                        Ok((s, _)) => checked.push(s),
                        Err(e) => return Err(e),
                    }
                }
                Ok((Statement::Block(checked), AzulaType::Void))
            }
            _ => unreachable!("{:?}", stmt),
        }
    }

    fn typecheck_function(&mut self, stmt: Statement<'a>) -> Result<Statement<'a>, String> {
        if let Statement::Function {
            name,
            args,
            returns,
            body,
            span,
        } = stmt
        {
            let args: Vec<_> = args.into_iter().map(|(t, n)| (self.resolve_type(t), n)).collect();
            let returns = self.resolve_type(returns);
            self.current_return = returns.clone();
            if let Statement::Block(stmts) = body.as_ref() {
                self.captured = captured_names(stmts);
            }

            let mut environment = Environment::new();
            for (typ, name) in &args {
                environment.add_variable(
                    name.to_string(),
                    VariableDefinition {
                        name: name.to_string(),
                        mutable: false,
                        typ: typ.clone(),
                    },
                )
            }
            let mut statements = vec![];
            let mut failed = false;
            if let Statement::Block(stmts) = body.deref().clone() {
                for stmt in stmts {
                    match self.typecheck_statement(stmt, &mut environment) {
                        Ok((stmt, _)) => statements.push(stmt),
                        // Keep going to report errors in later statements too
                        Err(_) => failed = true,
                    }
                }
            }
            if failed {
                return Err(format!("errors in function {}", name));
            }
            if returns == AzulaType::Never && !always_returns(&statements) {
                self.error(format!("Function {} returns `!` but can reach the end of its body", name), &span);
                return Err("never function finishes".to_string());
            }
            if returns != AzulaType::Void && !always_returns(&statements) {
                self.error(format!("Function {} might not return a value", name), &span);
                return Err("missing return".to_string());
            }

            return Ok(Statement::Function {
                name,
                args,
                returns,
                body: Rc::new(Statement::Block(statements)),
                span,
            });
        }

        unreachable!()
    }

    fn typecheck_global_assign(&mut self, expr: Statement<'a>) -> Result<Statement<'a>, String> {
        if let Statement::Assign(mutable, name, type_annotation, value, span) = expr {
            if mutable {
                self.errors.push(AzulaError::new(
                    ErrorType::NonGlobalConstant,
                    span.start,
                    span.end,
                ));
                return Err("Non constant at top-level".to_string());
            }

            // let (expr, typ) = match self.typecheck_expression(value, &Environment::new()) {
            //     Ok((expr, value)) => (expr, value),
            //     Err(e) => return Err(e),
            // };

            let mut typ = match value.expression.clone() {
                Expression::Integer(_) => AzulaType::Int,
                Expression::Negate(inner) if matches!(inner.expression, Expression::Integer(_)) => AzulaType::Int,
                Expression::Negate(inner) if matches!(inner.expression, Expression::Float(_)) => AzulaType::Float,
                Expression::Float(_) => AzulaType::Float,
                Expression::Boolean(_) => AzulaType::Bool,
                Expression::String(_) => AzulaType::Str,
                Expression::Array(val) => {
                    AzulaType::Array(Rc::new(val[0].typed.clone()), Some(val.len()))
                }
                _ => {
                    self.errors.push(AzulaError::new(
                        ErrorType::NonGlobalConstant,
                        span.start,
                        span.end,
                    ));
                    return Err("Non constant at top-level".to_string());
                }
            };

            if type_annotation.is_some() {
                let type_annotation = self.resolve_type(type_annotation.clone().unwrap());

                // An integer constant can have any integer type (`const X: i32 = 2`)
                if typ == AzulaType::Int && is_integer_type(&type_annotation) {
                    typ = type_annotation.clone();
                }
                if type_annotation != typ {
                    self.errors.push(AzulaError::new(
                        ErrorType::MismatchedAssignTypes(
                            format!("{:?}", type_annotation),
                            format!("{:?}", typ),
                        ),
                        span.start,
                        value.span.end,
                    ));
                    return Err("mismatched types in assign".to_string());
                }
            }

            self.globals.insert(
                name.clone(),
                VariableDefinition {
                    name: name.clone(),
                    mutable,
                    typ,
                },
            );

            Ok(Statement::Assign(
                mutable,
                name,
                type_annotation,
                value,
                span,
            ))
        } else {
            unreachable!()
        }
    }

    fn typecheck_assign(
        &mut self,
        expr: Statement<'a>,
        env: &mut Environment<'a>,
    ) -> Result<(Statement<'a>, AzulaType<'a>), String> {
        if let Statement::Assign(mutable, name, type_annotation, value, span) = expr {
            let type_annotation = type_annotation.map(|t| self.resolve_type(t));
            let (expr, typ) = match &type_annotation {
                Some(annotation) => self.typecheck_expecting(value, env, annotation)?,
                None => self.typecheck_expression(value, env)?,
            };

            if type_annotation.is_some() {
                let mut type_annotation = type_annotation.clone().unwrap();

                if let AzulaType::Array(arr_typ, size) = typ.clone() {
                    if let AzulaType::Array(inner_type, inner_size) = type_annotation.clone() {
                        if arr_typ != inner_type {
                            self.errors.push(AzulaError::new(
                                ErrorType::MismatchedAssignTypes(
                                    format!("{:?}", type_annotation),
                                    format!("{:?}", typ),
                                ),
                                span.start,
                                expr.span.end,
                            ));
                            return Err("mismatched types in assign".to_string());
                        }

                        if size.is_some() && inner_size.is_some() {
                            if size.unwrap() != inner_size.unwrap() {
                                self.errors.push(AzulaError::new(
                                    ErrorType::MismatchedAssignTypes(
                                        format!("{:?}", type_annotation),
                                        format!("{:?}", typ),
                                    ),
                                    span.start,
                                    expr.span.end,
                                ));
                                return Err("mismatched types in assign".to_string());
                            }
                        }

                        type_annotation = AzulaType::Array(arr_typ, size);
                    }
                }

                let types_compatible = assignable(&type_annotation, &typ, &expr);

                if !types_compatible {
                    self.errors.push(AzulaError::new(
                        ErrorType::MismatchedAssignTypes(
                            format!("{:?}", type_annotation),
                            format!("{:?}", typ),
                        ),
                        span.start,
                        expr.span.end,
                    ));
                    return Err("mismatched types in assign".to_string());
                }
            }

            let resolved_typ = if let Some(ann) = type_annotation.clone() { ann } else { typ };

            let def = VariableDefinition { name: name.clone(), mutable, typ: resolved_typ.clone() };
            if mutable && self.captured.contains(&name) {
                // A closure may capture this variable, so it lives in a heap cell
                env.add_boxed(name.clone(), def);
                let cell_type = AzulaType::Pointer(Rc::new(resolved_typ.clone()));
                let mut value = expr;
                value.typed = resolved_typ;
                let span_of_value = value.span.clone();
                let cell = ExpressionNode {
                    expression: Expression::NewCell(Rc::new(value)),
                    typed: cell_type.clone(),
                    span: span_of_value,
                };
                return Ok((Statement::Assign(mutable, name, Some(cell_type), cell, span), AzulaType::Void));
            }
            env.add_variable(name.clone(), def);

            Ok((
                Statement::Assign(mutable, name, type_annotation, expr, span),
                AzulaType::Void,
            ))
        } else {
            unreachable!()
        }
    }

    fn typecheck_reassign(
        &mut self,
        expr: Statement<'a>,
        env: &mut Environment<'a>,
    ) -> Result<(Statement<'a>, AzulaType<'a>), String> {
        if let Statement::Reassign(var, val, span) = expr {

            let mut mutable = true;
            match var.expression {
                Expression::Identifier(ref v) => match env.variable_definitions.get(v) {
                    Some(var) => {
                        mutable = var.mutable;
                    }
                    _ => {
                        self.errors.push(AzulaError::new(
                            ErrorType::UnknownVariable(v.clone()),
                            var.span.start,
                            var.span.end,
                        ));
                        return Err(format!("unknown variable {:?}", var.expression));
                    }
                },
                Expression::ArrayAccess(..) => {}
                Expression::StructAccess(..) => {}
                Expression::Deref(..) => {}
                _ => {
                    self.error("Can't assign to this expression".to_string(), &var.span);
                    return Err("invalid assignment target".to_string());
                }
            }

            if !mutable {
                self.errors.push(AzulaError::new(
                    ErrorType::ConstantAssign,
                    var.span.start,
                    var.span.end,
                ));
                return Err("constant assign".to_string());
            }

            let (variable, var_type) = match self.typecheck_expression(var, env) {
                Ok((expr, value)) => (expr, value),
                Err(e) => return Err(e),
            };
            let (val, typ) = self.typecheck_expecting(val, env, &var_type)?;

            if !assignable(&var_type, &typ, &val) {
                self.errors.push(AzulaError::new(
                    ErrorType::MismatchedAssignTypes(
                        format!("{:?}", var_type),
                        format!("{:?}", typ),
                    ),
                    span.start,
                    val.span.end,
                ));
                return Err("mismatched types in assign".to_string());
            }

            Ok((Statement::Reassign(variable, val, span), AzulaType::Void))
        } else {
            unreachable!()
        }
    }

    fn typecheck_return(
        &mut self,
        stmt: Statement<'a>,
        env: &mut Environment<'a>,
    ) -> Result<(Statement<'a>, AzulaType<'a>), String> {
        if let Statement::Return(value, span) = stmt {
            let expected = self.current_return.clone();
            if expected == AzulaType::Infer {
                // A closure without a declared return type returns what its first `return` does
                return match value {
                    None => {
                        self.current_return = AzulaType::Void;
                        Ok((Statement::Return(None, span), AzulaType::Void))
                    }
                    Some(value) => {
                        let (value, typ) = self.typecheck_expression(value, env)?;
                        if typ == AzulaType::Void {
                            self.error("This expression has no value to return".to_string(), &value.span);
                            return Err("void return".to_string());
                        }
                        self.current_return = typ.clone();
                        Ok((Statement::Return(Some(value), span), typ))
                    }
                };
            }
            if expected == AzulaType::Never {
                self.error("A function returning `!` can't return".to_string(), &span);
                return Err("return from never function".to_string());
            }
            let value = match value {
                None => {
                    if expected != AzulaType::Void {
                        self.error(format!("Missing return value of type {}", expected.mangle()), &span);
                        return Err("missing return value".to_string());
                    }
                    return Ok((Statement::Return(None, span), AzulaType::Void));
                }
                Some(value) => value,
            };
            let (value, typ) = self.typecheck_expecting(value, env, &expected)?;
            if !assignable(&expected, &typ, &value) {
                self.errors.push(AzulaError::new(
                    ErrorType::IncorrectFunctionReturn(expected.mangle(), typ.mangle()),
                    value.span.start,
                    value.span.end,
                ));
                return Err("wrong return type".to_string());
            }
            Ok((Statement::Return(Some(value), span), typ))
        } else {
            unreachable!()
        }
    }

    fn typecheck_if(
        &mut self,
        stmt: Statement<'a>,
        env: &mut Environment<'a>,
    ) -> Result<(Statement<'a>, AzulaType<'a>), String> {
        if let Statement::If(ref expr, ref body, ref else_branch, ref span) = stmt {
            let (expr, typ) = match self.typecheck_expression(expr.clone(), env) {
                Ok((expr, value)) => (expr, value),
                Err(e) => return Err(e),
            };

            if typ != AzulaType::Bool {
                self.errors.push(AzulaError::new(
                    ErrorType::NonBoolCondition(format!("{:?}", typ)),
                    expr.span.start,
                    expr.span.end,
                ));
                return Err("Non boolean condition".to_string());
            }

            let mut stmts = vec![];
            let mut body_env = env.clone();
            for stmt in body {
                match self.typecheck_statement(stmt.clone(), &mut body_env) {
                    Ok((stmt, _)) => stmts.push(stmt),
                    Err(e) => return Err(e),
                };
            }

            let checked_else = match else_branch {
                Some(else_stmt) => {
                    match self.typecheck_statement(else_stmt.as_ref().clone(), &mut env.clone()) {
                        Ok((stmt, _)) => Some(Rc::new(stmt)),
                        Err(e) => return Err(e),
                    }
                }
                None => None,
            };

            Ok((Statement::If(expr, stmts, checked_else, span.clone()), AzulaType::Void))
        } else {
            unreachable!()
        }
    }

    fn typecheck_while(
        &mut self,
        stmt: Statement<'a>,
        env: &mut Environment<'a>,
    ) -> Result<(Statement<'a>, AzulaType<'a>), String> {
        if let Statement::While(ref expr, ref body, ref span) = stmt {
            let (expr, typ) = match self.typecheck_expression(expr.clone(), env) {
                Ok((expr, value)) => (expr, value),
                Err(e) => return Err(e),
            };

            if typ != AzulaType::Bool {
                self.errors.push(AzulaError::new(
                    ErrorType::NonBoolCondition(format!("{:?}", typ)),
                    expr.span.start,
                    expr.span.end,
                ));
                return Err("Non boolean condition".to_string());
            }

            let mut stmts = vec![];
            let mut body_env = env.clone();
            for stmt in body {
                match self.typecheck_statement(stmt.clone(), &mut body_env) {
                    Ok((stmt, _)) => stmts.push(stmt),
                    Err(e) => return Err(e),
                };
            }

            Ok((Statement::While(expr, stmts, span.clone()), AzulaType::Void))
        } else {
            unreachable!()
        }
    }

    fn typecheck_for(
        &mut self,
        stmt: Statement<'a>,
        env: &mut Environment<'a>,
    ) -> Result<(Statement<'a>, AzulaType<'a>), String> {
        if let Statement::For(ref cond, ref body, ref span) = stmt {
            let checked_cond = match cond {
                Some(expr) => {
                    let (checked, typ) = match self.typecheck_expression(expr.clone(), env) {
                        Ok(v) => v,
                        Err(e) => return Err(e),
                    };
                    if typ != AzulaType::Bool {
                        self.errors.push(AzulaError::new(
                            ErrorType::NonBoolCondition(format!("{:?}", typ)),
                            checked.span.start,
                            checked.span.end,
                        ));
                        return Err("Non boolean condition".to_string());
                    }
                    Some(checked)
                }
                None => None,
            };

            let mut stmts = vec![];
            let mut body_env = env.clone();
            for stmt in body {
                match self.typecheck_statement(stmt.clone(), &mut body_env) {
                    Ok((stmt, _)) => stmts.push(stmt),
                    Err(e) => return Err(e),
                };
            }

            Ok((Statement::For(checked_cond, stmts, span.clone()), AzulaType::Void))
        } else {
            unreachable!()
        }
    }

    /// `target op= value`, checked like `target = target op value`
    fn typecheck_compound_assign(
        &mut self,
        stmt: Statement<'a>,
        env: &mut Environment<'a>,
    ) -> Result<(Statement<'a>, AzulaType<'a>), String> {
        if let Statement::CompoundAssign(target, op, value, span) = stmt {
            match &target.expression {
                Expression::Identifier(name) => {
                    if !env.variable_definitions.get(name).map(|v| v.mutable).unwrap_or(false) {
                        self.errors.push(AzulaError::new(ErrorType::ConstantAssign, target.span.start, target.span.end));
                        return Err("constant assign".to_string());
                    }
                }
                Expression::ArrayAccess(..) | Expression::StructAccess(..) | Expression::Deref(..) => {}
                _ => {
                    self.error("Can't assign to this expression".to_string(), &target.span);
                    return Err("invalid assignment target".to_string());
                }
            }
            let original_target = target.clone();
            let combined = ExpressionNode {
                expression: Expression::Infix(Rc::new(target), op, Rc::new(value)),
                typed: AzulaType::Infer,
                span: span.clone(),
            };
            let (checked, typ) = self.typecheck_infix_expression(combined, env)?;
            if let Expression::Infix(target, op, value) = checked.expression {
                if !assignable(&target.typed, &typ, &value) {
                    self.errors.push(AzulaError::new(
                        ErrorType::MismatchedAssignTypes(target.typed.mangle(), typ.mangle()),
                        span.start,
                        span.end,
                    ));
                    return Err("mismatched types in assign".to_string());
                }
                return Ok((
                    Statement::CompoundAssign(target.as_ref().clone(), op, value.as_ref().clone(), span),
                    AzulaType::Void,
                ));
            }
            // `s += t` on strings: the checker rewrote the operator into a call
            let (checked_target, _) = self.typecheck_expression(original_target, env)?;
            return Ok((Statement::Reassign(checked_target, checked, span), AzulaType::Void));
        }
        unreachable!()
    }

    /// `for name in ...` becomes a while loop over an index:
    ///
    ///   var $items = iterable; const $length = ...; var $index = 0;
    ///   while $index < $length { var name = $items.get($index); $index = $index + 1; body }
    ///
    /// (the index advances before the body, so `continue` works). Ranges count
    /// from start to end directly.
    fn typecheck_for_in(
        &mut self,
        stmt: Statement<'a>,
        env: &mut Environment<'a>,
    ) -> Result<(Statement<'a>, AzulaType<'a>), String> {
        if let Statement::ForIn(name, iterable, range_end, inclusive, body, span) = stmt {
            let node = |expression: Expression<'a>| ExpressionNode {
                expression,
                typed: AzulaType::Infer,
                span: span.clone(),
            };
            let ident = |name: &str| node(Expression::Identifier(name.to_string()));
            let var = |mutable: bool, name: &str, value: ExpressionNode<'a>| {
                Statement::Assign(mutable, name.to_string(), None, value, span.clone())
            };
            let method = |object: ExpressionNode<'a>, method: &str, args: Vec<ExpressionNode<'a>>| {
                node(Expression::FunctionCall {
                    function: Rc::new(node(Expression::StructAccess(Rc::new(object), Rc::new(ident(method))))),
                    args,
                })
            };

            let mut stmts = vec![];
            let condition;
            let element;
            match range_end {
                Some(end) => {
                    stmts.push(var(true, "$index", iterable));
                    stmts.push(var(false, "$end", end));
                    let op = if inclusive { Operator::Lte } else { Operator::Lt };
                    condition = node(Expression::Infix(Rc::new(ident("$index")), op, Rc::new(ident("$end"))));
                    element = ident("$index");
                }
                None => {
                    let (_, typ) = self.typecheck_expression(iterable.clone(), env)?;
                    // Iterators: types with an iter() method, or with next() themselves.
                    // (Arrays, strings and Vecs are indexed directly.)
                    let type_name = match &typ {
                        AzulaType::Pointer(inner) => inner.to_string(),
                        t => t.to_string(),
                    };
                    let methods = self.namespaces.get(&type_name).map(|n| n.funcs.clone()).unwrap_or_default();
                    let is_vec = self.instances.get(&type_name).map(|(g, _)| g == "Vec").unwrap_or(false);
                    let indexed = matches!(typ, AzulaType::Array(..) | AzulaType::Str) || is_vec;
                    if !indexed && (methods.contains_key("iter") || methods.contains_key("next")) {
                        let source = if methods.contains_key("iter") { method(iterable, "iter", vec![]) } else { iterable };
                        let mut loop_body = vec![
                            var(false, "$next", method(ident("$iter"), "next", vec![])),
                            Statement::If(
                                node(Expression::Not(Rc::new(method(ident("$next"), "is_some", vec![])))),
                                vec![Statement::Break(span.clone())],
                                None,
                                span.clone(),
                            ),
                            var(true, &name, method(ident("$next"), "unwrap", vec![])),
                        ];
                        loop_body.extend(body);
                        let stmts = vec![
                            var(true, "$iter", source),
                            Statement::While(node(Expression::Boolean(true)), loop_body, span.clone()),
                        ];
                        return self.typecheck_statement(Statement::Block(stmts), env);
                    }
                    let length = match &typ {
                        AzulaType::Array(_, Some(n)) => node(Expression::Integer(*n as i64)),
                        AzulaType::Str => node(Expression::FunctionCall {
                            function: Rc::new(ident("strlen")),
                            args: vec![ident("$items")],
                        }),
                        _ => {
                            let methods = self.namespaces.get(&typ.to_string()).map(|n| n.funcs.clone());
                            let iterable_type = methods
                                .map(|m| m.contains_key("length") && m.contains_key("get"))
                                .unwrap_or(false);
                            if !iterable_type {
                                self.error(
                                    format!("Can't iterate over {}: it needs an iter() or next() method, or length() and get()", typ.mangle()),
                                    &iterable.span,
                                );
                                return Err("not iterable".to_string());
                            }
                            method(ident("$items"), "length", vec![])
                        }
                    };
                    element = match &typ {
                        AzulaType::Array(..) | AzulaType::Str => {
                            node(Expression::ArrayAccess(Rc::new(ident("$items")), Rc::new(ident("$index"))))
                        }
                        _ => method(ident("$items"), "get", vec![ident("$index")]),
                    };
                    stmts.push(var(false, "$items", iterable));
                    stmts.push(var(false, "$length", length));
                    stmts.push(var(true, "$index", node(Expression::Integer(0))));
                    condition = node(Expression::Infix(Rc::new(ident("$index")), Operator::Lt, Rc::new(ident("$length"))));
                }
            }
            let mut loop_body = vec![
                var(true, &name, element),
                Statement::Reassign(
                    ident("$index"),
                    node(Expression::Infix(
                        Rc::new(ident("$index")),
                        Operator::Add,
                        Rc::new(node(Expression::Integer(1))),
                    )),
                    span.clone(),
                ),
            ];
            loop_body.extend(body);
            stmts.push(Statement::While(condition, loop_body, span.clone()));
            return self.typecheck_statement(Statement::Block(stmts), env);
        }
        unreachable!()
    }

    fn typecheck_expression(
        &mut self,
        mut expr: ExpressionNode<'a>,
        env: &Environment<'a>,
    ) -> Result<(ExpressionNode<'a>, AzulaType<'a>), String> {
        // The expected type only applies to this node, not its sub-expressions
        let expected = self.expected.take();
        match expr.expression {
            Expression::Infix(..) => self.typecheck_infix_expression(expr, env),
            Expression::Interpolation(parts) => self.typecheck_interpolation(parts, expr.span, env),
            Expression::Tuple(items) => self.typecheck_tuple(items, expr.span, env, expected),
            Expression::Try(inner) => self.typecheck_try(inner.as_ref().clone(), expr.span, env),
            Expression::If(cond, then, otherwise) => self.typecheck_if_expression(cond, then, otherwise, expr.span, env, expected),
            Expression::Integer(_) => {
                // Character literals are chars; other integer literals are ints
                if expr.typed != AzulaType::Char {
                    expr.typed = AzulaType::Int;
                }
                let typ = expr.typed.clone();
                Ok((expr, typ))
            }
            Expression::Float(_) => {
                expr.typed = AzulaType::Float;
                Ok((expr.clone(), AzulaType::Float))
            }
            Expression::Boolean(_) => {
                expr.typed = AzulaType::Bool;
                Ok((expr.clone(), AzulaType::Bool))
            }
            Expression::String(_) => {
                expr.typed = AzulaType::Str;
                Ok((expr.clone(), AzulaType::Str))
            }
            Expression::Identifier(ref name) => {
                if name == "nil" {
                    return Ok((expr.clone(), AzulaType::Void));
                }
                if let Some(variable) = env.variable_definitions.get(name) {
                    if env.boxed.contains(name) {
                        // Read through the variable's cell
                        let typ = variable.typ.clone();
                        let cell = ExpressionNode {
                            expression: expr.expression.clone(),
                            typed: AzulaType::Pointer(Rc::new(typ.clone())),
                            span: expr.span.clone(),
                        };
                        return Ok((
                            ExpressionNode { expression: Expression::Deref(Rc::new(cell)), typed: typ.clone(), span: expr.span },
                            typ,
                        ));
                    }
                    expr.typed = variable.typ.clone().into();

                    Ok((expr.clone(), variable.typ.clone()))
                } else if self.functions.get(name.as_str()).map(|f| !f.varargs).unwrap_or(false) {
                    // A named function used as a value
                    let name = name.clone();
                    self.function_value(&name, expr.span)
                } else if let Some(variable) = self.globals.get(name) {
                    expr.typed = variable.typ.clone().into();

                    Ok((expr.clone(), variable.typ.clone()))
                } else {
                    self.errors.push(AzulaError::new(
                        ErrorType::UnknownVariable(name.clone()),
                        expr.span.start,
                        expr.span.end,
                    ));
                    return Err(format!("Unknown variable {:?}", name));
                }
            }
            Expression::FunctionCall { function, args } => {
                self.typecheck_call(function.deref().clone(), args, expr.span, env, expected)
            }
            // A generic function instance used as a value: `max::<int>`
            Expression::Turbofish(ref name, ref type_args) if self.generic_funcs.contains_key(name) => {
                let type_args = type_args.iter().map(|t| self.resolve_type(t.clone())).collect();
                let instance = self.instantiate_function(&name.clone(), type_args);
                self.function_value(&instance, expr.span)
            }
            Expression::Turbofish(..) => {
                self.error("Type arguments must be followed by a call, `::` or `{`".to_string(), &expr.span);
                Err("stray turbofish".to_string())
            }
            Expression::Closure(params, returns, body) => {
                self.typecheck_closure(params, returns, body, expr.span, env, expected)
            }
            // Already checked (produced by the typechecker)
            Expression::MakeClosure(..) | Expression::EnvCell(_) | Expression::NewCell(_) | Expression::CallClosure(..) => {
                let typ = expr.typed.clone();
                Ok((expr, typ))
            }
            Expression::Not(exp) => {
                let (node, typ) = match self.typecheck_expression(exp.deref().clone(), env) {
                    Ok((node, typ)) => (node, typ),
                    Err(e) => return Err(e),
                };

                if typ != AzulaType::Bool {
                    self.errors.push(AzulaError::new(
                        ErrorType::NonBoolCondition(format!("{:?}", typ)),
                        expr.span.start,
                        expr.span.end,
                    ));

                    return Err("Non-bool in condition".to_string());
                }

                return Ok((
                    ExpressionNode {
                        expression: Expression::Not(Rc::new(node)),
                        typed: typ,
                        span: expr.span,
                    },
                    AzulaType::Bool,
                ));
            }
            Expression::BitNot(exp) => {
                let (node, typ) = self.typecheck_expression(exp.deref().clone(), env)?;
                if !is_integer_type(&typ) {
                    self.errors.push(AzulaError::new(
                        ErrorType::NonOperatorType(format!("{:?}", typ), "~".to_string()),
                        expr.span.start,
                        expr.span.end,
                    ));
                    return Err("~ requires an integer".to_string());
                }
                Ok((
                    ExpressionNode {
                        expression: Expression::BitNot(Rc::new(node)),
                        typed: typ.clone(),
                        span: expr.span,
                    },
                    typ,
                ))
            }
            Expression::SizeOf(typ) => {
                let typ = self.resolve_type(typ);
                Ok((
                    ExpressionNode {
                        expression: Expression::SizeOf(typ),
                        typed: AzulaType::Int,
                        span: expr.span,
                    },
                    AzulaType::Int,
                ))
            }
            Expression::Negate(exp) => {
                let (node, typ) = match self.typecheck_expression(exp.deref().clone(), env) {
                    Ok((node, typ)) => (node, typ),
                    Err(e) => return Err(e),
                };

                if !is_integer_type(&typ) && !is_float_type(&typ) {
                    self.errors.push(AzulaError::new(
                        ErrorType::MismatchedTypes(format!("{:?}", typ), "Int or Float".to_string()),
                        expr.span.start,
                        expr.span.end,
                    ));
                    return Err("Negate requires numeric type".to_string());
                }

                return Ok((
                    ExpressionNode {
                        expression: Expression::Negate(Rc::new(node)),
                        typed: typ.clone(),
                        span: expr.span,
                    },
                    typ,
                ));
            }
            Expression::Deref(exp) => {
                let (node, typ) = self.typecheck_expression(exp.deref().clone(), env)?;
                let target = match &typ {
                    AzulaType::Pointer(inner) => inner.as_ref().clone(),
                    AzulaType::Str => AzulaType::Char,
                    _ => {
                        self.error(format!("Can't dereference a value of type {}", typ.mangle()), &expr.span);
                        return Err("deref of non-pointer".to_string());
                    }
                };
                Ok((
                    ExpressionNode {
                        expression: Expression::Deref(Rc::new(node)),
                        typed: target.clone(),
                        span: expr.span,
                    },
                    target,
                ))
            }
            Expression::Pointer(exp) => {
                let (node, typ) = match self.typecheck_expression(exp.deref().clone(), env) {
                    Ok((node, typ)) => (node, typ),
                    Err(e) => return Err(e),
                };

                return Ok((
                    ExpressionNode {
                        expression: Expression::Pointer(Rc::new(node)),
                        typed: AzulaType::Pointer(Rc::new(typ.clone())),
                        span: expr.span,
                    },
                    AzulaType::Pointer(Rc::new(typ)),
                ));
            }
            Expression::Array(items) => {
                let typs = items
                    .iter()
                    .map(|v| self.typecheck_expression(v.clone(), env))
                    .collect::<Vec<_>>();

                if typs.is_empty() {
                    return Ok((
                        ExpressionNode {
                            expression: Expression::Array(vec![]),
                            typed: AzulaType::Array(Rc::new(AzulaType::Infer), Some(0)),
                            span: expr.span,
                        },
                        AzulaType::Array(Rc::new(AzulaType::Infer), Some(0)),
                    ));
                }

                let first_typ = &typs[0].as_ref().unwrap().1;

                for val in typs.clone() {
                    let (node, typ) = match val {
                        Ok((node, typ)) => (node, typ),
                        Err(_) => continue,
                    };
                    if typ != first_typ.clone() {
                        self.errors.push(AzulaError::new(
                            ErrorType::MismatchedTypes(
                                format!("{:?}", typ),
                                format!("{:?}", first_typ),
                            ),
                            node.span.start,
                            node.span.end,
                        ));
                    }
                }

                Ok((
                    ExpressionNode {
                        expression: Expression::Array(
                            typs.clone()
                                .iter()
                                .map(|s| s.as_ref().unwrap().clone())
                                .map(|(node, _)| node)
                                .collect(),
                        ),
                        typed: AzulaType::Array(Rc::new(first_typ.clone()), Some(typs.len())),
                        span: expr.span,
                    },
                    AzulaType::Array(Rc::new(first_typ.clone()), Some(typs.len())),
                ))
            }
            Expression::ArrayAccess(array, index) => {
                let (array, array_typ) = self.typecheck_expression(array.deref().clone(), env)?;

                let (index, typ) = self.typecheck_expression(index.deref().clone(), env)?;

                if typ != AzulaType::Int {
                    self.errors.push(AzulaError::new(
                        ErrorType::NonIntIndex(format!("{:?}", typ)),
                        array.span.start,
                        index.span.end,
                    ));

                    return Err("Non int index".to_string());
                }

                let return_typ = if array_typ.is_indexable() {
                    match array_typ {
                        AzulaType::Array(nested, _) => nested.deref().clone(),
                        AzulaType::Str => AzulaType::Char,
                        AzulaType::Pointer(nested) => nested.deref().clone(),
                        _ => unreachable!(),
                    }
                } else {
                    self.errors.push(AzulaError::new(
                        ErrorType::NonArrayInIndex(format!("{:?}", array_typ)),
                        array.span.start,
                        array.span.end,
                    ));
                    return Err("non-array in index".to_string());
                };

                return Ok((
                    ExpressionNode {
                        expression: Expression::ArrayAccess(Rc::new(array), Rc::new(index)),
                        typed: return_typ.clone(),
                        span: expr.span,
                    },
                    return_typ,
                ));
            }
            Expression::StructInitialisation(struc, attrs) => {
                self.typecheck_struct_init(struc.deref().clone(), attrs, expr.span, env, expected)
            }
            Expression::StructAccess(struc, access) => {
                let (struc, struc_type) =
                    match self.typecheck_expression(struc.deref().clone(), env) {
                        Ok(x) => x,
                        Err(e) => return Err(e),
                    };

                let struc_name = match struc_type {
                    AzulaType::Named(s) => s,
                    AzulaType::Pointer(nested) => match nested.deref().clone() {
                        AzulaType::Named(s) => s,
                        _ => {
                            self.errors.push(AzulaError::new(
                                ErrorType::AccessNonStruct,
                                struc.span.start,
                                struc.span.end,
                            ));
                            return Err("accessing non-struct".to_string());
                        }
                    },
                    _ => {
                        self.errors.push(AzulaError::new(
                            ErrorType::AccessNonStruct,
                            struc.span.start,
                            struc.span.end,
                        ));
                        return Err("accessing non-struct".to_string());
                    }
                };

                let struct_type = if let Some(struct_type) = self.structs.get(&struc_name) {
                    struct_type
                } else {
                    self.errors.push(AzulaError::new(
                        ErrorType::UnknownStruct(struc_name),
                        struc.span.start,
                        struc.span.end,
                    ));
                    return Err("Struct not found".to_string());
                };

                let member_name = match &access.expression {
                    Expression::Identifier(s) => s,
                    _ => {
                        self.errors.push(AzulaError::new(
                            ErrorType::AccessNonStruct,
                            access.span.start,
                            access.span.end,
                        ));
                        return Err("accessing non-struct".to_string());
                    }
                };

                let typ = match struct_type
                    .attrs
                    .iter()
                    .find(|(_, name)| name.to_string() == member_name.clone())
                {
                    Some((typ, _)) => typ,
                    _ => {
                        self.errors.push(AzulaError::new(
                            ErrorType::UnknownStructMember(member_name.clone(), struc_name),
                            access.span.start,
                            access.span.end,
                        ));
                        return Err("unknown struct member".to_string());
                    }
                };

                return Ok((
                    ExpressionNode {
                        expression: Expression::StructAccess(Rc::new(struc), access),
                        typed: typ.clone(),
                        span: expr.span,
                    },
                    typ.clone(),
                ));
            }
            Expression::NamespaceAccess(ns, identifier) => {
                let member = match &identifier.expression {
                    Expression::Identifier(m) => m.clone(),
                    _ => String::new(),
                };
                let ns = Rc::new(self.concretize_namespace(ns.deref().clone(), &member, None, env, &expected)?);
                let ns_name = if let Expression::Identifier(ref ident) = ns.deref().expression {
                    ident.clone()
                } else {
                    unreachable!()
                };

                // Check if it's an enum variant access
                if let Some(variants) = self.enums.get(&ns_name).cloned() {
                    let variant_name = match &identifier.expression {
                        Expression::Identifier(v) => v.clone(),
                        _ => unreachable!(),
                    };
                    if !variants.contains(&variant_name) {
                        self.errors.push(AzulaError::new(
                            ErrorType::UnknownVariant(variant_name.clone(), ns_name.clone()),
                            identifier.span.start,
                            identifier.span.end,
                        ));
                        return Err(format!("Unknown variant {} on {}", variant_name, ns_name));
                    }
                    if self.variant_payload(&ns_name, &variant_name).map(|p| !p.is_empty()).unwrap_or(false) {
                        self.errors.push(AzulaError::new(
                            ErrorType::Custom(format!("Variant {}::{} needs a payload", ns_name, variant_name)),
                            expr.span.start,
                            expr.span.end,
                        ));
                        return Err("variant without payload".to_string());
                    }
                    let typ = AzulaType::Named(ns_name.clone());
                    return Ok((
                        ExpressionNode {
                            expression: Expression::NamespaceAccess(ns, identifier),
                            typed: typ.clone(),
                            span: expr.span,
                        },
                        typ,
                    ));
                }

                let namespace = self.namespaces.get(&ns_name);
                let namespace = match namespace {
                    Some(f) => f.clone(),
                    None => return Err("namespace".to_string()),
                };

                let mut ns_node = ns.deref().clone();
                ns_node.typed = AzulaType::Named(namespace.name.clone());

                return Ok((
                    ExpressionNode {
                        expression: Expression::NamespaceAccess(Rc::new(ns_node), identifier),
                        typed: AzulaType::Infer,
                        span: expr.span,
                    },
                    AzulaType::Infer,
                ));
            }
            Expression::Match(scrutinee, arms) => {
                self.typecheck_match(scrutinee, arms, expr.span, env, expected)
            }
            Expression::Cast(_, _) => self.typecheck_cast_expression(expr, env),
            Expression::Null => Ok((
                ExpressionNode { expression: Expression::Null, typed: AzulaType::Str, span: expr.span },
                AzulaType::Str,
            )),
            Expression::Alloc(inner) => {
                let (inner_node, inner_typ) = self.typecheck_expression(inner.as_ref().clone(), env)?;
                let ptr_type = AzulaType::Pointer(Rc::new(inner_typ));
                Ok((
                    ExpressionNode {
                        expression: Expression::Alloc(Rc::new(inner_node)),
                        typed: ptr_type.clone(),
                        span: expr.span,
                    },
                    ptr_type,
                ))
            }
            Expression::Block(stmts, final_expr) => {
                let mut new_env = env.clone();
                let mut new_stmts = vec![];
                for stmt in stmts {
                    match self.typecheck_statement(stmt, &mut new_env) {
                        Ok((s, _)) => new_stmts.push(s),
                        Err(e) => return Err(e),
                    }
                }
                match final_expr {
                    Some(fe) => {
                        let (fe_node, fe_type) = match &expected {
                            Some(expected) => self.typecheck_expecting(fe.as_ref().clone(), &new_env, expected)?,
                            None => self.typecheck_expression(fe.as_ref().clone(), &new_env)?,
                        };
                        Ok((
                            ExpressionNode {
                                expression: Expression::Block(new_stmts, Some(Rc::new(fe_node))),
                                typed: fe_type.clone(),
                                span: expr.span,
                            },
                            fe_type,
                        ))
                    }
                    None => {
                        // A block that always leaves (through `return`, `break`,
                        // `continue` or a `!` call) never gives a value, so it
                        // fits anywhere (such as a match arm)
                        let typ = if block_diverges(&new_stmts) { AzulaType::Never } else { AzulaType::Void };
                        Ok((
                            ExpressionNode {
                                expression: Expression::Block(new_stmts, None),
                                typed: typ.clone(),
                                span: expr.span,
                            },
                            typ,
                        ))
                    }
                }
            }
        }
    }

    /// Whether the pattern `rows` (each matching values of `types`) together
    /// match every value
    fn patterns_exhaustive(&self, rows: Vec<Vec<MatchPattern<'a>>>, types: &[AzulaType<'a>]) -> bool {
        let is_wild = |p: &MatchPattern| matches!(p, MatchPattern::Wildcard | MatchPattern::Binding(_));
        if types.is_empty() {
            return !rows.is_empty();
        }
        let (first, rest) = (&types[0], &types[1..]);
        if let Some(items) = self.tuple_items(first) {
            // Expand the tuple's elements into columns
            let expanded = rows
                .into_iter()
                .map(|row| {
                    let mut new_row = match &row[0] {
                        MatchPattern::Tuple(inner) => inner.clone(),
                        _ => vec![MatchPattern::Wildcard; items.len()],
                    };
                    new_row.extend(row[1..].iter().cloned());
                    new_row
                })
                .collect();
            let mut new_types = items.clone();
            new_types.extend(rest.iter().cloned());
            return self.patterns_exhaustive(expanded, &new_types);
        }
        if let Some(variants) = self.enums.get(&first.to_string()) {
            // Every variant must be matched by the rows that allow it
            return variants.iter().all(|variant| {
                let remaining = rows
                    .iter()
                    .filter(|row| match &row[0] {
                        MatchPattern::Variant(_, v) | MatchPattern::Destructure(_, v, _) => v == variant,
                        p => is_wild(p),
                    })
                    .map(|row| row[1..].to_vec())
                    .collect();
                self.patterns_exhaustive(remaining, rest)
            });
        }
        // Integers and other values can only be covered by wildcards
        let remaining = rows.iter().filter(|row| is_wild(&row[0])).map(|row| row[1..].to_vec()).collect();
        self.patterns_exhaustive(remaining, rest)
    }

    /// Check a tuple pattern against the tuple's element `types`, binding its
    /// names in `env`. Returns the pattern with enum names resolved, and whether
    /// it matches every tuple.
    fn check_tuple_pattern(
        &mut self,
        items: Vec<MatchPattern<'a>>,
        types: Vec<AzulaType<'a>>,
        env: &mut Environment<'a>,
        span: &Span,
    ) -> Result<(MatchPattern<'a>, bool), String> {
        if items.len() != types.len() {
            self.error(format!("This pattern has {} elements, but the tuple has {}", items.len(), types.len()), span);
            return Err("wrong tuple pattern arity".to_string());
        }
        let mut irrefutable = true;
        let mut resolved = vec![];
        for (item, typ) in items.into_iter().zip(types) {
            let item = match item {
                MatchPattern::Wildcard => MatchPattern::Wildcard,
                MatchPattern::Binding(name) => {
                    env.add_variable(
                        name.to_string(),
                        VariableDefinition { name: name.to_string(), mutable: false, typ: typ.clone() },
                    );
                    MatchPattern::Binding(name)
                }
                MatchPattern::Integer(n) => {
                    if !is_integer_type(&typ) {
                        self.error(format!("An integer pattern can't match a value of type {}", typ.mangle()), span);
                        return Err("bad pattern".to_string());
                    }
                    irrefutable = false;
                    MatchPattern::Integer(n)
                }
                MatchPattern::Variant(pat_enum, variant) => {
                    let name = typ.to_string();
                    let generic = self.instances.get(&name).map(|(g, _)| g.clone());
                    let is_enum = self.enums.contains_key(&name);
                    if !is_enum || (pat_enum != name.as_str() && generic.as_deref() != Some(pat_enum)) {
                        self.error(format!("The pattern {}::{} can't match a value of type {}", pat_enum, variant, typ.mangle()), span);
                        return Err("bad pattern".to_string());
                    }
                    if !self.enums[&name].contains(&variant.to_string()) {
                        self.errors.push(AzulaError::new(
                            ErrorType::UnknownVariant(variant.to_string(), name.clone()),
                            span.start,
                            span.end,
                        ));
                        return Err("unknown variant".to_string());
                    }
                    irrefutable = false;
                    MatchPattern::Variant(leak(name), variant)
                }
                MatchPattern::Destructure(..) => {
                    self.error("Variant payloads can't be destructured inside a tuple pattern; match on the element instead".to_string(), span);
                    return Err("bad pattern".to_string());
                }
                MatchPattern::Or(_) | MatchPattern::Guarded(..) => {
                    self.error("`|` patterns can't be used inside a tuple pattern".to_string(), span);
                    return Err("bad pattern".to_string());
                }
                MatchPattern::Tuple(inner) => match self.tuple_items(&typ) {
                    Some(inner_types) => {
                        let (pattern, inner_irrefutable) = self.check_tuple_pattern(inner, inner_types, env, span)?;
                        irrefutable &= inner_irrefutable;
                        pattern
                    }
                    None => {
                        self.error(format!("A tuple pattern can't match a value of type {}", typ.mangle()), span);
                        return Err("bad pattern".to_string());
                    }
                },
            };
            resolved.push(item);
        }
        Ok((MatchPattern::Tuple(resolved), irrefutable))
    }

    fn typecheck_match(
        &mut self,
        scrutinee: Rc<ExpressionNode<'a>>,
        arms: Vec<(MatchPattern<'a>, ExpressionNode<'a>)>,
        span: Span,
        env: &Environment<'a>,
        expected: Option<AzulaType<'a>>,
    ) -> Result<(ExpressionNode<'a>, AzulaType<'a>), String> {
        let (scrut_node, scrut_type) = match self.typecheck_expression(scrutinee.deref().clone(), env) {
            Ok(x) => x,
            Err(e) => return Err(e),
        };

        // Dispatch based on scrutinee type: enum match or integer match
        let is_integer_match = is_integer_type(&scrut_type);

        let tuple_types = self.tuple_items(&scrut_type);
        let (enum_name, variants) = if is_integer_match {
            (String::new(), vec![])
        } else if tuple_types.is_some() {
            (scrut_type.to_string(), vec![])
        } else {
            let name = match &scrut_type {
                AzulaType::Named(n) => n.clone(),
                _ => {
                    self.errors.push(AzulaError::new(
                        ErrorType::MatchOnNonEnum(format!("{:?}", scrut_type)),
                        scrut_node.span.start,
                        scrut_node.span.end,
                    ));
                    return Err("match on non-enum".to_string());
                }
            };
            let vars = match self.enums.get(&name).cloned() {
                Some(v) => v,
                None => {
                    self.errors.push(AzulaError::new(
                        ErrorType::UnknownEnum(name.clone()),
                        scrut_node.span.start,
                        scrut_node.span.end,
                    ));
                    return Err(format!("Unknown enum {}", name));
                }
            };
            (name, vars)
        };

        let mut covered: Vec<String> = vec![];
        let mut has_wildcard = false;
        let mut result_type: Option<AzulaType<'a>> = None;
        let mut new_arms = vec![];

        for (pattern, body) in arms {
            // A guarded arm doesn't count towards covering the cases
            let (pattern, guard) = match pattern {
                MatchPattern::Guarded(p, g) => (p.as_ref().clone(), Some(g.as_ref().clone())),
                p => (p, None),
            };
            let mut arm_covered: Vec<String> = vec![];
            let mut arm_wildcard = false;
            if tuple_types.is_some() != matches!(pattern, MatchPattern::Tuple(_))
                && !matches!(pattern, MatchPattern::Wildcard | MatchPattern::Binding(_))
            {
                let message = if tuple_types.is_some() {
                    format!("Patterns matching the tuple {} must be tuples like (a, _)", scrut_type.mangle())
                } else {
                    format!("A tuple pattern can't match a value of type {}", scrut_type.mangle())
                };
                self.error(message, &body.span);
                return Err("bad tuple pattern".to_string());
            }
            let alternatives = match &pattern {
                MatchPattern::Or(alts) => alts.clone(),
                other => vec![other.clone()],
            };
            for alternative in &alternatives {
            if matches!(pattern, MatchPattern::Or(_))
                && (matches!(alternative, MatchPattern::Tuple(_) | MatchPattern::Binding(_) | MatchPattern::Or(_))
                    || matches!(alternative, MatchPattern::Destructure(_, _, b) if b.iter().any(Option::is_some)))
            {
                self.error("The alternatives of a `|` pattern can't bind names".to_string(), &body.span);
                return Err("binding in or-pattern".to_string());
            }
            match alternative {
                MatchPattern::Wildcard | MatchPattern::Binding(_) => {
                    arm_wildcard = true;
                }
                MatchPattern::Tuple(_) | MatchPattern::Or(_) | MatchPattern::Guarded(..) => {}
                MatchPattern::Integer(_) => {
                    if !is_integer_match {
                        self.errors.push(AzulaError::new(
                            ErrorType::MatchOnNonEnum(format!("{:?}", scrut_type)),
                            body.span.start,
                            body.span.end,
                        ));
                        return Err("integer pattern on non-integer scrutinee".to_string());
                    }
                }
                MatchPattern::Variant(pat_enum, variant) | MatchPattern::Destructure(pat_enum, variant, _) => {
                    // `Option::Some(x)` matches a value of an instance such as `Option<int>`
                    let generic_of_instance = self.instances.get(&enum_name).map(|(g, _)| g.clone());
                    if *pat_enum != enum_name.as_str() && generic_of_instance.as_deref() != Some(*pat_enum) {
                        self.errors.push(AzulaError::new(
                            ErrorType::UnknownEnum(pat_enum.to_string()),
                            body.span.start,
                            body.span.end,
                        ));
                        return Err(format!("Unknown enum {}", pat_enum));
                    }
                    if !variants.contains(&variant.to_string()) {
                        self.errors.push(AzulaError::new(
                            ErrorType::UnknownVariant(variant.to_string(), enum_name.clone()),
                            body.span.start,
                            body.span.end,
                        ));
                        return Err(format!("Unknown variant {}", variant));
                    }
                    arm_covered.push(variant.to_string());
                }
            }
            }

            // Bind the payload fields of a destructured variant
            let mut arm_env = env.clone();
            let pattern = match (pattern, &tuple_types) {
                (MatchPattern::Tuple(items), Some(types)) => {
                    let (pattern, irrefutable) =
                        self.check_tuple_pattern(items, types.clone(), &mut arm_env, &body.span)?;
                    if irrefutable {
                        arm_wildcard = true;
                    }
                    pattern
                }
                (pattern, _) => pattern,
            };
            // A name matching anything binds the whole value
            if let MatchPattern::Binding(name) = &pattern {
                arm_env.add_variable(
                    name.to_string(),
                    VariableDefinition { name: name.to_string(), mutable: false, typ: scrut_type.clone() },
                );
            }
            if let MatchPattern::Destructure(_, variant, bindings) = &pattern {
                let payload = self.variant_payload(&enum_name, variant).unwrap_or_default();
                if payload.len() != bindings.len() {
                    self.errors.push(AzulaError::new(
                        ErrorType::Custom(format!(
                            "Variant {}::{} has {} fields, pattern binds {}",
                            enum_name,
                            variant,
                            payload.len(),
                            bindings.len()
                        )),
                        body.span.start,
                        body.span.end,
                    ));
                    return Err("wrong binding count".to_string());
                }
                for (binding, typ) in bindings.iter().zip(payload) {
                    if let Some(name) = binding {
                        arm_env.add_variable(
                            name.to_string(),
                            VariableDefinition {
                                name: name.to_string(),
                                mutable: false,
                                typ: self.resolve_type(typ),
                            },
                        );
                    }
                }
            }

            let guard = match guard {
                Some(g) => {
                    let (g, t) = self.typecheck_expression(g, &arm_env)?;
                    if t != AzulaType::Bool {
                        self.error(format!("A match guard must be a bool, not {}", t.mangle()), &g.span);
                        return Err("bad guard".to_string());
                    }
                    Some(g)
                }
                None => {
                    covered.extend(arm_covered);
                    has_wildcard |= arm_wildcard;
                    None
                }
            };

            let (body_node, body_type) = match &expected {
                Some(expected) => self.typecheck_expecting(body, &arm_env, expected)?,
                None => self.typecheck_expression(body, &arm_env)?,
            };

            // Arms that always return don't produce a value, so don't affect the
            // match's type. Arms that disagree make the match a statement (Void).
            let diverges = body_type == AzulaType::Never
                || match &body_node.expression {
                    Expression::Block(stmts, None) => always_returns(stmts),
                    _ => false,
                };
            if !diverges {
                match result_type.clone() {
                    Some(rt) if rt != body_type => result_type = Some(AzulaType::Void),
                    Some(_) => {}
                    None => result_type = Some(body_type),
                }
            }

            let resolve = |p: MatchPattern<'a>| match p {
                MatchPattern::Variant(_, variant) => MatchPattern::Variant(leak(enum_name.clone()), variant),
                MatchPattern::Destructure(_, variant, bindings) => {
                    MatchPattern::Destructure(leak(enum_name.clone()), variant, bindings)
                }
                other => other,
            };
            let pattern = match pattern {
                MatchPattern::Or(alts) => MatchPattern::Or(alts.into_iter().map(resolve).collect()),
                other => resolve(other),
            };
            let pattern = match guard {
                Some(g) => MatchPattern::Guarded(Rc::new(pattern), Rc::new(g)),
                None => pattern,
            };
            new_arms.push((pattern, body_node));
        }

        // Exhaustiveness: enum match requires all variants covered or wildcard;
        // integer and tuple matches just require a wildcard (or a tuple pattern
        // matching anything).
        if !has_wildcard && tuple_types.is_some() {
            let rows: Vec<Vec<MatchPattern<'a>>> = new_arms
                .iter()
                .filter(|(p, _)| !matches!(p, MatchPattern::Guarded(..)))
                .map(|(p, _)| vec![p.clone()])
                .collect();
            if !self.patterns_exhaustive(rows, &[scrut_type.clone()]) {
                self.error(
                    "This match isn't exhaustive: some tuples match none of the arms (add a `_` arm?)".to_string(),
                    &span,
                );
                return Err("non-exhaustive match".to_string());
            }
        }
        if !has_wildcard && !is_integer_match {
            let uncovered: Vec<_> = variants.iter().filter(|v| !covered.contains(v)).collect();
            if !uncovered.is_empty() {
                self.errors.push(AzulaError::new(
                    ErrorType::NonExhaustiveMatch(enum_name.clone()),
                    span.start,
                    span.end,
                ));
                return Err("non-exhaustive match".to_string());
            }
        }

        let typ = result_type.unwrap_or(AzulaType::Void);
        Ok((
            ExpressionNode {
                expression: Expression::Match(Rc::new(scrut_node), new_arms),
                typed: typ.clone(),
                span,
            },
            typ,
        ))
    }

    fn typecheck_call(
        &mut self,
        function: ExpressionNode<'a>,
        args: Vec<ExpressionNode<'a>>,
        span: Span,
        env: &Environment<'a>,
        expected: Option<AzulaType<'a>>,
    ) -> Result<(ExpressionNode<'a>, AzulaType<'a>), String> {
        // Calls of function values: variables, fields of function type, and
        // other expressions
        let calls_value = match &function.expression {
            Expression::Identifier(name) => env.variable_definitions.contains_key(name),
            Expression::StructAccess(obj, member) => match &member.expression {
                Expression::Identifier(field) => self.is_function_field(obj, field, env),
                _ => false,
            },
            Expression::NamespaceAccess(..) | Expression::Turbofish(..) => false,
            _ => true,
        };
        if calls_value {
            let (callee, _) = self.typecheck_expression(function, env)?;
            return self.typecheck_closure_call(callee, args, span, env);
        }

        self.last_span = span.clone();
        let function = self.concretize_callee(function, &args, env, &expected)?;

        // Enum variant construction: `Enum::Variant(values...)`
        if let Some((enum_name, variant_name)) = self.as_variant(&function) {
            let payload = self.variant_payload(&enum_name, &variant_name).unwrap_or_default();
            if payload.len() != args.len() {
                self.error(
                    format!(
                        "Variant {}::{} takes {} values, got {}",
                        enum_name,
                        variant_name,
                        payload.len(),
                        args.len()
                    ),
                    &span,
                );
                return Err("wrong payload count".to_string());
            }
            let mut new_args = vec![];
            for (arg, expected) in args.into_iter().zip(payload.iter()) {
                let (arg, typ) = self.typecheck_expecting(arg, env, expected)?;
                if !assignable(expected, &typ, &arg) {
                    self.errors.push(AzulaError::new(
                        ErrorType::MismatchedTypes(format!("{:?}", expected), format!("{:?}", typ)),
                        arg.span.start,
                        arg.span.end,
                    ));
                    return Err("mismatched payload".to_string());
                }
                new_args.push(arg);
            }
            let typ = AzulaType::Named(enum_name);
            return Ok((
                ExpressionNode {
                    expression: Expression::FunctionCall { function: Rc::new(function), args: new_args },
                    typed: typ.clone(),
                    span,
                },
                typ,
            ));
        }

        let func = match self.resolve_function(self.functions.clone(), function.clone(), env) {
            Ok(f) => f,
            Err(e) => {
                self.errors.push(AzulaError::new(
                    ErrorType::FunctionNotFound(e),
                    function.span.start,
                    function.span.end,
                ));
                return Err(format!("Function not found {:?}", function));
            }
        };

        // Methods called as `value.method(...)` receive `value` as their first argument
        let is_method = matches!(function.expression, Expression::StructAccess(..));
        if is_method && func.args.first().map(|(_, name)| name != "self").unwrap_or(true) {
            self.error(
                format!("`{}` is a static function: call it as Type::{}()", func.name, func.name),
                &span,
            );
            return Err("static function called as a method".to_string());
        }
        if let Expression::NamespaceAccess(ns, _) = &function.expression {
            let is_type = matches!(&ns.expression, Expression::Identifier(n) if self.namespaces.contains_key(n.as_str()));
            if is_type && func.args.first().map(|(_, name)| name == "self").unwrap_or(false) {
                self.error(format!("`{}` is a method: call it on a value, like value.{}()", func.name, func.name), &span);
                return Err("method called as a static function".to_string());
            }
        }
        let function = self.typecheck_function_def(function, env);
        let params: Vec<AzulaType<'a>> = func
            .args
            .iter()
            .skip(if is_method { 1 } else { 0 })
            .map(|(t, _)| t.clone())
            .collect();

        if (!func.varargs && args.len() != params.len()) || args.len() < params.len() {
            self.error(
                format!("{} takes {} arguments, got {}", func.name, params.len(), args.len()),
                &span,
            );
            return Err("wrong argument count".to_string());
        }

        let mut new_args = vec![];
        for (i, arg) in args.into_iter().enumerate() {
            let (arg, typ) = match params.get(i) {
                Some(param) => {
                    let (arg, typ) = self.typecheck_expecting(arg, env, param)?;
                    if !assignable(param, &typ, &arg) {
                        self.errors.push(AzulaError::new(
                            ErrorType::MismatchedTypes(format!("{:?}", param), format!("{:?}", typ)),
                            arg.span.start,
                            arg.span.end,
                        ));
                        return Err("mismatched argument".to_string());
                    }
                    (arg, typ)
                }
                None => self.typecheck_expression(arg, env)?,
            };
            let _ = typ;
            new_args.push(arg);
        }

        // Check literal printf-style format strings against the arguments
        if let Some(index) = format_argument(&func.name) {
            if let Some(Expression::String(format)) = new_args.get(index).map(|a| &a.expression) {
                let types: Vec<AzulaType<'a>> = new_args[index + 1..].iter().map(|a| a.typed.clone()).collect();
                if let Some(message) = check_format(&func.name, format, &types, index + 1) {
                    self.error(message, &span);
                    return Err("bad format".to_string());
                }
            }
        }

        let return_type = func.returns;
        Ok((
            ExpressionNode {
                expression: Expression::FunctionCall {
                    function: Rc::new(function),
                    args: new_args,
                },
                typed: return_type.clone(),
                span,
            },
            return_type,
        ))
    }

    /// Rewrite references to generic functions and types in a callee into the
    /// names of concrete instances, inferring type arguments where needed.
    fn concretize_callee(
        &mut self,
        function: ExpressionNode<'a>,
        args: &[ExpressionNode<'a>],
        env: &Environment<'a>,
        expected: &Option<AzulaType<'a>>,
    ) -> Result<ExpressionNode<'a>, String> {
        match function.expression.clone() {
            Expression::Identifier(name) if self.generic_funcs.contains_key(&name) => {
                let (params, def) = self.generic_funcs[&name].clone();
                let (mut patterns, returns) = match def {
                    Statement::Function { args, returns, .. } => {
                        (args.into_iter().map(|(t, _)| t).collect::<Vec<_>>(), returns)
                    }
                    _ => unreachable!(),
                };
                let (patterns_known, concrete) = self.types_for_inference(&patterns, args, env);
                let mut patterns_known = patterns_known;
                let mut concrete = concrete;
                self.infer_from_closures(&params, &patterns, args, &mut patterns_known, &mut concrete, env);
                let mut patterns = patterns_known;
                if let Some(expected) = expected {
                    patterns.push(returns);
                    concrete.push(expected.clone());
                }
                let type_args = self
                    .infer_type_args(&name, &params, &None, &patterns, &concrete, &function.span)
                    .ok_or("cannot infer")?;
                let instance = self.instantiate_function(&name, type_args);
                Ok(ExpressionNode { expression: Expression::Identifier(instance), ..function })
            }
            Expression::Turbofish(name, type_args) if self.generic_funcs.contains_key(&name) => {
                let type_args = type_args.into_iter().map(|t| self.resolve_type(t)).collect();
                let instance = self.instantiate_function(&name, type_args);
                Ok(ExpressionNode { expression: Expression::Identifier(instance), ..function })
            }
            Expression::NamespaceAccess(ns, member) => {
                let (member_name, type_args) = match &member.expression {
                    Expression::Identifier(m) => (m.clone(), None),
                    Expression::Turbofish(m, t) => (m.clone(), Some(t.clone())),
                    _ => return Ok(function),
                };
                let ns = self.concretize_namespace(ns.deref().clone(), &member_name, Some(args), env, expected)?;
                // A static generic method
                let member = match &ns.expression {
                    Expression::Identifier(type_name) => {
                        match self.concretize_generic_method(type_name, &member_name, type_args, false, args, env, expected, &member.span)? {
                            Some(instance) => Rc::new(ExpressionNode { expression: Expression::Identifier(instance), ..member.as_ref().clone() }),
                            None => member,
                        }
                    }
                    _ => member,
                };
                Ok(ExpressionNode {
                    expression: Expression::NamespaceAccess(Rc::new(ns), member),
                    ..function
                })
            }
            Expression::StructAccess(receiver, member) => {
                let (member_name, type_args) = match &member.expression {
                    Expression::Identifier(m) => (m.clone(), None),
                    Expression::Turbofish(m, t) => (m.clone(), Some(t.clone())),
                    _ => return Ok(function),
                };
                // The receiver's type decides which methods there are
                let error_count = self.errors.len();
                let receiver_type = match self.typecheck_expression(receiver.as_ref().clone(), env) {
                    Ok((_, t)) => t,
                    Err(_) => {
                        self.errors.truncate(error_count);
                        return Ok(function);
                    }
                };
                let type_name = match &receiver_type {
                    AzulaType::Pointer(inner) => inner.to_string(),
                    t => t.to_string(),
                };
                match self.concretize_generic_method(&type_name, &member_name, type_args, true, args, env, expected, &member.span)? {
                    Some(instance) => Ok(ExpressionNode {
                        expression: Expression::StructAccess(
                            receiver,
                            Rc::new(ExpressionNode { expression: Expression::Identifier(instance), ..member.as_ref().clone() }),
                        ),
                        ..function
                    }),
                    None => Ok(function),
                }
            }
            _ => Ok(function),
        }
    }

    /// If `method` is a generic method of type `type_name`, instantiate it (with
    /// `type_args`, or type arguments inferred from the call) and return the
    /// instance's name, such as `map<int>`.
    #[allow(clippy::too_many_arguments)]
    fn concretize_generic_method(
        &mut self,
        type_name: &str,
        method: &str,
        type_args: Option<Vec<AzulaType<'a>>>,
        is_call_on_value: bool,
        args: &[ExpressionNode<'a>],
        env: &Environment<'a>,
        expected: &Option<AzulaType<'a>>,
        span: &Span,
    ) -> Result<Option<String>, String> {
        // For an instance such as `Vec<int>`, look in the generic `Vec`
        let (base, base_args) = match self.instances.get(type_name) {
            Some((generic, args)) if generic != TUPLE => (generic.clone(), args.clone()),
            _ => (type_name.to_string(), vec![]),
        };
        let found = self
            .generic_methods
            .get(&base)
            .and_then(|methods| {
                methods.iter().find(|(_, _, f)| matches!(f, Statement::Function { name, .. } if *name == method))
            })
            .cloned();
        let (impl_params, params, func) = match found {
            Some(found) => found,
            None => {
                if type_args.is_some() {
                    self.error(format!("{} has no generic method {}", type_name, method), span);
                    return Err("not a generic method".to_string());
                }
                return Ok(None);
            }
        };
        let impl_map: Substitution<'a> = impl_params.iter().cloned().zip(base_args.iter().cloned()).collect();
        let func = subst_stmt(&func, &impl_map);
        let type_args = match type_args {
            Some(t) => t.into_iter().map(|t| self.resolve_type(t)).collect(),
            None => {
                let (fargs, returns) = match &func {
                    Statement::Function { args, returns, .. } => (args.clone(), returns.clone()),
                    _ => unreachable!(),
                };
                let takes_self = fargs.first().map(|(_, n)| *n == "self").unwrap_or(false);
                let patterns: Vec<_> = fargs
                    .iter()
                    .skip(if takes_self && is_call_on_value { 1 } else { 0 })
                    .map(|(t, _)| t.clone())
                    .collect();
                let all_patterns = patterns;
                let (mut patterns, mut concrete) = self.types_for_inference(&all_patterns, args, env);
                self.infer_from_closures(&params, &all_patterns, args, &mut patterns, &mut concrete, env);
                if let Some(expected) = expected {
                    patterns.push(returns);
                    concrete.push(expected.clone());
                }
                self.infer_type_args(method, &params, &None, &patterns, &concrete, span).ok_or("cannot infer")?
            }
        };
        if type_args.len() != params.len() {
            self.error(format!("{} expects {} type arguments, got {}", method, params.len(), type_args.len()), span);
            return Err("wrong type argument count".to_string());
        }
        let instance = AzulaType::Generic(method.to_string(), type_args.clone()).mangle();
        let key = format!("{}_{}", type_name, instance);
        if !self.instantiated_functions.contains(&key) {
            self.instantiated_functions.insert(key);
            let map: Substitution<'a> = params.iter().cloned().zip(type_args).collect();
            if let Statement::Function { args: fargs, returns, body, span, .. } = subst_stmt(&func, &map) {
                let instance_name = leak(instance.clone());
                let def = self.signature(instance_name, &fargs, &returns);
                let namespace = self.namespaces.entry(type_name.to_string()).or_insert(Namespace {
                    name: type_name.to_string(),
                    funcs: HashMap::new(),
                });
                namespace.funcs.insert(instance_name, def);
                self.pending.push((
                    Some(AzulaType::Named(type_name.to_string())),
                    Statement::Function { name: instance_name, args: fargs, returns, body, span },
                ));
            }
        }
        Ok(Some(instance))
    }

    /// Turn the namespace part of `Name::member` into a concrete type name when
    /// `Name` is generic, using explicit type arguments or inference.
    fn concretize_namespace(
        &mut self,
        ns: ExpressionNode<'a>,
        member: &str,
        args: Option<&[ExpressionNode<'a>]>,
        env: &Environment<'a>,
        expected: &Option<AzulaType<'a>>,
    ) -> Result<ExpressionNode<'a>, String> {
        let instance = match ns.expression.clone() {
            Expression::Turbofish(name, type_args) => {
                let type_args = type_args.into_iter().map(|t| self.resolve_type(t)).collect();
                self.resolve_type(AzulaType::Generic(name, type_args))
            }
            Expression::Identifier(name)
                if self.generic_structs.contains_key(&name) || self.generic_enums.contains_key(&name) =>
            {
                // What the member's parameters look like, to match against the arguments
                let mut params: Vec<String> = vec![];
                let mut patterns: Vec<AzulaType<'a>> = vec![];
                if let Some((enum_params, variants, payloads)) = self.generic_enums.get(&name).cloned() {
                    params = enum_params;
                    if let Some(index) = variants.iter().position(|v| *v == member) {
                        patterns = payloads[index].clone();
                    }
                } else {
                    params = self.generic_structs[&name].0.clone();
                    for (impl_params, func) in self.generic_impls.get(&name).cloned().unwrap_or_default() {
                        if let Statement::Function { name: fname, args: fargs, returns, .. } = func {
                            if fname == member {
                                // Rename the impl's parameters to the struct's
                                let map: Substitution<'a> = impl_params
                                    .iter()
                                    .cloned()
                                    .zip(params.iter().map(|p| AzulaType::Named(p.clone())))
                                    .collect();
                                patterns = fargs.iter().map(|(t, _)| subst_type(t, &map)).collect();
                                if let Some(expected) = expected {
                                    // matched against the expected type below
                                    let _ = (returns, expected);
                                }
                            }
                        }
                    }
                }
                let (patterns, concrete) = self.types_for_inference(&patterns, args.unwrap_or(&[]), env);
                let type_args = self
                    .infer_type_args(&name, &params, expected, &patterns, &concrete, &ns.span)
                    .ok_or("cannot infer")?;
                self.instantiate_type(&name, type_args)
            }
            _ => return Ok(ns),
        };
        Ok(ExpressionNode {
            expression: Expression::Identifier(instance.to_string()),
            typed: AzulaType::Infer,
            span: ns.span,
        })
    }

    fn typecheck_struct_init(
        &mut self,
        struc: ExpressionNode<'a>,
        fields: Vec<(&'a str, ExpressionNode<'a>)>,
        span: Span,
        env: &Environment<'a>,
        expected: Option<AzulaType<'a>>,
    ) -> Result<(ExpressionNode<'a>, AzulaType<'a>), String> {
        // Work out which (possibly generic) struct is being built
        let name = match struc.expression.clone() {
            Expression::Identifier(name) if self.generic_structs.contains_key(&name) => {
                let (params, attrs) = self.generic_structs[&name].clone();
                let mut field_patterns = vec![];
                let mut values = vec![];
                for (field, value) in &fields {
                    if let Some((typ, _)) = attrs.iter().find(|(_, n)| n == field) {
                        field_patterns.push(typ.clone());
                        values.push(value.clone());
                    }
                }
                let (patterns, concrete) = self.types_for_inference(&field_patterns, &values, env);
                let args = self
                    .infer_type_args(&name, &params, &expected, &patterns, &concrete, &span)
                    .ok_or("cannot infer")?;
                self.instantiate_type(&name, args).to_string()
            }
            Expression::Turbofish(name, args) => {
                let args = args.into_iter().map(|t| self.resolve_type(t)).collect();
                self.instantiate_type(&name, args).to_string()
            }
            Expression::Identifier(name) => name,
            _ => unreachable!(),
        };

        let attrs = match self.structs.get(&name) {
            Some(def) => def.attrs.clone(),
            None => {
                self.errors.push(AzulaError::new(ErrorType::UnknownStruct(name), span.start, span.end));
                return Err("Struct not found".to_string());
            }
        };

        for (field, value) in &fields {
            if !attrs.iter().any(|(_, n)| n == field) {
                self.errors.push(AzulaError::new(
                    ErrorType::UnknownStructMember(field.to_string(), name.clone()),
                    value.span.start,
                    value.span.end,
                ));
                return Err("unknown struct member".to_string());
            }
        }

        // Check the fields, putting them in declaration order
        let mut checked = vec![];
        for (typ, attr) in &attrs {
            let value = match fields.iter().find(|(n, _)| n == attr) {
                Some((_, value)) => value.clone(),
                None => {
                    self.error(format!("Missing field {} in {}", attr, name), &span);
                    return Err("missing field".to_string());
                }
            };
            let (value, value_typ) = self.typecheck_expecting(value, env, typ)?;
            if !assignable(typ, &value_typ, &value) {
                self.errors.push(AzulaError::new(
                    ErrorType::MismatchedTypes(format!("{:?}", typ), format!("{:?}", value_typ)),
                    value.span.start,
                    value.span.end,
                ));
                return Err("mismatched field".to_string());
            }
            checked.push((*attr, value));
        }

        let typ = AzulaType::Named(name.clone());
        let struc = ExpressionNode {
            expression: Expression::Identifier(name),
            typed: typ.clone(),
            span: struc.span,
        };
        Ok((
            ExpressionNode {
                expression: Expression::StructInitialisation(Rc::new(struc), checked),
                typed: typ.clone(),
                span,
            },
            typ,
        ))
    }

    /// If `function` names an enum variant (`Enum::Variant`), return (enum, variant).
    fn as_variant(&self, function: &ExpressionNode<'a>) -> Option<(String, String)> {
        if let Expression::NamespaceAccess(ns, variant) = &function.expression {
            if let (Expression::Identifier(ns), Expression::Identifier(variant)) = (&ns.expression, &variant.expression) {
                if self.enums.get(ns).map(|variants| variants.contains(variant)).unwrap_or(false) {
                    return Some((ns.clone(), variant.clone()));
                }
            }
        }
        None
    }

    fn variant_payload(&self, enum_name: &str, variant: &str) -> Option<Vec<AzulaType<'a>>> {
        let index = self.enums.get(enum_name)?.iter().position(|v| v == variant)?;
        Some(
            self.enum_payloads
                .get(enum_name)
                .map(|p| p[index].clone())
                .unwrap_or_default(),
        )
    }

    /// Resolve type aliases and instantiate generic types used in `typ`.
    fn resolve_type(&mut self, typ: AzulaType<'a>) -> AzulaType<'a> {
        match typ {
            AzulaType::Named(ref n) => {
                if let Some(resolved) = self.type_aliases.get(n.as_str()).cloned() {
                    self.resolve_type(resolved)
                } else {
                    typ
                }
            }
            AzulaType::Pointer(inner) => AzulaType::Pointer(Rc::new(self.resolve_type(inner.as_ref().clone()))),
            AzulaType::Array(inner, size) => {
                AzulaType::Array(Rc::new(self.resolve_type(inner.as_ref().clone())), size)
            }
            AzulaType::Generic(name, args) => {
                let args = args.into_iter().map(|a| self.resolve_type(a)).collect();
                self.instantiate_type(&name, args)
            }
            AzulaType::Tuple(items) => {
                let items = items.into_iter().map(|a| self.resolve_type(a)).collect();
                self.instantiate_tuple(items)
            }
            AzulaType::Function(params, returns) => AzulaType::Function(
                params.into_iter().map(|a| self.resolve_type(a)).collect(),
                Rc::new(self.resolve_type(returns.as_ref().clone())),
            ),
            _ => typ,
        }
    }

    fn typecheck_cast_expression(
        &mut self,
        expr: ExpressionNode<'a>,
        env: &Environment<'a>,
    ) -> Result<(ExpressionNode<'a>, AzulaType<'a>), String> {
        if let Expression::Cast(ref inner, ref target_type) = expr.expression {
            let (inner_node, _) = self.typecheck_expression(inner.deref().clone(), env)?;
            let typ = self.resolve_type(target_type.clone());
            return Ok((
                ExpressionNode {
                    expression: Expression::Cast(Rc::new(inner_node), typ.clone()),
                    typed: typ.clone(),
                    span: expr.span,
                },
                typ,
            ));
        }
        unreachable!()
    }

    /// Typecheck a call to a stdlib helper on unchecked arguments
    fn typecheck_helper_call(
        &mut self,
        name: &str,
        args: Vec<ExpressionNode<'a>>,
        span: &Span,
        env: &Environment<'a>,
    ) -> Result<(ExpressionNode<'a>, AzulaType<'a>), String> {
        let call = ExpressionNode {
            expression: Expression::FunctionCall {
                function: Rc::new(ExpressionNode {
                    expression: Expression::Identifier(name.to_string()),
                    typed: AzulaType::Infer,
                    span: span.clone(),
                }),
                args,
            },
            typed: AzulaType::Infer,
            span: span.clone(),
        };
        self.typecheck_expression(call, env)
    }

    /// `"a ${x} b"` joins its parts with str_concat, converting each
    /// interpolated value to a string first
    fn typecheck_interpolation(
        &mut self,
        parts: Vec<ExpressionNode<'a>>,
        span: Span,
        env: &Environment<'a>,
    ) -> Result<(ExpressionNode<'a>, AzulaType<'a>), String> {
        let mut result: Option<ExpressionNode<'a>> = None;
        for part in parts {
            let part_span = part.span.clone();
            let (_, typ) = self.typecheck_expression(part.clone(), env)?;
            let converted = match &typ {
                AzulaType::Str => part,
                AzulaType::Bool => self.helper_call_node("str_from_bool", part),
                t if is_float_type(t) => self.helper_call_node(
                    "str_from_float",
                    ExpressionNode { expression: Expression::Cast(Rc::new(part), AzulaType::Float), typed: AzulaType::Infer, span: part_span.clone() },
                ),
                AzulaType::Char => self.helper_call_node("str_from_char", part),
                t if is_integer_type(t) => self.helper_call_node(
                    "str_from_int",
                    ExpressionNode { expression: Expression::Cast(Rc::new(part), AzulaType::Int), typed: AzulaType::Infer, span: part_span.clone() },
                ),
                _ => {
                    let has_to_str = self.type_has_method(&typ, "to_str");
                    if !has_to_str {
                        self.error(
                            format!("Can't interpolate a value of type {}; it needs a `to_str()` method", typ.mangle()),
                            &part_span,
                        );
                        return Err("can't interpolate".to_string());
                    }
                    ExpressionNode {
                        expression: Expression::FunctionCall {
                            function: Rc::new(ExpressionNode {
                                expression: Expression::StructAccess(
                                    Rc::new(part),
                                    Rc::new(ExpressionNode {
                                        expression: Expression::Identifier("to_str".to_string()),
                                        typed: AzulaType::Infer,
                                        span: part_span.clone(),
                                    }),
                                ),
                                typed: AzulaType::Infer,
                                span: part_span.clone(),
                            }),
                            args: vec![],
                        },
                        typed: AzulaType::Infer,
                        span: part_span.clone(),
                    }
                }
            };
            result = Some(match result {
                None => converted,
                Some(acc) => self.helper_call_node_2("str_concat", acc, converted, &span),
            });
        }
        let node = result.unwrap_or(ExpressionNode { expression: Expression::String(String::new()), typed: AzulaType::Infer, span: span.clone() });
        let (checked, typ) = self.typecheck_expression(node, env)?;
        if typ != AzulaType::Str {
            self.error(format!("`to_str()` must return str, not {}", typ.mangle()), &span);
            return Err("bad to_str".to_string());
        }
        Ok((checked, typ))
    }

    fn type_has_method(&self, typ: &AzulaType<'a>, method: &str) -> bool {
        let typ = match typ {
            AzulaType::Pointer(inner) => inner.as_ref(),
            t => t,
        };
        self.namespaces.get(&typ.to_string()).map(|n| n.funcs.contains_key(method)).unwrap_or(false)
    }

    fn helper_call_node(&self, name: &str, arg: ExpressionNode<'a>) -> ExpressionNode<'a> {
        let span = arg.span.clone();
        ExpressionNode {
            expression: Expression::FunctionCall {
                function: Rc::new(ExpressionNode {
                    expression: Expression::Identifier(name.to_string()),
                    typed: AzulaType::Infer,
                    span: span.clone(),
                }),
                args: vec![arg],
            },
            typed: AzulaType::Infer,
            span,
        }
    }

    fn helper_call_node_2(&self, name: &str, a: ExpressionNode<'a>, b: ExpressionNode<'a>, span: &Span) -> ExpressionNode<'a> {
        ExpressionNode {
            expression: Expression::FunctionCall {
                function: Rc::new(ExpressionNode {
                    expression: Expression::Identifier(name.to_string()),
                    typed: AzulaType::Infer,
                    span: span.clone(),
                }),
                args: vec![a, b],
            },
            typed: AzulaType::Infer,
            span: span.clone(),
        }
    }

    fn typecheck_infix_expression(
        &mut self,
        expr: ExpressionNode<'a>,
        env: &Environment<'a>,
    ) -> Result<(ExpressionNode<'a>, AzulaType<'a>), String> {
        if let Expression::Infix(ref left, ref operator, ref right) = expr.expression {
            let (original_left, original_right) = (left.deref().clone(), right.deref().clone());
            let (mut left, mut left_typ) = self.typecheck_expression(left.deref().clone(), env)?;
            let (mut right, mut right_typ) = self.typecheck_expression(right.deref().clone(), env)?;

            // `==` and `<` on types implementing Eq and Ord call their methods
            let is_plain_enum = matches!(&left_typ, AzulaType::Named(n) if self.enums.contains_key(n.as_str()) && !self.enum_payloads.contains_key(n.as_str()));
            if left_typ == right_typ && matches!(left_typ, AzulaType::Named(_)) && !is_plain_enum {
                let span = expr.span.clone();
                let method_call = |method: &str| ExpressionNode {
                    expression: Expression::FunctionCall {
                        function: Rc::new(ExpressionNode {
                            expression: Expression::StructAccess(
                                Rc::new(original_left.clone()),
                                Rc::new(ExpressionNode {
                                    expression: Expression::Identifier(method.to_string()),
                                    typed: AzulaType::Infer,
                                    span: span.clone(),
                                }),
                            ),
                            typed: AzulaType::Infer,
                            span: span.clone(),
                        }),
                        args: vec![original_right.clone()],
                    },
                    typed: AzulaType::Infer,
                    span: span.clone(),
                };
                match operator {
                    Operator::Eq | Operator::Neq if self.implements(&left_typ, "Eq") => {
                        let (call, _) = self.typecheck_expression(method_call("equals"), env)?;
                        if *operator == Operator::Eq {
                            return Ok((call, AzulaType::Bool));
                        }
                        let node = ExpressionNode { expression: Expression::Not(Rc::new(call)), typed: AzulaType::Bool, span };
                        return Ok((node, AzulaType::Bool));
                    }
                    Operator::Lt | Operator::Lte | Operator::Gt | Operator::Gte if self.implements(&left_typ, "Ord") => {
                        let (call, _) = self.typecheck_expression(method_call("compare"), env)?;
                        let zero = ExpressionNode { expression: Expression::Integer(0), typed: AzulaType::Int, span: span.clone() };
                        let node = ExpressionNode {
                            expression: Expression::Infix(Rc::new(call), operator.clone(), Rc::new(zero)),
                            typed: AzulaType::Bool,
                            span,
                        };
                        return Ok((node, AzulaType::Bool));
                    }
                    _ => {}
                }
            }

            // Operators on strings compare and join contents, via stdlib helpers
            let is_null = |e: &ExpressionNode<'a>| matches!(e.expression, Expression::Null);
            if left_typ == AzulaType::Str && right_typ == AzulaType::Str && !is_null(&left) && !is_null(&right) {
                let span = expr.span.clone();
                let args = vec![original_left, original_right];
                match operator {
                    Operator::Add => return self.typecheck_helper_call("str_concat", args, &span, env),
                    Operator::Eq => return self.typecheck_helper_call("str_equals", args, &span, env),
                    Operator::Neq => {
                        let (call, _) = self.typecheck_helper_call("str_equals", args, &span, env)?;
                        let node = ExpressionNode { expression: Expression::Not(Rc::new(call)), typed: AzulaType::Bool, span };
                        return Ok((node, AzulaType::Bool));
                    }
                    Operator::Lt | Operator::Lte | Operator::Gt | Operator::Gte => {
                        let (call, _) = self.typecheck_helper_call("str_compare", args, &span, env)?;
                        let zero = ExpressionNode { expression: Expression::Integer(0), typed: AzulaType::Int, span: span.clone() };
                        let node = ExpressionNode {
                            expression: Expression::Infix(Rc::new(call), operator.clone(), Rc::new(zero)),
                            typed: AzulaType::Bool,
                            span,
                        };
                        return Ok((node, AzulaType::Bool));
                    }
                    _ => {}
                }
            }

            // Integer literals take on the integer type of the other operand.
            if is_integer_type(&left_typ) && is_integer_literal(&right) {
                right.typed = left_typ.clone();
                right_typ = left_typ.clone();
            } else if is_integer_type(&right_typ) && is_integer_literal(&left) {
                left.typed = right_typ.clone();
                left_typ = right_typ.clone();
            }

            // Arithmetic between int and a narrower integer (such as a char) is done in int
            let widen = |mut node: ExpressionNode<'a>, typ: &AzulaType<'a>| {
                // The codegen zero-extends unsigned values, so it needs their type
                node.typed = typ.clone();
                let span = node.span.clone();
                ExpressionNode { expression: Expression::Cast(Rc::new(node), AzulaType::Int), typed: AzulaType::Int, span }
            };
            let arithmetic = matches!(
                operator,
                Operator::Add | Operator::Sub | Operator::Mul | Operator::Div | Operator::Mod
                    | Operator::BitAnd | Operator::BitOr | Operator::BitXor | Operator::Shl | Operator::Shr
            );
            if arithmetic && is_integer_type(&left_typ) && is_integer_type(&right_typ) && left_typ != right_typ {
                if left_typ == AzulaType::Int {
                    right = widen(right, &right_typ);
                    right_typ = AzulaType::Int;
                } else if right_typ == AzulaType::Int {
                    left = widen(left, &left_typ);
                    left_typ = AzulaType::Int;
                }
            }

            // Only plain (payload-free) enums can be compared
            let is_enum = |t: &AzulaType<'a>| {
                matches!(t, AzulaType::Named(n) if self.enums.contains_key(n.as_str()) && !self.enum_payloads.contains_key(n.as_str()))
            };
            let is_pointer_like = |t: &AzulaType<'a>| matches!(t, AzulaType::Pointer(_) | AzulaType::Str);

            let operand_ok = |t: &AzulaType<'a>| -> bool {
                match operator {
                    Operator::Add | Operator::Sub | Operator::Mul | Operator::Div | Operator::Mod | Operator::Power => {
                        is_integer_type(t) || is_float_type(t)
                    }
                    Operator::BitAnd | Operator::BitOr | Operator::BitXor | Operator::Shl | Operator::Shr => {
                        is_integer_type(t)
                    }
                    Operator::Or | Operator::And => *t == AzulaType::Bool,
                    Operator::Eq | Operator::Neq => {
                        is_integer_type(t) || is_float_type(t) || *t == AzulaType::Bool || is_enum(t) || is_pointer_like(t)
                    }
                    Operator::Lt | Operator::Lte | Operator::Gt | Operator::Gte => {
                        is_integer_type(t) || is_float_type(t) || is_pointer_like(t)
                    }
                }
            };

            for (node, typ) in [(&left, &left_typ), (&right, &right_typ)] {
                if !operand_ok(typ) {
                    self.errors.push(AzulaError::new(
                        ErrorType::NonOperatorType(format!("{:?}", typ), format!("{:?}", operator)),
                        node.span.start,
                        node.span.end,
                    ));
                    return Err("cannot use operator with type".to_string());
                }
            }

            let result_typ = match operator {
                Operator::Or
                | Operator::And
                | Operator::Eq
                | Operator::Neq
                | Operator::Lt
                | Operator::Lte
                | Operator::Gt
                | Operator::Gte => {
                    let both_pointers = is_pointer_like(&left_typ) && is_pointer_like(&right_typ);
                    // Integers of different widths can be compared (the narrower is widened)
                    let both_integers = is_integer_type(&left_typ) && is_integer_type(&right_typ);
                    if left_typ != right_typ && !both_pointers && !both_integers {
                        self.errors.push(AzulaError::new(
                            ErrorType::MismatchedTypes(format!("{:?}", left_typ), format!("{:?}", right_typ)),
                            left.span.start,
                            right.span.end,
                        ));
                        return Err("mismatched types in infix".to_string());
                    }
                    AzulaType::Bool
                }
                _ => {
                    if left_typ != right_typ {
                        self.errors.push(AzulaError::new(
                            ErrorType::MismatchedTypes(format!("{:?}", left_typ), format!("{:?}", right_typ)),
                            left.span.start,
                            right.span.end,
                        ));
                        return Err("mismatched types in infix".to_string());
                    }
                    left_typ.clone()
                }
            };

            Ok((
                ExpressionNode {
                    expression: Expression::Infix(Rc::new(left), operator.clone(), Rc::new(right)),
                    typed: result_typ.clone(),
                    span: expr.span,
                },
                result_typ,
            ))
        } else {
            unreachable!()
        }
    }

    fn typecheck_function_def(
        &mut self,
        mut expr: ExpressionNode<'a>,
        env: &Environment<'a>,
    ) -> ExpressionNode<'a> {
        if let Expression::Identifier(..) = expr.expression {
            return expr.clone();
        }

        if let Expression::NamespaceAccess(ref ns, _) = expr.expression {
            let namespace = if let Expression::Identifier(ident) = ns.deref().clone().expression {
                ident
            } else {
                unreachable!()
            };

            expr.typed = AzulaType::Named(namespace);
            return expr.clone();
        }

        if let Expression::StructAccess(ref struc, ref right) = expr.expression {
            let (typechecked_struc, resolved_type) = self
                .typecheck_expression(struc.deref().clone(), env)
                .unwrap();

            return ExpressionNode {
                expression: Expression::StructAccess(
                    Rc::new(typechecked_struc),
                    right.clone(),
                ),
                typed: resolved_type.clone(),
                span: expr.span,
            };
        }

        expr
    }

    fn resolve_function(
        &mut self,
        namespace: HashMap<&'a str, FunctionDefinition<'a>>,
        expr: ExpressionNode<'a>,
        env: &Environment<'a>,
    ) -> Result<FunctionDefinition<'a>, String> {
        if let Expression::Identifier(s) = expr.expression {
            return match namespace.get(&s.as_str()) {
                Some(f) => Ok(self.resolve_signature(f.clone())),
                None => {
                    if s == "printf" || s == "sprintf" || s == "puts" {
                        Ok(FunctionDefinition {
                            name: s,
                            args: vec![],
                            varargs: true,
                            returns: AzulaType::Void,
                        })
                    } else if s == "strlen" {
                        Ok(FunctionDefinition {
                            name: s,
                            args: vec![(AzulaType::Str, "s".to_string())],
                            varargs: false,
                            returns: AzulaType::Int,
                        })
                    } else if s == "strcmp" {
                        Ok(FunctionDefinition {
                            name: s,
                            args: vec![(AzulaType::Str, "a".to_string()), (AzulaType::Str, "b".to_string())],
                            varargs: false,
                            returns: AzulaType::from("i32"),
                        })
                    } else if s == "malloc" {
                        Ok(FunctionDefinition {
                            name: s,
                            args: vec![(AzulaType::Int, "size".to_string())],
                            varargs: false,
                            returns: AzulaType::Str,
                        })
                    } else if s == "memcpy" {
                        Ok(FunctionDefinition {
                            name: s,
                            args: vec![
                                (AzulaType::Str, "dest".to_string()),
                                (AzulaType::Str, "src".to_string()),
                                (AzulaType::Int, "n".to_string()),
                            ],
                            varargs: false,
                            returns: AzulaType::Str,
                        })
                    } else if s == "free" {
                        Ok(FunctionDefinition {
                            name: s,
                            args: vec![(AzulaType::Str, "ptr".to_string())],
                            varargs: false,
                            returns: AzulaType::Void,
                        })
                    } else if s == "realloc" {
                        Ok(FunctionDefinition {
                            name: s,
                            args: vec![(AzulaType::Str, "ptr".to_string()), (AzulaType::Int, "size".to_string())],
                            varargs: false,
                            returns: AzulaType::Str,
                        })
                    } else if s == "ptr_read_int" {
                        Ok(FunctionDefinition {
                            name: s,
                            args: vec![(AzulaType::Str, "ptr".to_string())],
                            varargs: false,
                            returns: AzulaType::Int,
                        })
                    } else if s == "ptr_write_int" {
                        Ok(FunctionDefinition {
                            name: s,
                            args: vec![(AzulaType::Str, "ptr".to_string()), (AzulaType::Int, "val".to_string())],
                            varargs: false,
                            returns: AzulaType::Void,
                        })
                    } else if s == "ptr_read_str" {
                        Ok(FunctionDefinition {
                            name: s,
                            args: vec![(AzulaType::Str, "ptr".to_string())],
                            varargs: false,
                            returns: AzulaType::Str,
                        })
                    } else if s == "ptr_write_str" {
                        Ok(FunctionDefinition {
                            name: s,
                            args: vec![(AzulaType::Str, "ptr".to_string()), (AzulaType::Str, "val".to_string())],
                            varargs: false,
                            returns: AzulaType::Void,
                        })
                    } else if s == "ptr_add" {
                        Ok(FunctionDefinition {
                            name: s,
                            args: vec![(AzulaType::Str, "ptr".to_string()), (AzulaType::Int, "offset".to_string())],
                            varargs: false,
                            returns: AzulaType::Str,
                        })
                    } else if s == "fopen" {
                        Ok(FunctionDefinition {
                            name: s,
                            args: vec![(AzulaType::Str, "path".to_string()), (AzulaType::Str, "mode".to_string())],
                            varargs: false,
                            returns: AzulaType::Str,
                        })
                    } else if s == "fclose" {
                        Ok(FunctionDefinition {
                            name: s,
                            args: vec![(AzulaType::Str, "file".to_string())],
                            varargs: false,
                            returns: AzulaType::Int,
                        })
                    } else if s == "fseek" {
                        Ok(FunctionDefinition {
                            name: s,
                            args: vec![
                                (AzulaType::Str, "file".to_string()),
                                (AzulaType::Int, "offset".to_string()),
                                (AzulaType::Int, "whence".to_string()),
                            ],
                            varargs: false,
                            returns: AzulaType::Int,
                        })
                    } else if s == "ftell" {
                        Ok(FunctionDefinition {
                            name: s,
                            args: vec![(AzulaType::Str, "file".to_string())],
                            varargs: false,
                            returns: AzulaType::Int,
                        })
                    } else if s == "fread" {
                        Ok(FunctionDefinition {
                            name: s,
                            args: vec![
                                (AzulaType::Str, "buf".to_string()),
                                (AzulaType::Int, "size".to_string()),
                                (AzulaType::Int, "count".to_string()),
                                (AzulaType::Str, "file".to_string()),
                            ],
                            varargs: false,
                            returns: AzulaType::Int,
                        })
                    } else {
                        Err(s)
                    }
                }
            };
        }

        if let Expression::NamespaceAccess(ns, identifier) = expr.expression {
            let namespace = if let Expression::Identifier(ident) = ns.deref().clone().expression {
                let namespace = self.namespaces.get(&ident);
                match namespace {
                    Some(f) => Ok(f.clone()),
                    None => Err(ident),
                }
            } else {
                unreachable!()
            };

            if namespace.is_err() {
                return Err("namespace".to_string());
            }

            let namespace = namespace.unwrap();
            if let Expression::Identifier(method) = &identifier.expression {
                self.instantiate_method(&namespace.name, method);
            }

            return self.resolve_function(namespace.funcs.clone(), identifier.deref().clone(), env);
        }

        if let Expression::StructAccess(struc, method) = expr.expression {
            let (_, resolved_type) = self
                .typecheck_expression(struc.deref().clone(), env)?;

            let namespace = match self.namespaces.get(&resolved_type.to_string()) {
                Some(namespace) => namespace.clone(),
                None => return Err(format!("no methods on {}", resolved_type.mangle())),
            };
            if let Expression::Identifier(name) = &method.expression {
                self.instantiate_method(&namespace.name, name);
            }

            return self.resolve_function(namespace.funcs.clone(), method.deref().clone(), env);
        }

        Err("none".to_string())
    }
}

/// Give methods their receiver type and resolve `Self`. In a type's methods,
/// `self` is a reference (`&T`) for structs and a value for other types, and
/// `Self` means the type itself.
fn resolve_receivers<'a>(stmts: Vec<Statement<'a>>) -> Vec<Statement<'a>> {
    let mut structs = HashSet::new();
    for stmt in &stmts {
        match stmt {
            Statement::Struct { name, .. } => {
                structs.insert(name.to_string());
            }
            Statement::Generic(_, _, inner) => {
                if let Statement::Struct { name, .. } = inner.as_ref() {
                    structs.insert(name.to_string());
                }
            }
            _ => {}
        }
    }
    let resolve_impl = |imp: &Statement<'a>| -> Statement<'a> {
        if let Statement::Impl { struct_impl, trait_impl, funcs, span } = imp {
            let base = match struct_impl {
                AzulaType::Named(n) | AzulaType::Generic(n, _) => n.clone(),
                _ => String::new(),
            };
            let receiver = if structs.contains(&base) {
                AzulaType::Pointer(Rc::new(struct_impl.clone()))
            } else {
                struct_impl.clone()
            };
            let mut map = Substitution::new();
            map.insert("Self".to_string(), struct_impl.clone());
            map.insert("__self".to_string(), receiver);
            Statement::Impl {
                struct_impl: struct_impl.clone(),
                trait_impl: trait_impl.clone(),
                funcs: funcs.iter().map(|f| subst_stmt(f, &map)).collect(),
                span: span.clone(),
            }
        } else {
            imp.clone()
        }
    };
    stmts
        .into_iter()
        .map(|stmt| match &stmt {
            Statement::Impl { .. } => resolve_impl(&stmt),
            Statement::Generic(params, bounds, inner) if matches!(inner.as_ref(), Statement::Impl { .. }) => {
                Statement::Generic(params.clone(), bounds.clone(), Rc::new(resolve_impl(inner)))
            }
            _ => stmt,
        })
        .collect()
}

/// For printf-like C functions, the index of the format string argument
fn format_argument(name: &str) -> Option<usize> {
    match name {
        "printf" => Some(0),
        "sprintf" | "fprintf" | "dprintf" => Some(1),
        "snprintf" => Some(2),
        _ => None,
    }
}

/// Check the conversions in a printf format string against the types of the
/// arguments that follow it; an error message if they don't fit
fn check_format(function: &str, format: &str, args: &[AzulaType], first: usize) -> Option<String> {
    let bytes = format.as_bytes();
    let mut next = 0;
    let mut i = 0;
    let mut take = |spec: &str, wanted: &str, ok: &dyn Fn(&AzulaType) -> bool| -> Option<String> {
        let result = match args.get(next) {
            None => Some(format!("`{}` format `{}` needs more arguments than were given", function, spec)),
            Some(t) if !ok(t) => Some(format!(
                "`{}` format `{}` expects {}, but argument {} is {}",
                function,
                spec,
                wanted,
                first + next + 1,
                t.mangle()
            )),
            _ => None,
        };
        next += 1;
        result
    };
    let integer = |t: &AzulaType| is_integer_type(t) || *t == AzulaType::Bool;
    let float = |t: &AzulaType| is_float_type(t);
    let string = |t: &AzulaType| *t == AzulaType::Str;
    let pointer = |t: &AzulaType| matches!(t, AzulaType::Str | AzulaType::Pointer(_) | AzulaType::Array(..) | AzulaType::Function(..));
    while i < bytes.len() {
        if bytes[i] != b'%' {
            i += 1;
            continue;
        }
        let start = i;
        i += 1;
        if i < bytes.len() && bytes[i] == b'%' {
            i += 1;
            continue;
        }
        while i < bytes.len() && b"-+ #0".contains(&bytes[i]) {
            i += 1;
        }
        let mut stars = 0;
        while i < bytes.len() && (bytes[i].is_ascii_digit() || bytes[i] == b'*' || bytes[i] == b'.') {
            if bytes[i] == b'*' {
                stars += 1;
            }
            i += 1;
        }
        while i < bytes.len() && b"hlLqjzt".contains(&bytes[i]) {
            i += 1;
        }
        if i >= bytes.len() {
            return Some(format!("`{}` format ends in the middle of a conversion", function));
        }
        let spec = &format[start..=i];
        for _ in 0..stars {
            if let Some(e) = take(spec, "an integer (for `*`)", &integer) {
                return Some(e);
            }
        }
        let error = match bytes[i] {
            b'd' | b'i' | b'u' | b'x' | b'X' | b'o' | b'c' => take(spec, "an integer", &integer),
            b'f' | b'F' | b'e' | b'E' | b'g' | b'G' | b'a' | b'A' => take(spec, "a float", &float),
            b's' => take(spec, "a str", &string),
            b'p' => take(spec, "a pointer", &pointer),
            other => Some(format!("`{}` format has an unknown conversion `%{}`", function, other as char)),
        };
        if error.is_some() {
            return error;
        }
        i += 1;
    }
    if next < args.len() {
        return Some(format!(
            "`{}` format uses {} arguments, but {} were given",
            function,
            next,
            args.len()
        ));
    }
    None
}

/// The name a type's methods and interfaces are recorded under
fn type_key(typ: &AzulaType) -> String {
    match typ {
        AzulaType::Named(n) | AzulaType::Generic(n, _) => n.clone(),
        other => other.to_string(),
    }
}

/// Whether `typ` refers to any of the type parameters `params`
fn mentions_params(typ: &AzulaType, params: &[String]) -> bool {
    match typ {
        AzulaType::Named(n) => params.contains(n),
        AzulaType::Pointer(inner) | AzulaType::Array(inner, _) => mentions_params(inner, params),
        AzulaType::Generic(_, args) | AzulaType::Tuple(args) => args.iter().any(|a| mentions_params(a, params)),
        AzulaType::Function(args, returns) => {
            args.iter().any(|a| mentions_params(a, params)) || mentions_params(returns, params)
        }
        _ => false,
    }
}

/// Whether executing `body` always ends in a `return` (or never finishes).
fn always_returns(body: &[Statement]) -> bool {
    match body.last() {
        Some(stmt) => statement_always_returns(stmt),
        None => false,
    }
}

fn block_diverges(body: &[Statement]) -> bool {
    matches!(body.last(), Some(Statement::Break(_)) | Some(Statement::Continue(_))) || always_returns(body)
}

fn statement_always_returns(stmt: &Statement) -> bool {
    match stmt {
        Statement::Return(..) => true,
        Statement::Block(body) => always_returns(body),
        Statement::If(_, body, Some(else_branch), _) => {
            always_returns(body) && statement_always_returns(else_branch)
        }
        // Infinite loops only finish through `break`
        Statement::For(None, body, _) => !contains_break(body),
        Statement::While(cond, body, _) if cond.expression == Expression::Boolean(true) => !contains_break(body),
        // Calls of functions returning `!`
        Statement::ExpressionStatement(expr, _) if expr.typed == AzulaType::Never => true,
        Statement::ExpressionStatement(expr, _) => match &expr.expression {
            Expression::Match(_, arms) => arms.iter().all(|(_, arm)| {
                arm.typed == AzulaType::Never
                    || match &arm.expression {
                        Expression::Block(stmts, None) => always_returns(stmts),
                        _ => false,
                    }
            }),
            _ => false,
        },
        Statement::Group(stmts) => always_returns(stmts),
        _ => false,
    }
}

/// Whether `body` contains a `break` that exits this loop (not a nested one).
fn contains_break(body: &[Statement]) -> bool {
    body.iter().any(|stmt| match stmt {
        Statement::Break(_) => true,
        Statement::If(_, body, else_branch, _) => {
            contains_break(body) || else_branch.as_ref().map(|e| contains_break(std::slice::from_ref(e.as_ref()))).unwrap_or(false)
        }
        Statement::Block(body) => contains_break(body),
        Statement::ExpressionStatement(expr, _) => match &expr.expression {
            Expression::Match(_, arms) => arms.iter().any(|(_, arm)| match &arm.expression {
                Expression::Block(stmts, _) => contains_break(stmts),
                _ => false,
            }),
            _ => false,
        },
        _ => false,
    })
}

fn is_integer_type(t: &AzulaType) -> bool {
    matches!(t, AzulaType::Int | AzulaType::SizedSignedInt(_) | AzulaType::SizedUnsignedInt(_) | AzulaType::Char)
}

fn is_unsigned_type(t: &AzulaType) -> bool {
    matches!(t, AzulaType::SizedUnsignedInt(_) | AzulaType::Char)
}

/// The width of an integer type, or 0 for other types
fn int_bits(t: &AzulaType) -> u32 {
    match t {
        AzulaType::Int => 64,
        AzulaType::SizedSignedInt(bits) | AzulaType::SizedUnsignedInt(bits) => *bits as u32,
        AzulaType::Char => 8,
        _ => 0,
    }
}

fn is_float_type(t: &AzulaType) -> bool {
    matches!(t, AzulaType::Float | AzulaType::SizedFloat(_))
}

fn is_integer_literal(expr: &ExpressionNode) -> bool {
    match &expr.expression {
        Expression::Integer(_) => true,
        Expression::Negate(inner) => is_integer_literal(inner),
        _ => false,
    }
}

/// Whether a value of type `got` (produced by `expr`) can be stored in a slot of type `expected`.
fn assignable(expected: &AzulaType, got: &AzulaType, expr: &ExpressionNode) -> bool {
    // `!` never produces a value, so it fits anywhere
    if expected == got || *got == AzulaType::Never {
        return true;
    }
    if is_integer_type(expected) && is_integer_type(got) {
        // Literals fit any integer type; otherwise only int <-> sized conversions
        // that the old compiler allowed.
        // chars and other 8-bit integers convert freely
        let byte = |t: &AzulaType| matches!(t, AzulaType::Char | AzulaType::SizedSignedInt(8) | AzulaType::SizedUnsignedInt(8));
        return is_integer_literal(expr)
            || matches!(got, AzulaType::Int)
            || matches!(expected, AzulaType::Int)
            || (byte(expected) && byte(got));
    }
    let pointer_like = |t: &AzulaType| matches!(t, AzulaType::Pointer(_) | AzulaType::Str);
    pointer_like(expected) && pointer_like(got) && (matches!(got, AzulaType::Str) || matches!(expected, AzulaType::Str))
}

